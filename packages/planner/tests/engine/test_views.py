class GoldenTests(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.plans = Path(tmp.name) / "plans"
        self.root = self.plans / GOLD_ID
        shutil.copytree(FIXTURES / "demo-plan", self.root)
        self.plan = store.load_plan(self.root)

    def test_demo_plan_is_structurally_valid(self):
        errors = [i for i in check.check(self.plan) if i.level == "error" and i.code != "stale_view"]
        self.assertEqual(errors, [])

    def test_views_match_the_golden_files(self):
        views.render_all(self.plan)
        golden = FIXTURES / "demo-views"
        if os.environ.get("UPDATE_GOLDEN") == "1":  # deliberate regeneration only
            for name in views.GENERATED:
                (golden / name).parent.mkdir(parents=True, exist_ok=True)
                shutil.copy(self.root / name, golden / name)
        self.assertEqual(sorted(p.relative_to(golden).as_posix() for p in golden.rglob("*.md")), sorted(views.GENERATED))
        for name in views.GENERATED:
            with self.subTest(name):
                actual = (self.root / name).read_text(encoding="utf-8")
                expected = (golden / name).read_text(encoding="utf-8")
                if actual != expected:
                    diff = "".join(difflib.unified_diff(expected.splitlines(True), actual.splitlines(True),
                                                        f"golden/{name}", f"rendered/{name}"))
                    self.fail(f"{name} differs from its golden file (UPDATE_GOLDEN=1 regenerates):\n{diff}")

    def test_every_view_starts_with_the_banner_and_ends_with_one_newline(self):
        views.render_all(self.plan)
        for name in views.GENERATED:
            text = (self.root / name).read_text(encoding="utf-8")
            self.assertTrue(text.startswith("<!-- generated by planner plan.py render — edit JSON through plan.py -->\n"), name)
            self.assertTrue(text.endswith("\n") and not text.endswith("\n\n"), name)

    def test_no_agent_instruction_files_are_generated(self):
        views.render_all(self.plan)
        self.assertFalse((self.root / "AGENTS.md").exists())
        self.assertFalse((self.root / "CLAUDE.md").exists())

    def test_pipes_and_newlines_are_escaped_only_inside_table_cells(self):
        views.render_all(self.plan)
        text = (self.root / "views/status.md").read_text(encoding="utf-8")
        self.assertIn("Validate types \\| and nesting", text)
        self.assertIn("# Status — PLAN3 Plan №1 — Gold | pipes", text)


class RenderAllTests(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.plans = Path(tmp.name) / "plans"
        self.plans.mkdir()
        self.root = demo.make_demo_plan(self.plans)  # already rendered
        self.plan = store.load_plan(self.root)

    def test_second_render_writes_nothing(self):
        stamps = {n: (self.root / n).stat().st_mtime_ns for n in views.GENERATED}
        self.assertEqual(views.render_all(self.plan), [])
        self.assertEqual({n: (self.root / n).stat().st_mtime_ns for n in views.GENERATED}, stamps)

    def test_check_mode_reports_stale_and_missing_views_without_writing(self):
        (self.root / "views/status.md").write_text("hand edit\n", encoding="utf-8")
        (self.root / "views/index.md").unlink()
        self.assertEqual(sorted(views.render_all(self.plan, check=True)), ["views/index.md", "views/status.md"])
        self.assertEqual((self.root / "views/status.md").read_text(encoding="utf-8"), "hand edit\n")
        self.assertFalse((self.root / "views/index.md").exists())

    def test_render_repairs_exactly_the_stale_files(self):
        (self.root / "views/status.md").write_text("hand edit\n", encoding="utf-8")
        self.assertEqual(views.render_all(self.plan), ["views/status.md"])
        self.assertEqual(views.render_all(self.plan, check=True), [])

    def test_a_json_change_stales_only_the_views_that_show_it(self):
        demo.rewrite(self.root, "decisions/D2.json", lambda d: d.update(title="Renamed question"))
        stale = views.render_all(store.load_plan(self.root), check=True)
        self.assertIn("views/plan.md", stale)
        self.assertIn("views/open-questions.md", stale)
        self.assertNotIn("views/roadmap.md", stale)
        self.assertNotIn("AGENTS.md", stale)

    def test_output_is_deterministic(self):
        first = {n: (self.root / n).read_bytes() for n in views.GENERATED}
        for name in views.GENERATED:
            (self.root / name).unlink()
        views.render_all(store.load_plan(self.root))
        self.assertEqual({n: (self.root / n).read_bytes() for n in views.GENERATED}, first)

    def test_check_reports_stale_views_by_file_name(self):
        (self.root / "views/status.md").write_text("hand edit\n", encoding="utf-8")
        hits = [i for i in check.check(store.load_plan(self.root)) if i.code == "stale_view"]
        self.assertEqual([(i.level, i.where) for i in hits], [])

    def test_check_skips_view_staleness_while_the_json_is_broken(self):
        (self.root / "views/status.md").write_text("hand edit\n", encoding="utf-8")
        demo.rewrite(self.root, P1 + "P1.2.json", lambda d: d.update(status="finished"))
        issues = check.check(store.load_plan(self.root))
        self.assertTrue(any(i.code == "schema" for i in issues))
        self.assertFalse(any(i.code == "stale_view" for i in issues))

    def test_mutations_keep_the_views_fresh(self):
        ops.add_item(self.plan, "P1", "New item")
        self.assertEqual(views.render_all(self.plan, check=True), [])
        self.assertIn("New item", (self.root / "views/status.md").read_text(encoding="utf-8"))


class CellTests(unittest.TestCase):
    def test_cell_escapes_pipes_and_collapses_whitespace(self):
        self.assertEqual(views.cell("a | b\n  c\t\td"), "a \\| b c d")
        self.assertEqual(views.cell(None), "")
        self.assertEqual(views.cell(5), "5")

    def test_line_collapses_whitespace_but_keeps_pipes(self):
        self.assertEqual(views.line("a | b\n c"), "a | b c")


class NextActionTests(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.plans = Path(tmp.name) / "plans"
        self.plans.mkdir()
        self.root = demo.make_demo_plan(self.plans)
        self.plan = store.load_plan(self.root)

    def next(self):
        return lifecycle.next(store.load_plan(self.root)).as_dict()

    def edit(self, rel, change):
        demo.rewrite(self.root, rel, change)

    def test_ready_item_with_launch_lines_and_route(self):
        action = self.next()
        self.assertEqual(action["kind"], "run-items")
        self.assertEqual(action["exact"], f"run-items: planner:plan-run {demo.PLAN_ID} P1.2")
        self.assertEqual(action["launch"], {"claude": f"/planner:plan-run {demo.PLAN_ID} P1.2",
                                            "codex": f"$ planner:plan-run {demo.PLAN_ID} P1.2"})
        self.assertEqual((action["phase"], action["batch"], action["items"]), ("P1", "B1", ["P1.2"]))
        self.assertEqual(action["route"], {"class": "implementation", "effort": "medium"})

    def test_batch_members_depending_on_earlier_members_run_together_with_the_max_route(self):
        self.edit(P1 + "P1.1.json", lambda d: d.update(status="todo", result=None, route={"class": "frontier", "effort": "low"}))
        action = self.next()
        self.assertEqual(action["items"], ["P1.1", "P1.2"])
        self.assertEqual(action["route"], {"class": "frontier", "effort": "medium"})

    def test_skeleton_phase_asks_for_design(self):
        self.edit(P1 + "phase.json", lambda d: d.update(design="skeleton"))
        action = self.next()
        self.assertEqual(action["exact"], f"design-phase: planner:plan-design {demo.PLAN_ID} P1")
        self.assertEqual(action["launch"]["codex"], f"$ planner:plan-design {demo.PLAN_ID} P1")

    def test_unmet_dependency_waits_on_the_first_unmet_item(self):
        ops.add_item(self.plan, "P1", "Third item")
        ops.patch(self.plan, "P1.2", {"depends_on": ["P1.3"]})
        action = self.next()
        self.assertEqual((action["kind"], action["exact"]), ("waiting", "waiting: P1.3"))

    def test_blocked_dependency_is_reported_with_its_escalation(self):
        ops.add_item(self.plan, "P1", "Third item")
        ops.patch(self.plan, "P1.2", {"depends_on": ["P1.3"]})
        self.edit(P1 + "P1.3.json", lambda d: d.update(status="blocked", result={"escalation": "owner must pick"}))
        self.assertEqual(self.next()["exact"], "waiting: blocked P1.3 — owner must pick")

    def outside_dependency_plan(self, mode):
        """P1.1 waits on P1.3 (another batch); P1.2 is independent."""
        self.edit(P1 + "P1.1.json", lambda d: d.update(status="todo", result=None))
        ops.add_item(self.plan, "P1", "Outside dependency")
        ops.patch(self.plan, "P1.1", {"depends_on": ["P1.3"]})
        ops.patch(self.plan, "P1.2", {"depends_on": []})
        ops.set_batches(self.plan, "P1", [{"id": "B1", "items": ["P1.1", "P1.2"], "mode": mode},
                                          {"id": "B2", "items": ["P1.3"], "mode": "recommended"}])

    def test_recommended_batch_runs_the_ready_subset(self):
        self.outside_dependency_plan("recommended")
        action = self.next()
        self.assertEqual((action["batch"], action["items"]), ("B1", ["P1.2"]))

    def test_required_batch_runs_only_when_every_member_is_ready(self):
        self.outside_dependency_plan("required")
        self.assertEqual(self.next()["exact"], "waiting: P1.3")
        self.edit(P1 + "P1.3.json", lambda d: d.update(status="done", result={"finished_at": "2026-10-05T12:00:00Z"}))
        self.assertEqual(self.next()["items"], ["P1.1", "P1.2"])

    def test_owner_gate_waits_until_a_gate_granted_event_exists(self):
        self.edit(P1 + "P1.2.json", lambda d: d.update(authority={"kind": "owner_gate", "gate": "RELEASE-1", "scope": "tag"}))
        self.assertEqual(self.next()["exact"], "waiting: gate RELEASE-1")
        store.append_log(self.root, store.new_event("gate_granted", "owner said go", demo.AUTHORING,
                                                    phase="P1", data={"gate": "RELEASE-1"}))
        self.assertEqual(self.next()["kind"], "run-items")

    def test_phase_dependency_waits_on_the_open_phase(self):
        ops.add_phase(self.plan, "Second")
        ops.add_phase(self.plan, "Third")
        self.edit(P1 + "phase.json", lambda d: d.update(closed={"at": "2026-10-05T12:00:00Z", "result": "done", "summary": "ok"}))
        ops.patch(self.plan, "P2", {"depends_on": ["P3"]})
        self.assertEqual(self.next()["exact"], "waiting: P3")

    def test_phase_with_finished_items_but_no_closure_waits_for_the_closure(self):
        self.edit(P1 + "P1.2.json", lambda d: d.update(status="done", result={"finished_at": "2026-10-05T12:00:00Z"}))
        self.assertEqual(self.next()["kind"], "waiting")
        self.assertIn("P1 closure", self.next()["exact"])

    def test_all_phases_closed_archives_then_terminates(self):
        self.edit(P1 + "P1.2.json", lambda d: d.update(status="done", result={"finished_at": "2026-10-05T12:00:00Z"}))
        self.edit(P1 + "phase.json", lambda d: d.update(closed={"at": "2026-10-05T12:00:00Z", "result": "done", "summary": "ok"}))
        self.assertEqual(self.next()["exact"], f"archive: planner:plan-close {demo.PLAN_ID} archive")
        self.edit("plan.json", lambda d: d.update(status="archived"))
        self.assertEqual(self.next()["exact"], "terminal: plan done")

    def test_plan_without_phases_asks_for_one(self):
        fresh = ops.new_plan("EMPTY", "Empty", plans_root=self.plans, repository="r", owner="o", authoring=demo.AUTHORING,
                             message="m", date="2026.10.07")
        self.assertEqual(lifecycle.next(fresh).exact, "waiting: no phases yet (add-phase)")

    def test_roadmap_states(self):
        text = lambda: (self.root / "views/roadmap.md").read_text(encoding="utf-8")  # noqa: E731
        self.assertIn("| ready |", text())
        self.edit(P1 + "phase.json", lambda d: d.update(design="skeleton"))
        views.render_all(store.load_plan(self.root))
        self.assertIn("| design-required |", text())
        self.edit(P1 + "phase.json", lambda d: d.update(design="detailed"))
        self.edit(P1 + "P1.2.json", lambda d: d.update(status="in_progress", result={"started_at": "2026-10-05T12:00:00Z"}))
        views.render_all(store.load_plan(self.root))
        self.assertIn("| in progress |", text())


