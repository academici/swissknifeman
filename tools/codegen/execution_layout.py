"""Keep execution outputs small while preserving their existing import facades."""

from collections import defaultdict
from pathlib import Path

from .parse import Parser
from .render_python import snake
from .scoped_settings import project

_PYTHON = {
    "skm.modules.execution.generated.documents",
    "skm.modules.integrations.generated.documents",
    "skm.modules.integrations.generated.host",
    "skm.modules.execution.generated.events",
    "skm.modules.execution.generated.views",
    "skm.modules.execution.generated.commands",
    "skm.modules.execution.generated.results",
}


def prepare(model):  # noqa: PLR0912 -- codegen layout partitions
    """Partition declarations, without changing schema wire shapes or public import paths."""
    model.python_model = Parser(model.documents, python_boundaries=True).run()
    project(model.python_model)
    facades = defaultdict(lambda: defaultdict(set))
    for current in (model, model.python_model):
        for declaration in {d.key: d for d in current.declarations.values()}.values():
            original = declaration.module
            if original not in _PYTHON:
                continue
            suffix = declaration.urn.removeprefix("urn:skm:execution:").removesuffix(":v1")
            suffix = suffix.split(":")[-1].replace("-", "_")
            prefix, kind = original.rsplit(".", 1)
            if kind in {"commands", "results", "events", "views", "documents"}:
                suffix = snake(declaration.name)
            declaration.module = f"{prefix}._{kind}_{suffix}"
            if current is model.python_model:
                exports = {declaration.name}
                if declaration.kind not in ("dataclass", "settings_view"):
                    exports.update(snake(declaration.name) + ending for ending in ("_from_json", "_to_json"))
                facades[original][declaration.module].update(exports)
    groups = defaultdict(list)
    for declaration in {d.key: d for d in model.declarations.values()}.values():
        if declaration.ts_file == "execution.ts":
            groups[(declaration.urn, declaration.name)].append(declaration)
    parts, size, number = defaultdict(set), 0, 1
    for _, declarations in sorted(groups.items()):
        weight = sum(len(d.fields) + 3 if d.type.tag == "record" else 3 for d in declarations)
        if size and size + weight > 350:
            number, size = number + 1, 0
        file = f"execution_{number:02d}.ts"
        for declaration in declarations:
            declaration.ts_file = file
            parts[file].add(declaration.ts_name)
            if declaration.kind == "enum":
                parts[file].add(declaration.ts_name + "Values")
        size += weight
    result = {}
    for original, modules in facades.items():
        owner = original.split(".")[2].capitalize()
        lines = ["# generated by tools/gen.py; do not edit", f'"""{owner} import facade."""', ""]
        exports = set()
        for module, names in sorted(modules.items()):
            bindings = ", ".join(f"{name} as {name}" for name in sorted(names))
            lines.append(f"from {module} import ({bindings})")
            exports.update(names)
        lines.extend(["", "__all__ = " + repr(sorted(exports)), ""])
        result[Path("src", *original.split(".")).with_suffix(".py")] = "\n".join(lines)
    if parts:
        result[Path("web/src/api/generated/execution.ts")] = _typescript_facade(parts)
    return result


def _typescript_facade(parts):
    lines = ["// generated execution type facade; do not edit", ""]
    exported: set[str] = set()
    for file, names in sorted(parts.items()):
        # The parser allows equivalent declarations to share a name. Sharding
        # keeps those declarations available locally, but the facade exports each name once.
        new_names = names - exported
        exported.update(new_names)
        types = sorted(name for name in new_names if not name.endswith("Values"))
        values = sorted(name for name in new_names if name.endswith("Values"))
        if types:
            lines.append(f"export type {{ {', '.join(types)} }} from './{file[:-3]}';")
        if values:
            lines.append(f"export {{ {', '.join(values)} }} from './{file[:-3]}';")
    return "\n".join(lines) + "\n"
