"""Hook modes of a project: `[harness.hooks]` in .swissknifeman/config.toml and the committed carrier.

The carrier `.swissknifeman/hooks.env` is generated from the project configuration by
`harness hooks sync`; hooks installed into projects read it with plain line parsing (they import
neither harness nor aicore). Line format: `<HOOK>_<KEY>=value`, with a provider override
`<HOOK>_<KEY>__<PROVIDER>`.
"""
from __future__ import annotations

import json
from pathlib import Path

from aicore.config import resolve

CARRIER_REL = ".swissknifeman/hooks.env"
CARRIER_HEADER = ("# Generated by harness from .swissknifeman/config.toml; do not edit. "
                  "Regenerate: harness hooks sync")
STATE_SCHEMA = "urn:swissknifeman:harness:hooks-state:v1"
SCHEMA_FILE = Path(__file__).resolve().parents[2] / "configs" / "config.schema.json"

# hook -> {key: "string" | "integer" | "boolean"}, in carrier order; enums live in the config schema.
HOOK_KEYS = {
    "auto_approve": {"mode": "string"},
    "memory": {"mode": "string", "brain": "string"},
    "agent_router": {"policy": "string"},
    "run_report": {"enabled": "string", "runs_keep": "integer"},
    "pack_guard": {"mode": "string"},
    "plan_guard": {"mode": "string"},
    "plan_regen": {"mode": "string"},
    "changelog_gate": {"mode": "string"},
    "review_gate": {"mode": "string"},
    "git_guardrails": {"mode": "string"},
    "observer": {"enabled": "boolean"},
}

# Legacy per-provider mode files `<provider-dir>/<name>.env.ini`; read, never written.
LEGACY_DIRS = {"claude-code": ".claude", "cursor": ".cursor", "codex": ".codex", "grok": ".grok"}


def hook_name(hook):
    """`agent-router` and `agent_router` both name the hook `agent_router`."""
    return hook.replace("-", "_")


def env_name(hook, key, provider=None):
    """Carrier variable of one setting, optionally for one provider."""
    name = f"{hook_name(hook)}_{key}".upper()
    if provider:
        name += "__" + provider.upper().replace("-", "_")
    return name


def _text(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def carrier_entries(settings):
    """Sorted `(variable, text)` pairs for the keys the configuration sets."""
    pairs = {}
    hooks = (settings or {}).get("hooks") or {}
    for hook, keys in HOOK_KEYS.items():
        table = hooks.get(hook)
        if not isinstance(table, dict):
            continue
        for key in keys:
            if key in table:
                pairs[env_name(hook, key)] = _text(table[key])
        for provider, overrides in sorted((table.get("providers") or {}).items()):
            for key in keys:
                if isinstance(overrides, dict) and key in overrides:
                    pairs[env_name(hook, key, provider)] = _text(overrides[key])
    return sorted(pairs.items())


def render_hooks_env(settings):
    """The carrier text for `settings` (the `settings` object of `hooks-state/v1`)."""
    lines = [CARRIER_HEADER] + [f"{name}={value}" for name, value in carrier_entries(settings)]
    return "\n".join(lines) + "\n"


def read_hooks_env(path):
    """`{variable: text}` of a carrier file; a missing or unreadable file is empty."""
    found = {}
    try:
        text = Path(path).read_text(encoding="utf-8")
    except (OSError, ValueError):
        return found
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        name, value = line.split("=", 1)
        found[name.strip()] = value.strip()
    return found


def hooks_env_value(cwd, hook, key, provider=None):
    """Provider variable, then the general one; `None` when the carrier sets neither."""
    found = read_hooks_env(Path(cwd) / CARRIER_REL)
    if provider:
        value = found.get(env_name(hook, key, provider))
        if value is not None:
            return value
    return found.get(env_name(hook, key))


def carrier_path(project):
    return Path(project) / CARRIER_REL


def legacy_env_files(project):
    """Existing legacy `<provider-dir>/*.env.ini` files of a project (read-only inheritance)."""
    found = []
    for directory in LEGACY_DIRS.values():
        base = Path(project) / directory
        if base.is_dir():
            found.extend(sorted(str(path) for path in base.glob("*.env.ini")))
    return found


def project_settings(project, *, warn=None):
    """`settings` of the project: the harness section of its project file (set keys only).

    The machine layer is left out on purpose: the carrier is committed, so a user's machine
    defaults must not be copied into it. The machine location points at a file that never exists."""
    resolved = resolve("harness", schema=SCHEMA_FILE, project=project, env={},
                       home=Path(project) / ".swissknifeman" / ".no-machine-layer",
                       warn=warn or (lambda _m: None))
    tree = resolved.as_dict()
    settings = {}
    modes = _prune(tree.get("hooks") or {})
    if modes:
        settings["hooks"] = modes
    if "policy_profile" in tree:
        settings["policy_profile"] = tree["policy_profile"]
    return settings


def _prune(value):
    if not isinstance(value, dict):
        return value
    pruned = {key: _prune(item) for key, item in value.items()}
    return {key: item for key, item in pruned.items() if item != {}}


def hooks_state(project):
    """The `hooks-state/v1` document of a project."""
    settings = project_settings(project)
    carrier = carrier_path(project)
    expected = render_hooks_env(settings)
    entries = carrier_entries(settings)
    try:
        current = carrier.read_text(encoding="utf-8")
    except (OSError, ValueError):
        current = None
    stale = current != expected if (entries or current is not None) else False
    return {
        "$schema": STATE_SCHEMA,
        "project": str(Path(project)),
        "settings": settings,
        "hooks_env": read_hooks_env(carrier),
        "legacy": legacy_env_files(project),
        "stale": stale,
    }


def dumps(document):
    return json.dumps(document, ensure_ascii=False, sort_keys=True)
