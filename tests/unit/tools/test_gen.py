    assert before == {p: ((tmp_path / p).read_bytes(), (tmp_path / p).stat().st_mtime_ns) for p in first}
    for path in first:
        if path.suffix == ".py":
            text = (tmp_path / path).read_text()
            compile(text, str(path), "exec")
            if path.name != "__init__.py":
                name = ".".join(path.with_suffix("").parts[1:])
                importlib.import_module(name)
    changed = first[0]
    target = tmp_path / changed
    target.write_text(target.read_text() + "\n# hand edit\n")
    assert generate(tmp_path, check=True, schema_root=ROOT / "src/skm/schemas") == [changed]
