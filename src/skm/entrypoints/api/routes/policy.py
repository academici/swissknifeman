"""HTTP routes for policy."""

from skm.application_bus.registry import IdempotencyMode
from skm.entrypoints.api.routing import Route
from skm.modules.policy.public import (
    ApproveIntent,
    ApproveIntentResult,
    CheckToolCall,
    DenyIntent,
    DenyIntentResult,
    EffectivePermissions,
    EffectivePermissionsView,
    ExplainPermissions,
    ExplainPermissionsResult,
    GetIntent,
    IntentApprovalView,
    IntentsView,
    ListIntents,
    ListProfiles,
    ListProfilesResult,
    ProposeIntent,
    ProposeIntentResult,
    RecordIntentOutcome,
    RecordIntentOutcomeResult,
    RecordToolDecisions,
    RecordToolDecisionsResult,
    StartIntentExecution,
    StartIntentExecutionResult,
    ToolDecisionView,
)

__all__ = ["ROUTES"]


ROUTES: tuple[Route, ...] = (
    Route(
        "GET",
        "/api/v1/policy/effective",
        EffectivePermissionsView,
        query=EffectivePermissions,
        query_params={"scope_id": "scope_id", "profile_id": "profile_id", "interactive": "interactive"},
        body="none",
        tags=("policy",),
    ),
    Route(
        "POST",
        "/api/v1/policy/check-tool-call",
        ToolDecisionView,
        query=CheckToolCall,
        tags=("policy",),
    ),
    Route(
        "GET",
        "/api/v1/policy/explain",
        ExplainPermissionsResult,
        query=ExplainPermissions,
        query_params={"scope_id": "scope_id", "profile_id": "profile_id", "interactive": "interactive"},
        body="none",
        tags=("policy",),
    ),
    Route(
        "GET",
        "/api/v1/policy/profiles",
        ListProfilesResult,
        query=ListProfiles,
        body="none",
        tags=("policy",),
    ),
    Route(
        "GET",
        "/api/v1/policy/intents",
        IntentsView,
        query=ListIntents,
        query_params={
            "workspace_id": "workspace_id",
            "scope_id": "scope_id",
            "state": "state",
            "after": "after",
            "limit": "limit",
        },
        body="none",
        tags=("policy",),
    ),
    Route(
        "GET",
        "/api/v1/policy/intents/{intent_id}",
        IntentApprovalView,
        query=GetIntent,
        path_params={"intent_id": "intent_id"},
        query_params={"include_approval_binding": "include_approval_binding"},
        etag_from="row_version",
        body="none",
        tags=("policy",),
    ),
    Route(
        "POST",
        "/api/v1/policy/intents/{intent_id}/approve",
        ApproveIntentResult,
        command=ApproveIntent,
        path_params={"intent_id": "intent_id"},
        if_match_to="expected_row_version",
        idempotency=IdempotencyMode.OPTIONAL,
        tags=("policy",),
    ),
    Route(
        "POST",
        "/api/v1/policy/intents/{intent_id}/deny",
        DenyIntentResult,
        command=DenyIntent,
        path_params={"intent_id": "intent_id"},
        if_match_to="expected_row_version",
        idempotency=IdempotencyMode.OPTIONAL,
        tags=("policy",),
    ),
    Route(
        "POST",
        "/api/v1/policy/tool-decisions",
        RecordToolDecisionsResult,
        command=RecordToolDecisions,
        idempotency=IdempotencyMode.OPTIONAL,
        tags=("policy",),
    ),
    Route(
        "POST",
        "/api/v1/worker/intents",
        ProposeIntentResult,
        command=ProposeIntent,
        success_status=201,
        idempotency=IdempotencyMode.OPTIONAL,
        tags=("worker",),
    ),
    Route(
        "POST",
        "/api/v1/worker/intents/{intent_id}/start",
        StartIntentExecutionResult,
        command=StartIntentExecution,
        path_params={"intent_id": "intent_id"},
        idempotency=IdempotencyMode.OPTIONAL,
        tags=("worker",),
    ),
    Route(
        "POST",
        "/api/v1/worker/intents/{intent_id}/outcome",
        RecordIntentOutcomeResult,
        command=RecordIntentOutcome,
        path_params={"intent_id": "intent_id"},
        idempotency=IdempotencyMode.OPTIONAL,
        tags=("worker",),
    ),
)
