class SectionTests(unittest.TestCase):
    def test_numbered_and_named_headings(self):
        self.assertEqual(context.extract_section(DOC, "§1"), "Intro.")
        self.assertEqual(context.extract_section(DOC, "§2.1"), "Nested body.")
        self.assertEqual(context.extract_section(DOC, "§2 Validation").splitlines()[0], "Body line.")  # N alone decides
        self.assertEqual(context.extract_section(DOC, "validation").splitlines()[0], "Body line.")  # case-insensitive
        self.assertEqual(context.extract_section(DOC, "Error format"), "Nested body.")  # substring tier
        self.assertEqual(context.extract_section(DOC, "out of scope"), "Last.")  # markup ignored in headings

    def test_a_section_runs_to_the_next_heading_of_the_same_or_higher_level(self):
        body = context.extract_section(DOC, "§2")
        self.assertIn("### 2.1 Error format", body)  # a deeper heading stays inside
        self.assertIn("Nested body.", body)
        self.assertNotIn("Last.", body)
        self.assertIn("## fenced, not a heading", body)  # fenced lines are never headings

    def test_missing_empty_and_last_sections(self):
        self.assertIsNone(context.extract_section(DOC, "§9"))
        self.assertIsNone(context.extract_section(DOC, "Nonexistent"))
        self.assertEqual(context.extract_section(DOC, "Empty"), "")
        self.assertEqual(context.extract_section(DOC, "Tail"), "tail text")


class PackCase(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.plans = Path(tmp.name) / "plans"
        self.plans.mkdir()
        self.root = self.plans / "2026.10.05-№1-GOLD"
        shutil.copytree(FIXTURES / "demo-plan", self.root)
        self.plan = store.load_plan(self.root)


class GoldenPackTests(PackCase):
    def test_pack_matches_the_golden_file(self):
        actual = context.render(self.plan, "P1.2")
        golden = FIXTURES / "demo-context" / "P1.2.md"
        if os.environ.get("UPDATE_GOLDEN") == "1":  # deliberate regeneration only
            golden.write_text(actual, encoding="utf-8")
        self.assertEqual(actual, golden.read_text(encoding="utf-8"))

    def test_build_writes_the_pack_under_context_and_is_deterministic(self):
        path = context.build(self.plan, "P1.2")
        self.assertEqual(path, self.root / "context" / "P1.2.md")
        first = path.read_bytes()
        context.build(self.plan, "P1.2")
        self.assertEqual(path.read_bytes(), first)
        self.assertTrue(first.decode("utf-8").startswith("<!-- generated by task plan.py context"))

    def test_sections_follow_the_dossier_order(self):
        text = context.render(self.plan, "P1.2")
        headings = [line for line in text.splitlines() if line.startswith("## ")]
        self.assertEqual(headings, ["## Goal", "## Scope", "## Context", "## Decisions", "## Upstream results", "## Reads",
                                    "## Files to change (hint)", "## Lessons", "## Rules & guidance", "## Done when"])
        self.assertIn("_Pack size: ", text.splitlines()[-1])

    def test_unknown_item_is_a_typed_refusal(self):
        with self.assertRaises(PlanError) as caught:
            context.render(self.plan, "P9.9")
        self.assertEqual(caught.exception.code, "REF_UNKNOWN")

    def test_empty_sections_are_omitted_whole(self):
        ops.add_item(self.plan, "P2", "Bare")
        text = context.render(store.load_plan(self.root), "P2.3")
        for heading in ("## Reads", "## Decisions", "## Upstream results", "## Files to change", "## Artifacts", "## Scout map"):
            self.assertNotIn(heading, text)
        self.assertIn("## Done when", text)

    def test_scout_map_is_section_13_when_the_file_exists(self):
        self.assertNotIn("## Scout map", context.render(self.plan, "P1.2"))
        (self.root / "context").mkdir()
        (self.root / "context" / "P1.2.scout.md").write_text("- lib/pkg/config.py: load_config\n", encoding="utf-8")
        text = context.render(self.plan, "P1.2")
        self.assertIn("## Scout map\n\n- lib/pkg/config.py: load_config\n", text)
        self.assertLess(text.index("## Done when"), text.index("## Scout map"))


class ReadsTests(PackCase):
    def reads(self, *reads):
        ops.patch(self.plan, "P1.2", {"reads": list(reads)})
        return context.render(self.plan, "P1.2")

    def test_only_md_sections_are_inlined_and_the_rest_is_listed(self):
        (self.root.parent.parent / "lib").mkdir()
        (self.root.parent.parent / "lib" / "a.py").write_text("x = 1\n", encoding="utf-8")
        text = self.reads({"path": "lib/a.py", "section": "§1", "why": "code", "required": True},
                          {"path": "@plan/research/00-design.md", "why": "no section", "required": False})
        self.assertIn("1. lib/a.py §1 — code (required)\n2. @plan/research/00-design.md — no section\n", text)
        self.assertNotIn("   >", text)

    def test_a_long_section_is_listed_not_inlined(self):
        text = self.reads({"path": "@plan/research/00-design.md", "section": "§2", "why": "w", "required": True})
        self.assertIn("   > Collect every problem", text)
        ops.patch(self.plan, "P1.2", {"reads": [{"path": "@plan/research/00-design.md", "section": "§2", "why": "w",
                                                 "required": True}]})
        short = context.render(self.plan, "P1.2", max_inline_lines=3)
        self.assertIn("[section has 12 lines; read it from the file]", short)
        self.assertNotIn("   >", short)

    def test_section_not_found_and_missing_files_are_marked(self):
        text = self.reads({"path": "@plan/research/00-design.md", "section": "§9", "why": "w", "required": True},
                          {"path": "docs/none.md", "section": "§1", "why": "w", "required": False},
                          {"path": "@plan/research/*.md", "why": "glob", "required": False})
        self.assertIn("§9 — w (required) [section not found]", text)
        self.assertIn("docs/none.md §1 — w [missing]", text)
        self.assertIn("@plan/research/*.md — glob\n", text)  # a glob that matches is not missing

    def test_a_read_outside_its_base_is_treated_as_missing(self):
        self.assertEqual(context.missing_reads(
            self._with_read({"path": "@plan/../escape.md", "why": "w", "required": True}), "P1.2"), ["@plan/../escape.md"])

    def _with_read(self, read):
        ops.patch(self.plan, "P1.2", {"reads": [read]})
        return self.plan

    def test_required_reads_missing_excludes_the_outputs_of_pending_dependencies(self):
        ops.patch(self.plan, "P1.1", {"artifacts": [{"path": "@plan/artifacts/out.md", "role": "output"}]})
        self._with_read({"path": "@plan/artifacts/out.md", "why": "w", "required": True})
        self.assertEqual(context.missing_reads(store.load_plan(self.root), "P1.2"), ["@plan/artifacts/out.md"])  # P1.1 is done
        path = self.root / "phases" / "P1" / "P1.1.json"
        doc = json.loads(path.read_text(encoding="utf-8"))
        doc.update(status="todo", result=None)
        path.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        self.assertEqual(context.missing_reads(store.load_plan(self.root), "P1.2"), [])  # the output is still owed


class LessonsAndDecisionsTests(test_lifecycle.LifeCase):
    def pack(self, item="P1.1"):
        return context.render(self.load(), item)

    def test_lessons_are_newest_first_and_capped_at_ten(self):
        for number in range(12):
            lifecycle.log(self.root, "P1.1", "difficulty", f"problem {number}", next=f"fix {number}")
        lifecycle.log(self.root, "P1.1", "note", "not a lesson")  # notes are not friction lessons
        lines = [l for l in self.pack().splitlines() if " difficulty: " in l]
        self.assertEqual(len(lines), 10)
        self.assertIn("problem 11 → fix 11", lines[0])
        self.assertIn("problem 2 → fix 2", lines[-1])
        self.assertNotIn("not a lesson", self.pack())

    def test_lessons_come_from_the_phase_and_related_items_only(self):
        lifecycle.log(self.root, "P1.2", "deviation", "same phase")
        lifecycle.log(self.root, "P2.1", "blocker", "related item elsewhere")
        lifecycle.log(self.root, "P2", "difficulty", "other phase, unrelated")
        ops.patch(self.root, "P1.1", {"related": [{"ref": "P2.1", "relation": "informs"}]})
        text = self.pack("P1.1")
        self.assertIn("P1.2 deviation: same phase", text)
        self.assertIn("P2.1 blocker: related item elsewhere", text)
        self.assertNotIn("other phase, unrelated", text)

    def test_decisions_open_flagged_declared_and_applicable_ones_listed(self):
        ops.add_decision(self.root, "Format", data={"question": "Which format?", "applies_to": ["P1.1"]})
        ops.add_decision(self.root, "Style", data={"status": "accepted", "decision": "snake_case", "rationale": "r",
                                                  "applies_to": ["P1"], "consequences": ["rename helpers"]})
        ops.add_decision(self.root, "Unrelated", data={"status": "accepted", "decision": "x", "rationale": "r"})
        ops.patch(self.root, "P1.1", {"decisions": ["D1", "PLAN3.D4"]})
        text = self.pack("P1.1")
        self.assertIn("- D1 (OPEN — ask/decide before relying): Which format?", text)
        self.assertIn("- D2 (accepted): snake_case\n  Consequences: rename helpers", text)
        self.assertIn("- PLAN3.D4 (other plan; not loaded):", text)
        self.assertNotIn("D3", text)
        self.assertLess(text.index("D1 (OPEN"), text.index("D2 (accepted)"))

    def test_upstream_results_carry_notes_deviations_and_outputs(self):
        ops.patch(self.root, "P1.1", {"artifacts": [{"path": "@plan/artifacts/out.md", "role": "output"}]})
        self.start("P1.1")
        self.finish("P1.1", "done_with_deviations", notes="3 tests", deviations=["slow"], pending=["docs"])
        text = self.pack("P1.2")
        self.assertIn("- P1.1 🟠 Done with deviations — 3 tests (deviations: slow) (pending: docs) Outputs: @plan/artifacts/out.md", text)
        self.assertIn("Batch B1 (P1.1 ✓, P1.2)", text)


class StartIntegrationTests(test_lifecycle.LifeCase):
    def test_start_builds_one_pack_per_item_and_prints_the_paths(self):
        result = self.start("P1.1", "P1.2")
        self.assertEqual([p.name for p in result.packs], ["P1.1.md", "P1.2.md"])
        self.assertTrue(all(p.is_file() and p.parent == self.root / "context" for p in result.packs))
        text = result.text(self.root.name)
        self.assertIn("context packs: ", text)
        self.assertIn("P1.1.md first.", text)
        self.assertIn("Batch B1 (P1.1, P1.2)", result.packs[0].read_text(encoding="utf-8"))

    def test_resume_rebuilds_the_pack(self):
        self.start("P1.1")
        pack = self.root / "context" / "P1.1.md"
        pack.write_text("stale", encoding="utf-8")
        self.start("P1.1", actor=test_lifecycle.SONNET)
        self.assertTrue(pack.read_text(encoding="utf-8").startswith("<!-- generated"))

    def test_missing_required_read_refuses_before_any_mutation(self):
        ops.patch(self.root, "P1.1", {"reads": [{"path": "lib/gone.py", "why": "w", "required": True}]})
        error = self.refused("READ_MISSING", lambda root, *a: lifecycle.start(root, ["P1.1"], test_lifecycle.OPUS))
        self.assertIn("P1.1: lib/gone.py", error.message)
        self.assertEqual(self.load().items["P1.1"]["status"], "todo")
        self.assertFalse((self.root / "context").exists())

    def test_a_pending_dependency_output_does_not_block_start(self):
        ops.patch(self.root, "P1.1", {"artifacts": [{"path": "@plan/artifacts/out.md", "role": "output"}]})
        ops.patch(self.root, "P1.2", {"reads": [{"path": "@plan/artifacts/out.md", "why": "w", "required": True}]})
        result = self.start("P1.1", "P1.2")
        self.assertIn("[pending: produced by P1.1]", result.packs[1].read_text(encoding="utf-8"))
        self.finish("P1.1")
        # P1.1 is terminal but never wrote the file: the owed output is now a real gap
        self.refused("READ_MISSING", lambda root, *a: lifecycle.start(root, ["P1.2"], test_lifecycle.OPUS))

    def test_pack_directory_is_gitignored_by_the_plan(self):
        self.start("P1.1")
        self.assertIn("context/", (self.root / ".gitignore").read_text(encoding="utf-8").splitlines())


class ContextVerbTests(test_lifecycle.LifeCase):
    def run_verb(self, *args, expect=0):
        result = subprocess.run([sys.executable, str(SCRIPT), *args, "--plans-root", str(self.plans)],
                                capture_output=True, text=True, timeout=60, cwd=self.plans.parent)
        self.assertEqual(result.returncode, expect, f"{args}\n{result.stdout}\n{result.stderr}")
        return result

    def test_context_verb_writes_the_pack_and_prints_its_path(self):
        out = self.run_verb("context", "PLAN1", "P1.1").stdout.strip()
        self.assertEqual(out, f"plans/{self.root.name}/context/P1.1.md")
        self.assertTrue((self.root / "context" / "P1.1.md").is_file())

    def test_stdout_prints_the_pack_and_writes_nothing(self):
        out = self.run_verb("context", "PLAN1", "P1.1", "--stdout").stdout
        self.assertTrue(out.startswith("<!-- generated by task plan.py context"))
        self.assertIn("# PLAN1.P1.1 — First", out)
        self.assertFalse((self.root / "context").exists())

    def test_unknown_item_exits_1_with_a_code(self):
        self.assertTrue(self.run_verb("context", "PLAN1", "P9.9", expect=1).stderr.startswith("REF_UNKNOWN: "))

    def test_start_verb_prints_the_context_paths(self):
        out = self.run_verb("start", "PLAN1", "P1.1", "--actor", "claude-code/claude-opus-5-5/high").stdout
        self.assertIn(f"context packs: plans/{self.root.name}/context/P1.1.md", out)
        self.assertIn(f"Read plans/{self.root.name}/context/P1.1.md first.", out)

    def test_negative_control_removed_required_read_exits_1_and_item_stays_todo(self):
        ops.patch(self.root, "P1.1", {"reads": [{"path": "lib/gone.py", "why": "w", "required": True}]})
        before = (self.root / "phases" / "P1" / "P1.1.json").read_bytes()
        result = self.run_verb("start", "PLAN1", "P1.1", "--actor", "claude-code/claude-opus-5-5/high", expect=1)
        self.assertTrue(result.stderr.startswith("READ_MISSING: "), result.stderr)
        self.assertEqual((self.root / "phases" / "P1" / "P1.1.json").read_bytes(), before)
        self.assertEqual(self.load().items["P1.1"]["status"], "todo")


