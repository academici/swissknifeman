"""Generate the HTTP API reference from the OpenAPI 3.1 document."""

import json
from collections import defaultdict
from hashlib import sha256
from pathlib import Path

OUTPUT = Path("docs/reference/api.md")
_METHODS = {"get", "put", "post", "delete", "options", "head", "patch", "trace"}


def _codes(values: list[str]) -> str:
    return ", ".join(f"`{value}`" for value in sorted(values)) or "—"


def render(openapi: str) -> str:
    """List the published operations in tag, path and method order."""
    document = json.loads(openapi)
    digest = sha256(openapi.encode("utf-8")).hexdigest()
    lines = [
        f"<!-- generated by tools/gen.py from OpenAPI; sources sha256:{digest}; do not edit -->",
        "",
        "# HTTP API reference",
        "",
        "The [OpenAPI 3.1 document](../../src/skm/entrypoints/api/openapi.json) defines the full",
        "request and response schemas. Endpoints require a bearer token unless marked public.",
        "An asterisk marks a required header or request body.",
    ]
    groups: dict[str, list[str]] = defaultdict(list)
    shared_params = document["components"].get("parameters", {})
    for path, item in sorted(document["paths"].items()):
        base = item.get("servers", document["servers"])[0]["url"].rstrip("/")
        for method in sorted(_METHODS.intersection(item)):
            operation = item[method]
            primary = operation.get("x-skm-permission")
            alternatives = operation.get("x-skm-permission-alternatives", [])
            access = f"`{primary}`" if primary is not None else "—"
            if alternatives:
                access += f" (alternatives {_codes(alternatives)})"
            if not operation.get("security", document["security"]):
                access = "Public"
            headers = []
            for entry in operation.get("parameters", []):
                ref = entry.get("$ref")
                parameter = shared_params[ref.rsplit("/", 1)[-1]] if ref else entry
                if parameter["in"] == "header":
                    required = "*" if parameter.get("required") else ""
                    headers.append(f"{parameter['name']}{required}")
            body = operation.get("requestBody", {})
            body_required = "*" if body.get("required") else ""
            media = _codes([f"{content_type}{body_required}" for content_type in body.get("content", {})])
            responses = _codes([code for code in operation["responses"] if code != "default"])
            tag = operation["tags"][0]
            groups[tag].append(
                f"| `{method.upper()} {base}{path}` | `{operation['operationId']}` | {access} | "
                f"{_codes(headers)} | {media} | {responses} |"
            )

    for tag, rows in sorted(groups.items()):
        lines.extend(
            [
                "",
                f"## {tag.capitalize()}",
                "",
                "| Endpoint | Operation ID | Primary permission | "
                "Request headers | Request body | Responses |",
                "| --- | --- | --- | --- | --- | --- |",
                *rows,
            ]
        )
    return "\n".join(lines) + "\n"
