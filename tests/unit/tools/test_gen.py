# Wider than the default int-to-text limit (4300 digits): written and read as text, never through str().
WIDE_TEXT = "1" + "0" * 4998 + "7"
WIDE = 10**4999 + 7
WIDE_REFUSAL = "expected one of"


def literal_codec_diagnostic_messages(module_name):
    """Exercise the same exact comparisons and bounded diagnostics under each interpreter limit."""
    codec = importlib.import_module(module_name)

    class UnprintableInput:
        @override
        def __repr__(self):
            raise AssertionError("a rejected value must never be formatted")

    secret = "secret-value-not-for-errors"
    messages = set()
    for values in (
        (WIDE,),
        (-WIDE,),
        (0, WIDE, -WIDE, None, True, "literal"),
        (*range(30), WIDE),
        ("start" + "\x00\n'\\" * 5000 + "end", WIDE),
        (2**128 - 1, -(2**128 - 1), 2**128, -(2**128)),
    ):
        literal = ("literal", (), values, ())
        for spec, wrap in (
            (literal, lambda value: value),
            (("array", (literal,), (), ()), lambda value: [value]),
            (("tuple", (literal,), (), ()), lambda value: [value]),
            (("map", (literal,), (), ()), lambda value: {"item": value}),
            (("union", (literal, ("null", (), (), ())), (), ()), lambda value: value),
        ):
            for options in ({}, {"encode": True}, {"json_mode": True}, {"encode": True, "json_mode": True}):
                for allowed in values:
                    result = codec.convert(spec, wrap(allowed), **options)
                    assert codec.convert(spec, result, encode=True) == wrap(allowed)
                for invalid in (WIDE + 1, -WIDE - 1, False, 0.0, secret, UnprintableInput()):
                    with pytest.raises(ValueError, match=WIDE_REFUSAL) as caught:
                        codec.convert(spec, wrap(invalid), **options)
                    message = str(caught.value)
                    assert len(message) <= 350
                    assert secret not in message
                    assert "integer string conversion" not in message
                    messages.add(message)
    for values, invalid in (((1,), True), ((True,), 1), ((None,), False), (("literal",), 1)):
        with pytest.raises(ValueError, match=WIDE_REFUSAL) as caught:
            codec.convert(("literal", (), values, ()), invalid)
        assert str(caught.value) == f"expected one of {values!r}"
    return sorted(messages)


@pytest.mark.parametrize("module_name", ["tools.codegen.runtime", "skm.kernel.generated._codec"])
def test_literal_codec_diagnostics_are_bounded_and_do_not_format_inputs(module_name):
    limit = sys.get_int_max_str_digits()
    messages = literal_codec_diagnostic_messages(module_name)
    assert any("..." in message for message in messages)
    assert any("<integer" in message for message in messages)
    assert sys.get_int_max_str_digits() == limit


STRING_LITERAL_CHOICES = [
    pytest.param("\x01" * 8, id="escaped-controls"),
    pytest.param("\x00\n\t\r\b\f", id="short-controls"),
    pytest.param("\ud800" * 6, id="lone-surrogates"),
    pytest.param("\U000e0001" * 3, id="supplementary-escapes"),
    pytest.param("a" * 11 + "\U000e0001" * 3, id="prefix-before-escape"),
    pytest.param("\\" * 20, id="backslashes"),
    pytest.param("'\"\\\n" * 10, id="quotes-and-escapes"),
    pytest.param("\U0001f600" * 40, id="printable-supplementary"),
    pytest.param("abcdefghijklmnopqrstuvwxyz" * 3, id="long-ascii"),
    pytest.param("it's ASCII\\text", id="short-ascii"),
]


def assert_literal_string_diagnostic(message, allowed):
    assert message.startswith("expected one of ")
    choices = message.removeprefix("expected one of ")
    assert len(choices) <= 33  # One string of at most 30 characters, plus its tuple wrapper.
    # Parsing is an oracle for complete escapes, not a public diagnostic format contract.
    (displayed,) = ast.literal_eval(choices)
    if len(repr(allowed)) <= 30:
        assert choices == repr((allowed,))
    else:
        prefix, suffix = displayed.split("...")
        assert allowed.startswith(prefix)
        assert allowed.endswith(suffix)
        assert len(prefix) + len(suffix) < len(allowed)
    return displayed


@pytest.mark.parametrize("allowed", STRING_LITERAL_CHOICES)
@pytest.mark.parametrize("module_name", ["tools.codegen.runtime", "skm.kernel.generated._codec"])
def test_literal_string_diagnostics_preserve_characters(module_name, allowed):
    codec = importlib.import_module(module_name)
    spec = ("literal", (), (allowed,), ())

    class UnprintableInput:
        @override
        def __repr__(self):
            raise AssertionError("a rejected value must never be formatted")

    secret = "secret-value-not-for-errors"
    for options in ({}, {"encode": True}, {"json_mode": True}, {"encode": True, "json_mode": True}):
        assert codec.convert(spec, allowed, **options) is allowed
        for invalid in (False, allowed + "x", secret, UnprintableInput()):
            with pytest.raises(ValueError, match="expected one of") as caught:
                codec.convert(spec, invalid, **options)
            message = str(caught.value)
            assert secret not in message
            displayed = assert_literal_string_diagnostic(message, allowed)
            if displayed != allowed:
                with pytest.raises(ValueError, match="expected one of"):
                    codec.convert(spec, displayed, **options)


@pytest.mark.parametrize("allowed", STRING_LITERAL_CHOICES)
@pytest.mark.parametrize("kind", ["dataclass", "typeddict", "alias"])
def test_literal_string_generated_public_codecs(monkeypatch, allowed, kind):
    node = schema(kind=kind)
    literal = {"type": "string", "const": allowed}
    if kind == "alias":
        for key in ("properties", "required", "additionalProperties"):
            node.pop(key)
        node.update(literal)
    else:
        node["properties"]["value"] = literal
    model = normalize({node["$id"]: node})
    text = render_python.render(model, list(model.declarations.values()), "# fixture", "test")
    module = ModuleType(node["x-skm-codegen"]["python"]["module"])
    monkeypatch.setitem(sys.modules, module.__name__, module)
    exec(compile(text, "<string literal codec>", "exec"), module.__dict__)  # noqa: S102
    raw = kind != "dataclass"
    decode = module.example_from_json if raw else module.Example.from_json
    encode = module.example_to_json if raw else lambda value: value.to_json()

    def wire(value):
        return value if kind == "alias" else {"value": value}

    assert encode(decode(wire(allowed))) == wire(allowed)
    secret = "secret-value-not-for-errors"
    for invalid in (False, allowed + "x", secret):
        for operation, value in (
            (decode, wire(invalid)),
            (encode, wire(invalid) if raw else module.Example(value=invalid)),
        ):
            with pytest.raises(ValueError, match="expected one of") as caught:
                operation(value)
            message = str(caught.value)
            assert secret not in message
            assert_literal_string_diagnostic(message, allowed)


