def cmd_check(ctx: Context, args) -> int:
    issues: list = []
    for _name, run in CHECKS:
        issues.extend(run(ctx))
    violations, scan_issues = scan_boundaries(ctx)
    issues.extend(scan_issues)
    baseline = {} if args.strict else load_baseline(ctx.root)
    boundary_errors, improvements = compare_with_baseline(violations, baseline, args.strict)
    issues.extend(boundary_errors)
    if args.json:
        print(json.dumps({"ok": not issues, "errors": [i.as_json() for i in issues],
                          "violations": [{"key": k, "count": c, "baseline": baseline.get(k, 0)}
                                         for k, c in sorted(violations.items())],
                          "improvements": improvements}, indent=2))
    for issue in issues:
        print(issue.text(), file=sys.stderr)
    for item in improvements:
        print(f"ecosystem-units: improvement: {item['key']}: {item['baseline']} -> {item['count']}; "
              "run baseline --update", file=sys.stderr)
    return 1 if issues else 0


def baseline_text(violations: dict, standalone: dict) -> str:
    doc = {"schema_version": BASELINE_SCHEMA_VERSION, "_doc": BASELINE_DOC,
           "violations": dict(sorted(violations.items())), "standalone": dict(sorted(standalone.items()))}
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def cmd_baseline(ctx: Context, args) -> int:
    violations, issues = scan_boundaries(ctx)
    if issues:
        for issue in issues:
            print(issue.text(), file=sys.stderr)
        print("ecosystem-units: baseline not updated: fix the errors above", file=sys.stderr)
        return 1
    old = load_baseline(ctx.root)
    path = ctx.root / BASELINE_PATH
    standalone = {}
    if path.is_file():
        standalone = json.loads(path.read_text(encoding="utf-8")).get("standalone") or {}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(baseline_text(violations, standalone), encoding="utf-8")
    for key in sorted(set(old) | set(violations)):
        before, after = old.get(key, 0), violations.get(key, 0)
        if before != after:
            sign = "+" if after > before else "-"
            print(f"{sign} {key}: {before} -> {after}")
    print(f"{BASELINE_PATH}: {len(violations)} violation key(s), {sum(violations.values())} occurrence(s)")
    return 0


