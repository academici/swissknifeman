TYPESCRIPT_DIR = Path("web/src/api/generated")


def closure(documents, urns):
    found = set()

    def visit(urn):
        if urn in found:
            return
        found.add(urn)
        for _, node in nodes(documents[urn]):
            if "$ref" in node:
                visit(node["$ref"].split("#")[0] or urn)

    for urn in urns:
        visit(urn)
    return {urn: documents[urn] for urn in sorted(found)}


# Below every int-to-text limit an interpreter accepts (sys.int_info.str_digits_check_threshold, 640 digits).
_PART_DIGITS = 512


def _decimal(number):
    """The exact decimal digits of ``number``, also past the interpreter's int-to-text limit."""
    try:
        return int.__repr__(number)
    except ValueError:
        pass
    sign, number, parts = "-" if number < 0 else "", abs(number), []
    while number:
        number, part = divmod(number, 10**_PART_DIGITS)
        parts.append(part)
    return sign + str(parts[-1]) + "".join(f"{part:0{_PART_DIGITS}d}" for part in reversed(parts[:-1]))


def _exact_json(value, separators):
    item, key = separators
    if isinstance(value, dict):
        pairs = sorted(value.items())
        members = (json.dumps(k, ensure_ascii=False) + key + _exact_json(v, separators) for k, v in pairs)
        return "{" + item.join(members) + "}"
    if isinstance(value, (list, tuple)):
        return "[" + item.join(_exact_json(v, separators) for v in value) + "]"
    if isinstance(value, int) and not isinstance(value, bool):
        return _decimal(value)
    return json.dumps(value, ensure_ascii=False)


def json_text(value, separators=(", ", ": ")):
    """``json.dumps(value, ensure_ascii=False, sort_keys=True)``. A loaded schema may hold an integer past the
    interpreter's int-to-text limit, which json.dumps refuses: it is written with its exact decimal digits."""
    try:
        return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=separators)
    except ValueError:
        return _exact_json(value, separators)


def digest(documents, urns):
    payload = json_text(closure(documents, urns), separators=(",", ":"))
    return hashlib.sha256(payload.encode()).hexdigest()


def _cell(value):
    if not isinstance(value, str):
        value = json_text(value)
    return value.replace("|", "\\|").replace("\n", "<br>").replace("\r", "")


def _table(headers, rows):
    return [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
        *("| " + " | ".join(_cell(v) for v in row) + " |" for row in rows),
        "",
    ]


def _doc_header(title, sources):
    sha = hashlib.sha256(json_text(sources).encode()).hexdigest()
    return [f"<!-- generated by tools/gen.py; sources sha256:{sha}; do not edit -->", "", f"# {title}", ""]


def _settings_rows(document):
    section = document["x-skm-section"]["id"]
    rows = []

    def walk(node, prefix):
        for name, child in node.get("properties", {}).items():
            key = prefix + "." + name
            metadata = child.get("x-skm")
            if isinstance(metadata, dict) and "chain" in metadata:
                shape = child.get("type", child.get("$ref", "union"))
                if shape == "array":
                    shape = "array[" + str(child.get("items", {}).get("type", "value")) + "]"
                rows.append(
                    [
                        key,
                        shape,
                        child.get("default", "—"),
                        metadata.get("chain", "—"),
                        metadata.get("levels", []),
                        metadata.get("merge", "—"),
                        metadata.get("reload", "—"),
                        metadata.get("override", False),
                        metadata.get("sensitivity", "—"),
                        child.get("description", ""),
                    ]
                )
            else:
                walk(child, key)

    walk(document, section)
    return rows


def _event_streams(root):
    """Read event class declarations without importing unfinished application modules."""
    streams = {}
    for path in sorted((root / "src/skm/modules").glob("*/domain/events.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        owner = path.parent.parent.name
        for node in tree.body:
            if not isinstance(node, ast.ClassDef):
                continue
            values = {}
            for statement in node.body:
                if isinstance(statement, ast.AnnAssign):
                    targets, value = [statement.target], statement.value
                elif isinstance(statement, ast.Assign):
                    targets, value = statement.targets, statement.value
                else:
                    continue
                if isinstance(value, ast.Constant) and isinstance(value.value, str):
                    for target in targets:
                        if isinstance(target, ast.Name):
                            values[target.id] = value.value
            if "stream_kind" in values:
                streams[(owner, node.name)] = values["stream_kind"]
    return streams


def reference_outputs(root, model):
    result = {}
    settings = {urn: doc for urn, doc in model.documents.items() if "x-skm-section" in doc}
    lines = _doc_header(
        "Configuration reference",
        {"schemas": closure(model.documents, settings), "cli": cli_reference.CONFIG_GUIDE},
    )
    lines.extend([cli_reference.CONFIG_GUIDE, ""])
    for urn, document in sorted(settings.items()):
        lines.extend([f"## {document['x-skm-section']['id']}", "", f"Schema: `{urn}`.", ""])
        lines.extend(
            _table(
                [
                    "Key",
                    "Type",
                    "Default",
                    "Chain",
                    "Levels",
                    "Merge",
                    "Reload",
                    "Override",
                    "Sensitivity",
                    "Description",
                ],
                _settings_rows(document),
            )
        )
    result[Path("docs/reference/config.md")] = "\n".join(lines)
    catalog_path = root / error_catalog.CATALOG_RELPATH
    if catalog_path.exists():
        catalog = error_catalog.load_catalog(root)
        lines = _doc_header("Error reference", catalog)
        lines.extend(
            _table(
                ["Code", "Category", "HTTP status", "CLI exit", "Retryable", "Description"],
                [
                    [
                        row[key]
                        for key in ("code", "category", "http_status", "cli_exit", "retryable", "description")
                    ]
                    for row in catalog["codes"]
                ],
            )
        )
        result[Path("docs/reference/errors.md")] = "\n".join(lines)
    events = {urn: doc for urn, doc in model.documents.items() if urn.split(":")[3] == "event"}
    streams = _event_streams(root)
    lines = _doc_header(
        "Event reference",
        {
            "schemas": closure(model.documents, events),
            "streams": {f"{m}.{c}": s for (m, c), s in sorted(streams.items())},
        },
    )
    lines.extend(
        [
            "Stream kind is shown when declared by the domain event class. "
            "A dash denotes a payload contract whose event class is not yet declared.",
            "",
        ]
    )
    rows = []
    for urn, document in sorted(events.items()):
        owner = urn.split(":")[2]
        name = document.get("x-skm-codegen", {}).get("python", {}).get("class", document.get("title", ""))
        rows.append(
            [
                urn,
                streams.get((owner, name), "—"),
                document.get("required", []),
                ", ".join(document.get("properties", {})),
                document.get("description", ""),
            ]
        )
    lines.extend(_table(["Schema", "Stream kind", "Required fields", "Fields", "Description"], rows))
    result[Path("docs/reference/events.md")] = "\n".join(lines)
    return result


def _api_outputs(root: Path, only: str | None, schema_root: Path | None) -> dict[Path, str]:
    # Schema-only fixtures have no HTTP surface to project.
    has_api = (root / "src/skm/entrypoints/api/routing.py").is_file()
    if only != "openapi" and (not has_api or only not in (None, "docs", "typescript")):
        return {}
    from . import _openapi

    openapi = _openapi.render(schema_root or root / "src/skm/schemas")
    result = {}
    if only in (None, "openapi"):
        result[_openapi.OUTPUT] = openapi
    if only in (None, "docs"):
        result[api_reference.OUTPUT] = api_reference.render(openapi)
    if only in (None, "typescript"):
        result[TYPESCRIPT_DIR / "openapi.ts"] = render_typescript.render_routes(openapi)
    return result


def _error_outputs(root: Path, only: str | None) -> dict[Path, str]:
    if only not in (None, "python", "typescript") or not (root / error_catalog.CATALOG_RELPATH).is_file():
        return {}
    catalog = error_catalog.load_catalog(root)
    result = {}
    if only in (None, "python"):
        target = error_catalog.OUTPUT_DIR_RELPATH
        result[target / "error_codes.py"] = error_catalog.render_error_codes(catalog)
        result[target / "__init__.py"] = error_catalog.render_package_marker()
    # Schema-only scaffolds can generate DTOs without a frontend error catalog.
    if only == "typescript" or (only is None and (root / "web/package.json").is_file()):
        result[TYPESCRIPT_DIR / "errors.ts"] = error_catalog.render_typescript(catalog)
    return result


def outputs(root: Path = ROOT, *, only: str | None = None, schema_root: Path | None = None):
    result = _api_outputs(root, only, schema_root)
    if only == "openapi":
        return result

    model = load(schema_root or root / "src/skm/schemas")
    facades = execution_layout(model)
    python = defaultdict(list)
    typescript = defaultdict(list)
    for d in {d.key: d for d in model.declarations.values()}.values():
        python[d.module].append(d)
        typescript[d.ts_file].append(d)
    if model.python_model is not None:
        for declaration in model.python_model.declarations.values():
            python.setdefault(declaration.module, [declaration])
    if only in (None, "python"):
        for module, declarations in sorted(python.items()):
            urns = sorted({key.split("#")[0] for key, d in model.declarations.items() if d.module == module})
            if not urns and model.python_model is not None:
                urns = sorted({d.urn for d in model.python_model.declarations.values() if d.module == module})
            sha = digest(model.documents, urns)
            header = f"# generated by tools/gen.py from {', '.join(urns)}; schemas sha256:{sha}; do not edit"
            path = Path("src", *module.split(".")).with_suffix(".py")
            # A generated package can itself declare types (config SecretRefText).
            if any(other.startswith(module + ".") for other in python):
                path = path.with_suffix("") / "__init__.py"
            result[path] = render_python.render(model, declarations, header, sha)
            generated = list(path.parts).index("generated")
            for i in range(generated + 1, len(path.parts)):
                result.setdefault(
                    Path(*path.parts[:i]) / "__init__.py", '"""Generated contracts; do not edit."""\n'
                )
        runtime = (ROOT / "tools/codegen/runtime.py").read_text(encoding="utf-8")
        result[Path("src/skm/kernel/generated/_codec.py")] = (
            "# generated by tools/gen.py; do not edit\n" + runtime
        )
    if only in (None, "typescript"):
        typescript.setdefault("kernel.ts", [])
        for file, declarations in sorted(typescript.items()):
            urns = sorted({d.urn for d in declarations})
            sha = digest(model.documents, urns)
            header = f"// generated by tools/gen.py from {', '.join(urns)}; schemas sha256:{sha}; do not edit"
            result[TYPESCRIPT_DIR / file] = render_typescript.render(
                model, declarations, header, kernel=file == "kernel.ts"
            )
    result.update(_error_outputs(root, only))
    if only in (None, "docs"):
        result.update(reference_outputs(root, model))
        result.update(cli_reference.outputs(root))
    result.update(
        (path, text)
        for path, text in facades.items()
        if only is None
        or (only == "python" and path.suffix == ".py")
        or (only == "typescript" and path.suffix == ".ts")
    )
    return result


def generate(
    root: Path = ROOT, *, check: bool = False, only: str | None = None, schema_root: Path | None = None
):
    # Render everything before the first write, so unsupported input cannot leave partial output.
    rendered = outputs(root, only=only, schema_root=schema_root)
    changed = []
    for relative, text in sorted(rendered.items()):
        path = root / relative
        data = text.encode("utf-8")
        if path.is_file() and path.read_bytes() == data:
            continue
        changed.append(relative)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    # These private execution shards are entirely owned by execution_layout.
    # Layout changes must not leave stale declarations/imports on disk.
    if only in (None, "python"):
        execution_dir = root / "src/skm/modules/execution/generated"
        for path in execution_dir.glob("_*.py"):
            if not path.name.startswith(("_commands_", "_results_", "_events_", "_views_", "_documents_")):
                continue
            relative = path.relative_to(root)
            if relative not in rendered and path.read_text().startswith("# generated by tools/gen.py"):
                changed.append(relative)
                if not check:
                    path.unlink()
    return changed


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("surface", nargs="?", choices=("openapi",))
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--only", choices=("python", "typescript", "docs", "openapi"))
    args = parser.parse_args(argv)
    if args.surface and args.only and args.surface != args.only:
        parser.error("openapi cannot be combined with a different --only target")
    try:
        changed = generate(check=args.check, only=args.surface or args.only)
    except (CodegenError, error_catalog.CatalogError) as exc:
        print(str(exc), file=sys.stderr)
        return 1
    if args.check and changed:
        for path in changed:
            print(f"SCHEMA_CODEGEN_DRIFT: {path}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
