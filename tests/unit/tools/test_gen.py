def test_scalar_conversion_rejects_invalid_inputs():
    from skm.kernel.generated._codec import convert

    spec = lambda tag: (tag, (), (), ())  # noqa: E731
    assert convert(spec("date"), date(2026, 1, 1), encode=True) == "2026-01-01"
    for tag, value, encode in (
        ("date", "2026-01-01", True),
        ("date", datetime(2026, 1, 1, tzinfo=UTC), True),
        ("uuid", 5, False),
        ("date", 5, False),
        ("datetime", 5, False),
        ("float", 10**400, False),
    ):
        with pytest.raises(ValueError, match=r"expected|range"):
            convert(spec(tag), value, encode=encode)


