#!/usr/bin/env python3
"""Render the committed lifecycle handlers `.codex/`, `.cursor/` and `.grok/hooks/lifecycle.py`.

The handlers are generated by `harness.hooks.render_*_hook_handler`; consumers receive exactly those bytes, so the
copies this repository commits for itself must not drift from the renderer.

Needs `PYTHONPATH` to hold the aicore `lib` (the golden generator sets it), like the other harness scripts.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO_ROOT / "packages/harness/lib"))

from harness import hooks  # noqa: E402


def targets():
    """(repository-relative path, bytes) of every committed handler."""
    return (
        (".codex/hooks/lifecycle.py", hooks.render_codex_hook_handler(state_dir=".codex")),
        (".cursor/hooks/lifecycle.py", hooks.render_cursor_hook_handler()),
        (".grok/hooks/lifecycle.py", hooks.render_codex_hook_handler(state_dir=".grok")),
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check", action="store_true", help="fail when a committed handler drifted from the renderer")
    group.add_argument("--write", action="store_true", help="regenerate the committed handlers")
    parser.add_argument("--root", default=str(REPO_ROOT), help="repository root")
    args = parser.parse_args()
    root = Path(args.root).resolve()

    drift = []
    for relative, content in targets():
        path = root / relative
        current = path.read_bytes() if path.is_file() else None
        if current == content:
            continue
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
            print(f"wrote: {relative}")
        else:
            drift.append(relative)
    for relative in drift:
        print(f"drift: {relative}", file=sys.stderr)
    if drift:
        print("render-hook-handlers: run --write, the handlers are edited by the generator", file=sys.stderr)
        return 1
    print("render-hook-handlers: ok")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
