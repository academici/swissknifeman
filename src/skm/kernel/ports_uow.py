"""Unit of work, request metadata and the repository port marker (kernel-platform §2.11).

Declarations only: the memory and PostgreSQL implementations of ``UnitOfWorkFactory`` are
``adapters/{memory,postgres}/uow.py``, and the commit rules of §2.11 belong to them.
"""

from __future__ import annotations

from contextlib import AbstractContextManager
from dataclasses import dataclass
from datetime import datetime
from enum import StrEnum
from types import TracebackType
from typing import TYPE_CHECKING, Final, Literal, Protocol, Self

if TYPE_CHECKING:
    from skm.kernel.events import DomainEvent
    from skm.kernel.ids import EventId

__all__ = [
    "PORT_KIND_ATTRIBUTE",
    "Isolation",
    "OutboxEnqueuer",
    "PortKind",
    "RequestMeta",
    "Surface",
    "UnitOfWork",
    "UnitOfWorkFactory",
    "repository_port",
]

# Attribute set by the port markers; bootstrap and GatewayTable read it to tell port kinds apart.
PORT_KIND_ATTRIBUTE: Final = "__skm_port_kind__"

type PortKind = Literal["repository", "control_plane_gateway", "host_gateway", "shared_gateway"]


class Surface(StrEnum):
    CLI = "cli"
    API = "api"
    MCP = "mcp"
    WORKER = "worker"
    BACKGROUND = "background"
    HOOK = "hook"
    TEST = "test"


class Isolation(StrEnum):
    READ_COMMITTED = "read_committed"
    REPEATABLE_READ = "repeatable_read"
    SERIALIZABLE = "serializable"


@dataclass(frozen=True, slots=True)
class RequestMeta:
    request_id: str  # "req_" + 26 base32 chars of a uuid7; generated by the surface
    surface: Surface
    idempotency_key: str | None  # <= 200 chars of [A-Za-z0-9._:-]
    received_at: datetime
    client: str | None = None  # "skm-cli/2.0.0", "web/2.0.0", "worker/2.0.0"
    correlation_id: str | None = None  # root of the causal chain; None -> request_id (filled by the bus)
    causation_id: str | None = None  # verified event id or request id of the parent command
    idempotency_deadline: datetime | None = None  # latest safe execution of a persisted retry


class OutboxEnqueuer(Protocol):
    def enqueue(self, event_id: EventId, destination: str, *, available_at: datetime | None = None) -> None:
        """Explicit outbox row for an external consumer, e.g. ``"hook:<subscription_id>"``.

        Buffered until commit; a duplicate ``(event_id, destination)`` is a no-op;
        ``available_at=None`` means now.
        """
        ...


class UnitOfWork(Protocol):
    def repo[R](self, port: type[R]) -> R:
        """One instance per port per UoW; an unknown port is ``InternalError``."""
        ...

    def record(self, event: DomainEvent) -> None:
        """Buffer an event; written on commit. ``RuntimeError`` in a readonly UoW."""
        ...

    @property
    def outbox(self) -> OutboxEnqueuer:
        """Explicit outbox rows; ``enqueue`` raises ``RuntimeError`` in a readonly UoW."""
        ...

    def savepoint(self) -> AbstractContextManager[None]:
        """Roll back this block on error, including buffered events/outbox; never commit the UoW."""
        ...

    def commit(self) -> None:
        """A second commit is ``RuntimeError``."""
        ...

    def rollback(self) -> None:
        """Idempotent."""
        ...

    @property
    def readonly(self) -> bool: ...

    def __enter__(self) -> Self: ...

    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> None:
        """Exception or no commit means rollback; the exception is not swallowed."""
        ...


class UnitOfWorkFactory(Protocol):
    def __call__(
        self,
        meta: RequestMeta,
        *,
        readonly: bool = False,
        isolation: Isolation = Isolation.READ_COMMITTED,
    ) -> UnitOfWork: ...


def repository_port[T: type[object]](cls: T) -> T:
    """Mark a Protocol as a repository port: reached only through ``uow.repo(port)``."""
    setattr(cls, PORT_KIND_ATTRIBUTE, "repository")
    return cls
