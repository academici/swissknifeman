def test_nested_value_objects_and_documents_round_trip(generated_fixture):
    m = generated_fixture
    data = payload()
    value = m.Envelope.from_json(data)
    assert value.id == UUID(data["id"])
    assert value.at == datetime(2026, 10, 25, 14, 3, 11, 1, tzinfo=UTC)
    assert value.day == date(2026, 10, 25)
    assert value.priority is m.Priority.HIGH_PRIORITY
    assert value.labels == {"a": (1, 2)}
    assert isinstance(value.labels, MappingProxyType)
    assert value.document == data["document"]
    assert value.document is not data["document"]
    assert isinstance(value.document["data"], list)
    assert isinstance(value.document["id"], str)
    assert value.scope.include == ()
    assert value.node.children[0].value == 2
    assert value.tuple == ("a", 3)
    wire = value.to_json()
    assert wire["at"] == "2026-10-25T14:03:11.000001Z"
    assert wire["nullable"] is None
    assert "optional_first" not in wire
    assert wire["from"] == "owner"
    assert value.from_ == "owner"
    assert wire["SKM_TOKEN"] == ""
    assert value.skm_token == ""
    assert m.Envelope.from_json(wire) == value
    with pytest.raises(FrozenInstanceError):
        value.id = UUID(int=1)
    with pytest.raises(TypeError):
        cast(Any, value.labels)["bad"] = ()
    assert list(wire)[:3] == ["id", "at", "day"]


