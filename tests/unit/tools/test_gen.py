def test_python_foreign_json_shapes_are_local_and_preserve_round_trip(monkeypatch):
    parent = schema("Consumer")
    foreign = schema("Wire", kind="typeddict")
    foreign["$id"] = "urn:skm:other:wire:v1"
    foreign["x-skm-codegen"]["python"]["module"] = "skm.modules.other.generated.documents"
    foreign["x-skm-codegen"]["typescript"]["file"] = "other.ts"
    parent["properties"]["value"] = {"$ref": foreign["$id"]}
    model = normalize({parent["$id"]: parent, foreign["$id"]: foreign})
    before = list(model.declarations)
    root = model.declarations[parent["$id"] + "#"]
    ts = render_typescript.render(model, [root], "// fixture")
    text = render_python.render(model, [root], "# fixture", "test")
    assert "import skm.modules.other" not in text
    assert list(model.declarations) == before
    assert render_typescript.render(model, [root], "// fixture") == ts
    module = ModuleType(root.module)
    monkeypatch.setitem(sys.modules, root.module, module)
    exec(compile(text, "<foreign JSON shape>", "exec"), module.__dict__)  # noqa: S102
    wire = {"value": {"value": 7}}
    value = module.Consumer.from_json(wire)
    assert value.to_json() == wire
    assert module.Consumer.from_json(value.to_json()) == value
    wire["value"]["value"] = 9
    assert value.value == {"value": 7}
    with pytest.raises(ValueError, match="expected int"):
        module.Consumer.from_json({"value": {"value": "invalid"}})


