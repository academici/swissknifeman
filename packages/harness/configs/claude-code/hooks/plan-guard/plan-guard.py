#!/usr/bin/env python3
"""PreToolUse guard: generated planner plan files are changed through plan.py, never by hand."""
import fnmatch
import json
import os
import sys
from pathlib import Path

_DEFAULT_MODE = "off"
_MODES = ("off", "warn", "strict")
_EDIT_TOOLS = ("Edit", "Write", "MultiEdit")
_UNIT_BRIEF = "phases/*/*/U*/brief.json"
_MESSAGE = "generated by plan.py — change JSON through plan.py"


def _carrier(cwd, key):
    """Value of `key` in the committed carrier .swissknifeman/hooks.env (provider key first)."""
    try:
        text = (Path(cwd) / ".swissknifeman" / "hooks.env").read_text(encoding="utf-8")
    except Exception:
        return None
    found = {}
    for line in text.splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            found[k.strip()] = v.strip()
    return found.get(key + "__CLAUDE_CODE", found.get(key))


def _read_mode(cwd):
    if not cwd:
        return _DEFAULT_MODE
    carried = _carrier(cwd, "PLAN_GUARD_MODE")
    if carried is not None:
        carried = carried.lower()
        return carried if carried in _MODES else _DEFAULT_MODE
    try:
        text = (Path(cwd) / ".claude" / "plan-guard.env.ini").read_text(encoding="utf-8")
    except Exception:
        return _DEFAULT_MODE
    mode = _DEFAULT_MODE
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = (x.strip() for x in line.split("=", 1))
        if k == "MODE":
            v = v.lower()
            mode = v if v in _MODES else _DEFAULT_MODE
    return mode


def _generated(path, cwd):
    absolute = Path(path) if os.path.isabs(path) else Path(cwd) / path
    absolute = Path(os.path.normpath(absolute))
    for directory in absolute.parents:
        if not (directory / "plan.json").is_file():
            continue
        parts = absolute.relative_to(directory).parts
        if (parts[0] == "views" and len(parts) > 1
                or parts[0] == "context" and len(parts) > 1
                or len(parts) == 5 and fnmatch.fnmatchcase("/".join(parts), _UNIT_BRIEF)):
            return True
    return False


def main():
    try:
        raw = sys.stdin.read()
        payload = json.loads(raw) if raw.strip() else {}
    except Exception:
        sys.exit(0)
    if not isinstance(payload, dict):
        sys.exit(0)
    cwd = payload.get("cwd") or os.getcwd()
    mode = _read_mode(cwd)
    if mode == "off" or payload.get("tool_name") not in _EDIT_TOOLS:
        sys.exit(0)
    tool_input = payload.get("tool_input")
    path = tool_input.get("file_path") if isinstance(tool_input, dict) else None
    if not isinstance(path, str) or not path or not _generated(path, cwd):
        sys.exit(0)
    msg = f"plan-guard: {_MESSAGE}: {path}"
    if mode == "strict":
        sys.stderr.write(msg + "\n")
        sys.exit(2)
    sys.stderr.write("[warn] " + msg + "\n")
    sys.exit(0)


if __name__ == "__main__":
    try:
        main()
    except SystemExit:
        raise
    except Exception:
        sys.exit(0)
