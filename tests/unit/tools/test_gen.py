def test_typescript_integer_policy_matches_node_oracle():
    node = shutil.which("node")
    if node is None:
        pytest.skip("optional Node oracle is unavailable; the generator itself needs no Node")
    values = {0, *EXACT_INTEGERS, *LOSSY_INTEGERS, WIDE}
    # Exercise both binary spacing transitions and decimal notation/significance transitions.
    for exponent in range(1024):
        base, step = 2**exponent, 2 ** max(0, exponent - 52)
        values.update(base + offset * step for offset in (-2, -1, 0, 1, 2, 17))
    for exponent in range(309):
        base = 10**exponent
        rounded = int(float(base))
        step = 2 ** max(0, rounded.bit_length() - 53)
        values.update((base - 1, base, base + 1, rounded - step, rounded, rounded + step))
    values |= {-value for value in values}
    values = sorted(values)
    sources = [generator._decimal(value) for value in values]
    # Static JavaScript reads decimal strings as data. Never eval schema-controlled text.
    oracle = """
        const fs = require('node:fs');
        const sources = JSON.parse(fs.readFileSync(0, 'utf8'));
        const results = sources.map(source => {
            const number = JSON.parse(source);
            return [Number.isFinite(number) ? BigInt(number).toString() : null, JSON.stringify(number)];
        });
        process.stdout.write(JSON.stringify(results));
    """
    result = subprocess.run(
        [node, "-e", oracle],
        input=json.dumps(sources),
        text=True,
        capture_output=True,
        check=True,
        timeout=30,
    )
    results = json.loads(result.stdout)
    assert len(results) == len(values)
    for value, source, (parsed, written) in zip(values, sources, results, strict=True):
        # Decimal interprets scientific notation exactly; parsing the wire back as a double would hide loss.
        exact = parsed == source and json.loads(written, parse_float=Decimal) == value
        assert (render_typescript._javascript_loss(value) == "") == exact, source


