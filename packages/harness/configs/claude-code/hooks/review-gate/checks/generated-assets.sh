#!/usr/bin/env bash
set -uo pipefail

changed="$( { git diff --name-only 2>/dev/null; git diff --cached --name-only 2>/dev/null; git ls-files --others --exclude-standard 2>/dev/null; } | sort -u | grep -v '^$')"
[ -n "$changed" ] || exit 0

violations=0
while IFS= read -r f; do
  [ -f "$f" ] || continue
  line="$(grep -nE '^(<!-- |# |// )swissknifeman:generated[[:space:]]*$' "$f" 2>/dev/null | head -1 | cut -d: -f1)"
  if [ -n "$line" ]; then
    echo "$f:$line: file generated by the pack (swissknifeman:generated) — move edit to override-file (see Extension-points in the title), do not edit directly"
    violations=1
  fi
done <<< "$changed"

exit "$violations"
