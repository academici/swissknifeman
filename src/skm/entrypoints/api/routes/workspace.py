def _checkout_payload(payload: Mapping[str, Any]) -> None:
    for field in ("local_locator", "observed_toplevel"):
        locator = payload.get(field)
        if locator is not None and workspace.checkout_id_from_locator(locator) is None:
            raise error_for(
                ErrorCode.SCHEMA_INVALID, "Project checkout references require a machine checkout ID"
            )


