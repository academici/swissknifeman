@functools.lru_cache(maxsize=128)
def _tool_digest(path: Path, signature: tuple) -> bytes:
    """Hash each installed tool once per stat identity; replacements and in-place writes change the identity."""
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.digest()


def content_key(folders: list, command: list, context=None) -> str:
    """The working-tree bytes and executable modes a command reads, independent of staging and commits."""
    digest = hashlib.sha256(json.dumps([command, sys.version.split()[0], folders]).encode("utf-8"))
    env = bridge_env()
    context_env = {k: env.get(k) for k in CONTEXT_ENV}
    for name in env:
        if (name.startswith(("SKM_", "PLANNER_", "AICORE_"))
                and name not in ("SKM_CHECK_RUN", "SKM_CHECK_ROUND", "SKM_VALIDATE_SKIP_TESTS")
                and not any(word in name for word in ("TOKEN", "SECRET", "PASSWORD", "CREDENTIAL", "API_KEY"))):
            context_env[name] = env[name]
    digest.update(json.dumps([str(ROOT), context_env, context], sort_keys=True).encode("utf-8"))
    # Hub runners/configs can change execution without changing a unit. Keep index/commit representation irrelevant.
    reads = list(dict.fromkeys([*folders, "scripts", "configs", ".swissknifeman/config.toml"]))
    names = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z", "--", *reads], cwd=ROOT,
                           capture_output=True, check=True).stdout.split(b"\0")
    digest.update(Path(__file__).read_bytes())
    # Resolve and fingerprint actual runner executables; PATH or an in-place tool replacement invalidates reuse.
    for tool in dict.fromkeys([command[0], "python3", "bash", "git", "node", "npm"]):
        resolved = shutil.which(tool, path=env.get("PATH"))
        if resolved is None:
            digest.update(f"missing:{tool}".encode("utf-8"))
        else:
            path = Path(resolved).resolve()
            digest.update(os.fsencode(path))
            try:
                stat = path.stat()
                signature = (stat.st_dev, stat.st_ino, stat.st_size, stat.st_mtime_ns, stat.st_ctime_ns, stat.st_mode)
                digest.update(_tool_digest(path, signature))
                digest.update(str(stat.st_mode & 0o111).encode("ascii"))
            except OSError:
                digest.update(b"unreadable")
    for name in sorted(set(item for item in names if item)):
        path = ROOT / os.fsdecode(name)
        if not path.exists() and not path.is_symlink():
            continue  # an unstaged deletion and its committed state are the same candidate
        digest.update(b"\0" + name)
        try:
            digest.update(str(path.lstat().st_mode & 0o170111).encode("ascii"))
            digest.update(os.fsencode(os.readlink(path)) if path.is_symlink() else path.read_bytes())
        except OSError:
            digest.update(b"?")
    return digest.hexdigest()


def cache_file() -> Path:
    common = subprocess.run(["git", "rev-parse", "--path-format=absolute", "--git-common-dir"], cwd=ROOT,
                            capture_output=True, text=True, check=True).stdout.strip()
    primary = Path(common) / "affected-tests" / "green.json"
    try:
        primary.parent.mkdir(parents=True, exist_ok=True)
        probe = primary.parent / f".probe-{os.getpid()}"
        probe.write_text("", encoding="utf-8")
        probe.unlink()
        return primary
    except OSError:  # a read-only git directory (a sandboxed check): the cache moves to the temporary folder
        key = hashlib.sha256(str(ROOT).encode("utf-8")).hexdigest()[:16]
        return Path(tempfile.gettempdir()) / "skm-affected-tests" / key / "green.json"


# Inline JSON Schemas keep this hub script stdlib-only. The small validator below implements exactly their keywords.
GREEN_SCHEMA = {"$id": "urn:swissknifeman:hub:affected-tests:green:v1", "type": "object", "additionalProperties": False,
                "patternProperties": {"^[a-f0-9]{64}$": {"type": "object", "required": ["folder", "command"],
                    "additionalProperties": False, "properties": {"folder": {"type": "string"},
                    "command": {"type": "array", "items": {"type": "string"}, "minItems": 1}}}}}
DURATIONS_SCHEMA = {"$id": "urn:swissknifeman:hub:affected-tests:durations:v1", "type": "object",
                    "additionalProperties": {"type": "number", "minimum": 0}}
EXPLAIN_SCHEMA = {
    "$id": "urn:swissknifeman:hub:affected-tests:selection:v1", "type": "object",
    "required": ["tier", "units", "hub", "commands"], "additionalProperties": False,
    "properties": {
        "tier": {"type": "string", "enum": ["fast", "full", "all"]},
        "units": {"type": "array", "items": {"type": "string"}}, "hub": {"type": "boolean"},
        "commands": {"type": "array", "items": {"type": "object", "required": ["folder", "argv"],
            "additionalProperties": False, "properties": {"folder": {"type": "string"},
            "argv": {"type": "array", "items": {"type": "string"}, "minItems": 1}}}},
        "profiles": {"type": "array", "items": {"type": "string"}},
        "inputs": {"type": "array", "items": {"type": "string"}},
        "jobs": {"type": "object", "required": ["requested", "effective", "budget", "child"],
                 "additionalProperties": {"type": "integer", "minimum": 1}},
        "selection": {"type": "array", "items": {"type": "object", "additionalProperties": False,
            "required": ["folder", "profiles", "context", "inputs", "obligation", "reason"], "properties": {
                "folder": {"type": "string"}, "profiles": {"type": "array", "items": {"type": "string"}},
                "context": {"type": "string"}, "inputs": {"type": "array", "items": {"type": "string"}},
                "obligation": {"type": "string", "enum": ["full-suite", "explicit-subset"]},
                "reason": {"type": "string"}}}}}}


def _valid(doc, schema) -> bool:
    if "enum" in schema and doc not in schema["enum"]:
        return False
    kind = schema.get("type")
    if kind == "object":
        if not isinstance(doc, dict) or any(k not in doc for k in schema.get("required", ())):
            return False
        for key, value in doc.items():
            sub = schema.get("properties", {}).get(key)
            if sub is None:
                sub = next((s for p, s in schema.get("patternProperties", {}).items() if re.fullmatch(p, key)),
                           schema.get("additionalProperties", {}))
            if sub is False or not _valid(value, sub):
                return False
        return True
    if kind == "array":
        return isinstance(doc, list) and len(doc) >= schema.get("minItems", 0) and all(
            _valid(item, schema.get("items", {})) for item in doc)
    if kind == "string":
        return isinstance(doc, str)
    if kind == "boolean":
        return isinstance(doc, bool)
    if kind == "integer":
        return type(doc) is int and doc >= schema.get("minimum", -math.inf)
    if kind == "number":
        return type(doc) in (int, float) and (type(doc) is int or math.isfinite(doc)) and doc >= schema.get("minimum", -math.inf)
    return True


def _cache_schema(path: Path) -> dict:
    return DURATIONS_SCHEMA if path.name == "durations.json" else GREEN_SCHEMA


def read_cache(path: Path) -> dict:
    try:
        found = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError, RecursionError):
        return {}
    return found if _valid(found, _cache_schema(path)) else {}


def _write_json_atomic(path: Path, doc) -> None:
    """A reader sees either complete document, even when multiple checks write concurrently."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = None
    try:
        with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent, delete=False) as stream:
            tmp = Path(stream.name)
            json.dump(doc, stream, sort_keys=True, allow_nan=False)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(tmp, path)
    finally:
        if tmp is not None:
            tmp.unlink(missing_ok=True)


def merge_cache(path: Path, updates: dict) -> None:
    # Atomic replace protects readers; the lock also prevents lost read/merge/write updates across processes.
    import fcntl
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.with_suffix(".lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        doc = {**read_cache(path), **updates}
        if not _valid(doc, _cache_schema(path)):
            raise ValueError(f"invalid cache document: {path.name}")
        _write_json_atomic(path, doc)
    if path.name.startswith("run-"):
        for old in path.parent.glob("run-*.json"):
            try:
                if old != path and old.stat().st_mtime < time.time() - 14 * 86400:
                    old.unlink()
            except OSError:
                pass  # another writer may already have pruned it


def bridge_env() -> dict:
    """The partners a bridge finds through the environment, wired from the hub layout (as scripts/test-bridges.sh does)."""
    env = dict(os.environ)
    packages = ROOT / "packages"
    env.update({name: str(packages / unit) for name, unit in PARTNER_ENV.items()})
    env["PLANNER_PLAN_PY"] = str(packages / "planner/scripts/plan.py")
    return env


@contextlib.contextmanager
def command_env(folder: str, command: list):
    """The environment of one command. ``validate.sh`` of a module calls the guarded CLIs of the clone (``skiller registry
    --check``), which refuse the real HOME, so it runs with a throwaway one, as scripts/dev-sandbox.sh sets it up."""
    env = bridge_env()
    env.pop("SKM_VALIDATE_SKIP_TESTS", None)  # only this invocation can establish the full-test prerequisite
    if command[-1:] != ["scripts/validate.sh"]:
        yield env
        return
    with tempfile.TemporaryDirectory(prefix="skm-validate-home-") as home:
        env.update({"HOME": home, "XDG_CONFIG_HOME": f"{home}/.config", "XDG_STATE_HOME": f"{home}/.local/state",
                    "XDG_DATA_HOME": f"{home}/.local/share", "XDG_CACHE_HOME": f"{home}/.cache",
                    "SKM_HOME": f"{home}/.swissknifeman-home", "GIT_CONFIG_GLOBAL": f"{home}/.gitconfig"})
        yield env


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--base")
    parser.add_argument("--paths", nargs="*")
    parser.add_argument("--tier", choices=["fast", "full", "all"], default="fast")
    parser.add_argument("--with-tools", action="store_true")
    parser.add_argument("--run", action="store_true")
    parser.add_argument("-j", "--jobs", type=int, default=3)
    parser.add_argument("--fail-fast", action="store_true", help="stop submitting jobs after the first failed command")
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--no-cache", dest="cache", action="store_false",
                        help="run every command even when its content was green before")
    args = parser.parse_args(argv)
    if args.jobs < 1:
        parser.error("jobs must be positive")
    try:
        budget = int(os.environ.get("SKM_TEST_JOBS", os.cpu_count() or 2))
        if budget < 1:
            raise ValueError
    except ValueError:
        parser.error("SKM_TEST_JOBS must be a positive integer")
    config = json.loads((ROOT / "configs" / "ecosystem-units.json").read_text(encoding="utf-8"))
    tools = set((config.get("standalone") or {}).get("tools") or ())
    all_units = units()
    foundation = (config.get("foundation") or {}).get("id", "aicore")
    paths = changed_paths(args)
    folders, hub = select(all_units, foundation, tools, paths, args.tier, args.with_tools)
    subsets, explain = obligations(all_units, folders, paths, foundation, args.tier)
    plan = commands(all_units, folders, hub, args.tier, paths, subsets)
    jobs = min(args.jobs, budget, max(1, sum(f != "hub" for f, _ in plan)))
    share = str(max(1, budget // jobs))
    flat = [(f, a) for f, argv in plan for a in argv]
    if args.json:
        document = {"tier": args.tier, "units": folders, "hub": hub,
                          "commands": [{"folder": f, "argv": a} for f, a in flat], "selection": explain,
                          "profiles": sorted({profile(all_units, foundation, p) for p in paths}),
                          "inputs": paths, "jobs": {"requested": args.jobs, "effective": jobs,
                                                   "budget": budget, "child": int(share)}}
        if not _valid(document, EXPLAIN_SCHEMA):
            raise ValueError("invalid selection document")
        print(json.dumps(document, indent=2))
    else:
        for folder, command in flat:
            print(f"{folder}: {' '.join(command)}")
    if not args.run:
        return 0

    primary = cache_file()
    durations_store = primary.with_name("durations.json")
    durations = read_cache(durations_store)
    run_id = os.environ.get("SKM_CHECK_RUN", "")
    store = None
    if args.cache:
        if args.tier != "all":
            store = primary
        elif re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]*", run_id):
            store = primary.with_name(f"run-{run_id}.json")
    green = read_cache(store) if store else {}
    by_id = {doc.get("id", f.split("/")[-1]) for f, doc in all_units.items()}
    stop = threading.Event()

    def key_of(folder, command, skip_tests):
        if not store or folder == "hub":
            return None
        reads = requirements(all_units, folder, foundation)
        if any((r.get("unit") if isinstance(r, dict) else r) not in by_id
               for f in reads for r in all_units[f].get("requires") or ()):
            return None  # unknown dependencies cannot produce a reusable receipt
        return content_key(reads, command, {"child_jobs": share, "skip_tests": skip_tests})

    def run(item):
        folder, argv = item
        results, tested = [], False
        cwd = ROOT if folder == "hub" else ROOT / folder
        dev = all_units.get(folder, {}).get("dev") or {}
        for command in argv:
            is_test = command == dev.get("test")
            skip_tests = tested and command == dev.get("validate")
            key = key_of(folder, command, skip_tests)
            cached = bool(key and key in green)
            seconds, done, stable, launched = None, None, False, False
            if not cached:
                began = time.monotonic()
                try:
                    with command_env(folder, command) as env:
                        env["SKM_TEST_JOBS"] = share
                        if skip_tests:
                            env["SKM_VALIDATE_SKIP_TESTS"] = "1"
                        done = subprocess.run(command, cwd=cwd, capture_output=True, text=True, env=env)
                        launched = True
                except OSError as error:
                    done = subprocess.CompletedProcess(command, 1, "", str(error) + "\n")
                seconds = time.monotonic() - began
                if done.returncode:
                    stop.set()
                stable = bool(key and key == key_of(folder, command, skip_tests))
            # A cached full test is green; a freshly failed full test remains in results, even when validate skips it.
            tested = tested or (is_test and (cached or launched))
            results.append((folder, command, done, key if stable else None, seconds))
        return results

    failed = 0
    updates, spent = {}, {}

    def record(results):
        nonlocal failed
        for folder, command, done, key, seconds in results:
            state = "cached" if done is None else "ok" if done.returncode == 0 else "FAIL"
            print(f"[{state}] {folder}: {' '.join(command)}", flush=True)
            if seconds is not None:
                spent[folder + " " + " ".join(command)] = seconds
            if done is not None and done.returncode:
                failed += 1
                sys.stderr.write((done.stdout + done.stderr)[-3000:])
            elif key:
                updates[key] = {"folder": folder, "command": command}

    def skipped(items):
        for folder, argv in items:
            for command in argv:
                print(f"[skipped] {folder}: {' '.join(command)} (fail-fast)", flush=True)

    hubs = [item for item in plan if item[0] == "hub"]
    rest = [item for item in plan if item[0] != "hub"]
    # Stable sort: unknown jobs follow the known ones in their original order.
    def weight(item):
        keys = [item[0] + " " + " ".join(a) for a in item[1]]
        return (not any(k in durations for k in keys), -sum(durations.get(k, 0) for k in keys))
    rest.sort(key=weight)
    # A barrier makes cheap hub failures visible before any expensive unit work is launched.
    for index, item in enumerate(hubs):
        record(run(item))
        if failed and args.fail_fast:
            skipped(hubs[index + 1:] + rest)
            rest = []
            break
    with ThreadPoolExecutor(max_workers=jobs) as pool:
        pending, index = set(), 0
        while pending or index < len(rest):
            while index < len(rest) and len(pending) < jobs and not (stop.is_set() and args.fail_fast):
                pending.add(pool.submit(run, rest[index]))
                index += 1
            if not pending:
                break
            done, pending = wait(pending, return_when=FIRST_COMPLETED)
            for future in done:
                record(future.result())
        if index < len(rest):
            skipped(rest[index:])
    if store:
        merge_cache(store, updates)
    merge_cache(durations_store, spent)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
