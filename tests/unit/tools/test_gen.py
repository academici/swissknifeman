def _cli_scaffold(tmp_path: Path, db_source: str) -> Path:
    commands = tmp_path / "src/skm/entrypoints/cli/commands"
    commands.mkdir(parents=True)
    (commands.parent / "parser.py").write_text("GLOBAL_FLAGS = [(('--json',), {'help': 'machine output'})]\n")
    (commands / "db.py").write_text(db_source)
    return tmp_path


_LOCAL_GROUP = """
_HELP = {"migrate": "apply", "snapshot": "print"}


def register(sub):
    verbs = sub.add_parser("db").add_subparsers()
    for verb in ("migrate", "snapshot"):
        command = verbs.add_parser(verb, help=_HELP[verb])
        command.add_argument("--database-url", metavar="URL")
        if verb == "migrate":
            command.add_argument("--target", type=int)
            command.add_argument("--dry-run", action="store_true")
        elif verb == "snapshot":
            command.add_argument("--output")
            command.add_argument("--write", action="store_true")
"""


def test_cli_reference_emits_local_group_without_operations(tmp_path):
    cli_reference = importlib.import_module("tools.codegen.cli_reference")
    text = cli_reference.outputs(_cli_scaffold(tmp_path, _LOCAL_GROUP))[Path("docs/reference/cli.md")]
    rows = {line.split(" | ")[0]: line for line in text.splitlines() if line.startswith("| skm db ")}
    migrate = "| skm db migrate | local | apply | --database-url; --target; --dry-run |"
    snapshot = "| skm db snapshot | local | print | --database-url; --output; --write |"
    assert rows["| skm db migrate"] == migrate
    assert rows["| skm db snapshot"] == snapshot


def test_cli_reference_local_group_keeps_verb_specific_flags_apart(tmp_path):
    cli_reference = importlib.import_module("tools.codegen.cli_reference")
    text = cli_reference.outputs(_cli_scaffold(tmp_path, _LOCAL_GROUP))[Path("docs/reference/cli.md")]
    migrate = next(line for line in text.splitlines() if line.startswith("| skm db migrate"))
    snapshot = next(line for line in text.splitlines() if line.startswith("| skm db snapshot"))
    assert "--write" not in migrate
    assert "--dry-run" not in snapshot


