"""Codex permission flag rendering, isolated config.toml generation, and denial hints."""

from __future__ import annotations

import json
import posixpath
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Final, Literal

from skm.kernel.error_codes import ErrorCode
from skm.kernel.errors import CapabilityUnavailable
from skm.kernel.isolation import IsolationProfile
from skm.modules.runtimes.domain.classes import RoleId
from skm.modules.runtimes.domain.request import AgentRequest
from skm.platform.fs.atomic_write import atomic_write
from skm.platform.process.argv_rules import check_argv

__all__: list[str] = []

SandboxMode = Literal["read-only", "workspace-write", "danger-full-access"]

_SAFE_PROG_RE: Final = re.compile(r"^[A-Za-z0-9._+-]{1,64}$")
_SAFE_MCP_NAME_RE: Final = re.compile(r"^[A-Za-z0-9._-]{1,64}$")
_SAFE_ENV_KEY_RE: Final = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,127}$")
_NETWORK_TOOLS: Final = frozenset({"WebSearch", "WebFetch", "web_search", "web_fetch"})


@dataclass(frozen=True, slots=True)
class RenderedPermissions:
    """Rendered Codex CLI sandbox flags and isolated config.toml path for one step."""

    sandbox_mode: SandboxMode
    argv: tuple[str, ...]
    config_path: Path
    bypass_approvals_and_sandbox: bool = False


def can_bypass_approvals_and_sandbox(
    request: AgentRequest,
    *,
    policy_profile: str | None,
    allow_full_access: bool,
    bypass_supported: bool = True,
    request_bypass: bool = False,
) -> bool:
    """``--dangerously-bypass-approvals-and-sandbox`` requires external containment and full-access policy."""
    if not request_bypass or not bypass_supported:
        return False
    return (
        policy_profile == "trusted-full-access"
        and allow_full_access
        and request.isolation_profile in (IsolationProfile.LANDLOCK, IsolationProfile.CONTAINER)
    )


def resolve_sandbox_mode(
    request: AgentRequest,
    *,
    policy_profile: str | None = None,
    allow_full_access: bool = False,
) -> SandboxMode:
    """Map ``AgentRequest.permissions`` and policy profile onto Codex ``--sandbox`` mode (Dossier §3.2)."""
    effective_profile = policy_profile or request.labels.get("policy_profile")
    has_wildcard_write = any(rule.root == "*" for rule in request.permissions.fs_write.allow)
    if allow_full_access and (effective_profile == "trusted-full-access" or has_wildcard_write):
        sandbox_mode: SandboxMode = "danger-full-access"
    elif request.permissions.fs_write.allow:
        sandbox_mode = "workspace-write"
    else:
        sandbox_mode = "read-only"

    needs_network = (
        request.role is RoleId.RESEARCHER
        or request.permissions.network.mode != "none"
        or bool(request.permissions.tools & _NETWORK_TOOLS)
    )
    if sandbox_mode == "read-only" and needs_network:
        raise CapabilityUnavailable(
            ErrorCode.CAPABILITY_UNAVAILABLE,
            "Codex read-only sandbox does not support network access",
            details={
                "runtime_id": "codex",
                "reason": "read_only_network_unsupported",
                "role": request.role.value,
            },
        )
    return sandbox_mode


def _toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False).replace("\x7f", "\\u007f")


def _toml_string_array(values: tuple[str, ...] | list[str]) -> str:
    return "[" + ", ".join(_toml_string(item) for item in values) + "]"


def render_codex_config_toml(request: AgentRequest) -> str:
    """Render minimal isolated ``config.toml`` with explicit request MCP servers and zero secrets."""
    secret_values = tuple(secret.reveal() for secret in request.secret_env.values())
    lines: list[str] = [
        "# Generated by SKM for isolated Codex execution (P08.04).",
    ]
    if request.config_mode == "isolated":
        lines.append('cli_auth_credentials_store = "file"')
    for server in sorted(request.mcp_servers, key=lambda item: item.name):
        if not _SAFE_MCP_NAME_RE.fullmatch(server.name):
            raise ValueError(f"invalid MCP server name: {server.name!r}")
        argv = check_argv(server.command)
        lines.append("")
        lines.append(f"[mcp_servers.{server.name}]")
        lines.append(f"args = {_toml_string_array(argv[1:])}")
        lines.append(f"command = {_toml_string(argv[0])}")
        if server.secret_env_names:
            for secret_name in server.secret_env_names:
                if not _SAFE_ENV_KEY_RE.fullmatch(secret_name):
                    raise ValueError(f"invalid MCP secret_env name: {secret_name!r}")
            lines.append(f"env_vars = {_toml_string_array(sorted(set(server.secret_env_names)))}")
        if server.env:
            lines.append("")
            lines.append(f"[mcp_servers.{server.name}.env]")
            for key in sorted(server.env):
                if not _SAFE_ENV_KEY_RE.fullmatch(key):
                    raise ValueError(f"invalid MCP env key: {key!r}")
                lines.append(f"{key} = {_toml_string(server.env[key])}")

    payload = "\n".join(lines) + "\n"
    if any(secret and secret in payload for secret in secret_values):
        raise ValueError("secret plaintext must never enter Codex config.toml")
    return payload


def write_codex_config_toml(request: AgentRequest, target_dir: Path) -> Path:
    """Write a private ``config.toml``, read-only for a verified launch."""
    payload = render_codex_config_toml(request)
    config_path = target_dir / "config.toml"
    mode = 0o600 if request.verification_context is None else 0o400
    atomic_write(config_path, payload.encode("utf-8"), mode=mode, private=True)
    return config_path


def render_permission_flags(
    request: AgentRequest,
    *,
    config_dir: Path,
    policy_profile: str | None = None,
    allow_full_access: bool = False,
    bypass_supported: bool = True,
    request_bypass: bool = False,
) -> RenderedPermissions:
    """Resolve sandbox mode, write isolated ``config.toml``, and render Codex CLI sandbox flags."""
    if config_dir.resolve().is_relative_to(Path(request.workdir).resolve()):
        raise ValueError("config_dir must be outside request.workdir")

    effective_profile = policy_profile or request.labels.get("policy_profile")
    sandbox_mode = resolve_sandbox_mode(
        request,
        policy_profile=effective_profile,
        allow_full_access=allow_full_access,
    )
    bypass = can_bypass_approvals_and_sandbox(
        request,
        policy_profile=effective_profile,
        allow_full_access=allow_full_access,
        bypass_supported=bypass_supported,
        request_bypass=request_bypass,
    )
    config_path = write_codex_config_toml(request, config_dir)

    if request.resume_session_ref is not None:
        flags: list[str] = ["-c", f'sandbox_mode="{sandbox_mode}"']
    else:
        flags = ["--sandbox", sandbox_mode]

    return RenderedPermissions(
        sandbox_mode=sandbox_mode,
        argv=tuple(flags),
        config_path=config_path,
        bypass_approvals_and_sandbox=bypass,
    )


def denial_hint(tool: str, tool_input: object) -> str:
    """Produce a bounded, secret-free diagnostic hint for a denied tool call (never raw arguments)."""
    clean_tool = tool.strip()
    if clean_tool in ("file_change", "apply_patch", "Edit", "Write"):
        return "filesystem write denied by Codex sandbox policy"
    if clean_tool in ("command_execution", "shell", "Bash"):
        if isinstance(tool_input, dict):
            raw_cmd = tool_input.get("command")  # pyright: ignore[reportUnknownMemberType,reportUnknownVariableType]
            if isinstance(raw_cmd, str) and raw_cmd.strip():
                first = posixpath.basename(raw_cmd.strip().split()[0])
                if _SAFE_PROG_RE.fullmatch(first):
                    return f"shell command '{first}' denied by Codex sandbox policy"
            elif isinstance(raw_cmd, list) and raw_cmd:
                first_item = raw_cmd[0]  # pyright: ignore[reportUnknownVariableType]
                if isinstance(first_item, str) and first_item.strip():
                    first = posixpath.basename(first_item.strip().split()[0])
                    if _SAFE_PROG_RE.fullmatch(first):
                        return f"shell command '{first}' denied by Codex sandbox policy"
        return "shell command denied by Codex sandbox policy"
    if clean_tool in ("web_search", "WebSearch", "WebFetch"):
        return "network access denied by Codex sandbox policy"
    if clean_tool == "mcp_tool_call" or clean_tool.startswith("mcp__"):
        return "MCP tool call denied by Codex sandbox policy"
    return "tool call denied by Codex sandbox policy"
