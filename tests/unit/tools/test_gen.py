def wide_outputs(tmp_path, node, only):
    """Generator outputs for ``node`` loaded from a schema file whose ``"WIDE"`` is the wide integer token."""
    node["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    path = tmp_path / "schemas/example/example.v1.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(node).replace('"WIDE"', WIDE_TEXT))
    limit = sys.get_int_max_str_digits()
    result = generator.outputs(tmp_path, only=only, schema_root=tmp_path / "schemas")
    assert sys.get_int_max_str_digits() == limit
    return result


def exact_digest(node):
    payload = json.dumps({node["$id"]: node}, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.replace('"WIDE"', WIDE_TEXT).encode()).hexdigest()


@pytest.mark.parametrize("keyword", ["maximum", "const", "default"])
def test_wide_schema_integer_gets_exact_digest_and_python_constant(tmp_path, monkeypatch, keyword):
    node = schema()
    node["properties"]["value"][keyword] = "WIDE"
    if keyword == "default":
        node["required"] = []
    rendered = wide_outputs(tmp_path, node, "python")
    text = rendered[Path("src/skm/modules/example/generated/documents.py")]
    assert f"schemas sha256:{exact_digest(node)};" in text
    module = ModuleType(node["x-skm-codegen"]["python"]["module"])
    monkeypatch.setitem(sys.modules, module.__name__, module)
    exec(compile(text, "<wide integer>", "exec"), module.__dict__)  # noqa: S102
    if keyword == "maximum":
        assert hex(WIDE) not in text
        assert module.Example.from_json({"value": WIDE}).value == WIDE
        return
    # Exact in hexadecimal: a decimal literal this wide does not compile under the interpreter limit.
    assert hex(WIDE) in text
    assert module.Example.from_json({"value": WIDE}).value == WIDE
    if keyword == "default":
        assert module.Example().value == WIDE
        assert module.Example.from_json({}).value == WIDE
    else:
        assert get_type_hints(module.Example, module.__dict__)["value"].__args__ == (WIDE,)
        with pytest.raises(ValueError, match=WIDE_REFUSAL):
            module.Example.from_json({"value": WIDE - 1})


