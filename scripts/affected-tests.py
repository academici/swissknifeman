#!/usr/bin/env python3
"""The tests a change needs, and no others: modules touched by the changed paths and the units that depend on them.

    affected-tests.py [--base REF] [--paths P ...] [--tier fast|full|all] [--with-tools] [--run] [-j N] [--fail-fast] [--json]

Changed paths come from ``git status`` (both rename owners), or from ``git diff REF`` plus untracked files with ``--base``, or from
``--paths``. Each path belongs to the unit whose folder is its longest prefix (``packages/<id>``, ``bridges/<id>``); other
paths belong to the hub. The affected set is the touched units plus the units that require a touched one (a bridge follows
its partners); a change of the foundation (``aicore``) affects every unit. A *tool* (``standalone.tools`` of
``configs/ecosystem-units.json``, e.g. ``maind``) is tested only when its own files changed or ``--with-tools`` is given: it
never joins the tests of the core because a core module changed.

Tiers: ``fast`` runs ``dev.test`` of the affected units (and the hub checks of the hub paths that changed); ``full`` adds
``dev.validate``; ``all`` is every unit that is not a tool — the full pass for the end of a phase. Without ``--run`` the
commands are only printed (one per line, ``<folder>: <command>``), ``--json`` prints them as a document.

Hub paths bring their own checks: always ``ecosystem-units check`` and ``public-hygiene``; ``golden.py check`` when a
generated surface can move (skills, configs, bootstrap, command catalogs, unit manifests) and with any change inside a
unit (its help and generated bytes are golden; seconds); ``scripts/test-<name>.py`` when
``scripts/<name>.*`` or the test itself changed.

Hub checks finish first; unit jobs run test then validate, longest previous duration first. Only a full test permits
validate to skip its own tests (a failed test remains failed). Known test-only surfaces can select an explicit subset
in fast; unknown surfaces fall back to the full owner/dependent closure. JSON explains each obligation and its inputs.
``--fail-fast`` stops submitting jobs after a failure; running jobs finish. Nested runners share SKM_TEST_JOBS.

Green results use content, Python, runner/config/dependency bytes, tools and execution environment; inputs are checked
again after execution. The git directory's affected-tests/ holds atomically merged green.json and durations.json.
Tier all never reads green.json: only a safe SKM_CHECK_RUN enables reuse in run-<id>.json within that conductor run.
Manual tier-all runs are full; --no-cache disables all reuse. Run receipts older than 14 days are pruned on write.
"""
