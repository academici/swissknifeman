class EnvironmentProblem(Exception):
    """Not a usage error of the user's command line but a missing prerequisite (exit 2)."""


@dataclass(frozen=True)
class Issue:
    code: str
    path: str
    message: str

    def text(self) -> str:
        return f"ECOSYSTEM_{self.code}: {self.path}: {self.message}"

    def as_json(self) -> dict:
        return {"code": f"ECOSYSTEM_{self.code}", "path": self.path, "message": self.message}


@dataclass
class Context:
    root: Path
    config: dict
    files: list
    _units: dict = field(default_factory=dict)
    _texts: dict = field(default_factory=dict)

    def text(self, rel: str):
        """File contents as text (undecodable bytes replaced), or None when it cannot be read."""
        if rel not in self._texts:
            try:
                self._texts[rel] = (self.root / rel).read_text(encoding="utf-8", errors="replace")
            except OSError:
                self._texts[rel] = None
        return self._texts[rel]


@dataclass
class Unit:
    folder: str
    doc: object  # parsed unit.json (any JSON value; validity is a separate check)
    base: str = ""  # repository-relative folder of the unit: packages/<id> or bridges/<id>


# --------------------------------------------------------------------------------------------- inputs

def list_files(root: Path) -> list:
    """Tracked and untracked-not-ignored files that exist, as sorted POSIX paths relative to root."""
    try:
        result = subprocess.run(["git", "-C", str(root), "ls-files", "-z", "--cached", "--others",
                                 "--exclude-standard"], capture_output=True, check=True)
    except (OSError, subprocess.CalledProcessError) as exc:
        raise EnvironmentProblem(f"{root}: cannot list files with git: {exc}") from exc
    names = [n for n in result.stdout.decode("utf-8", "surrogateescape").split("\0") if n]
    return sorted({n for n in names if (root / n).is_file()})


def load_config(root: Path) -> dict:
    path = root / CONFIG_PATH
    try:
        config = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise EnvironmentProblem(f"{CONFIG_PATH}: cannot load: {exc}") from exc
    if not isinstance(config, dict):
        raise EnvironmentProblem(f"{CONFIG_PATH}: must be a JSON object")
    return config


def build_context(root: Path) -> Context:
    return Context(root=root, config=load_config(root), files=list_files(root))


def schema_validator():
    """Closed-profile validator of the foundation (``aicore.util.schema``)."""
    lib = str(HUB_ROOT / "packages" / "aicore" / "lib")
    if lib not in sys.path:
        sys.path.insert(0, lib)
    try:
        from aicore.util import schema  # type: ignore
    except ImportError as exc:
        raise EnvironmentProblem(f"cannot import aicore.util.schema from {lib}: {exc}") from exc
    return schema


# ------------------------------------------------------------------------------------ semver and ranges

def parse_version(text: str):
    """(major, minor, patch, release_flag); a pre-release sorts below its release (flag 0 < 1)."""
    match = SEMVER.match(text)
    if not match:
        return None
    return (int(match.group(1)), int(match.group(2)), int(match.group(3)), 0 if match.group(4) else 1)


def caret_bounds(text: str):
    """npm caret ``^X.Y[.Z]`` as (inclusive lower, exclusive upper) comparison keys, or None if malformed.

    X > 0: >=X.Y.Z <(X+1).0.0. X = 0: >=0.Y.Z <0.(Y+1).0; with an explicit patch on 0.0 the patch is pinned:
    ^0.0.Z is >=0.0.Z <0.0.(Z+1). A pre-release of the lower bound does not satisfy the range.
    """
    match = CARET.match(text)
    if not match:
        return None
    major, minor = int(match.group(1)), int(match.group(2))
    patch = int(match.group(3)) if match.group(3) is not None else 0
    if major > 0:
        upper = (major + 1, 0, 0, 0)
    elif minor > 0 or match.group(3) is None:
        upper = (0, minor + 1, 0, 0)
    else:
        upper = (0, 0, patch + 1, 0)
    return (major, minor, patch, 1), upper


def satisfies(version: str, range_text: str) -> bool:
    key = parse_version(version)
    bounds = caret_bounds(range_text)
    if key is None or bounds is None:
        return False
    return bounds[0] <= key < bounds[1]


def read_version(root: Path, source: dict) -> str:
    """Version string from a ``version_sources`` entry; raises ValueError with a readable reason."""
    path, how = source.get("path"), source.get("read")
    if not isinstance(path, str) or how not in VERSION_READERS:
        raise ValueError(f"version source must have a path and a read mode of {', '.join(VERSION_READERS)}")
    try:
        text = (root / path).read_text(encoding="utf-8")
    except OSError as exc:
        raise ValueError(f"cannot read {path}: {exc.strerror or exc}") from exc
    if how == "json:version":
        try:
            value = json.loads(text).get("version")
        except (ValueError, AttributeError) as exc:
            raise ValueError(f"{path} is not a JSON object with a version") from exc
    else:
        value = None
        try:
            for node in ast.parse(text).body:
                if isinstance(node, ast.Assign) and any(
                        isinstance(t, ast.Name) and t.id == "__version__" for t in node.targets):
                    value = ast.literal_eval(node.value)
        except (SyntaxError, ValueError) as exc:
            raise ValueError(f"cannot read __version__ from {path}: {exc}") from exc
    if not isinstance(value, str):
        raise ValueError(f"{path} has no string version")
    return value


# ----------------------------------------------------------------------------------------------- units

def module_folders(ctx: Context) -> list:
    """Folders under packages/ that hold files, minus the retired ones."""
    retired = set(ctx.config.get("retired") or ())
    folders = {p.split("/")[1] for p in ctx.files if p.startswith("packages/") and p.count("/") >= 2}
    return sorted(folders - retired)


def bridge_folders(ctx: Context) -> list:
    """Folders under bridges/ that hold files: every one is a bridge unit of the hub."""
    return sorted({p.split("/")[1] for p in ctx.files if p.startswith(BRIDGES_DIR + "/") and p.count("/") >= 2})


def unit_base(ctx: Context, folder: str) -> str:
    """Repository-relative folder of a unit id: packages/<id>, or bridges/<id> for a bridge."""
    if folder in bridge_folders(ctx) and folder not in packages_folders(ctx):
        return f"{BRIDGES_DIR}/{folder}"
    return f"packages/{folder}"


def load_units(ctx: Context) -> dict:
    """folder -> Unit for every module and bridge folder whose unit.json exists and parses; cached per context."""
    if not ctx._units:
        for base in [f"packages/{f}" for f in module_folders(ctx)] + [f"{BRIDGES_DIR}/{f}" for f in bridge_folders(ctx)]:
            folder = base.split("/")[1]
            if folder in ctx._units:
                continue  # a bridge folder named like a module is reported by the manifest check
            try:
                doc = json.loads((ctx.root / base / UNIT_FILE).read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            ctx._units[folder] = Unit(folder, doc, base)
    return ctx._units


def unit_registry(ctx: Context, schema):
    """The registry of unit/v1 together with the contracts it references (permissions/v1)."""
    registry, _kind = schema.load_contract(ctx.root / AICORE_SCHEMAS[0][1], urn_prefix=AICORE_SCHEMA_URN_PREFIX)
    return registry


def lib_packages(ctx: Context, folder: str) -> list:
    prefix = f"packages/{folder}/lib/"
    names = set()
    for path in ctx.files:
        if path.startswith(prefix):
            top = path[len(prefix):].split("/")[0]
            if top.endswith(".py"):
                top = top[:-3]
            if top and top != "__pycache__" and not top.endswith(".egg-info"):
                names.add(top)
    return sorted(names)


def safe_relpath(value: str) -> bool:
    return not (value.startswith("/") or any(part in ("", ".", "..") for part in value.split("/")))


def check_manifests(ctx: Context) -> list:
    issues: list = []
    schema = schema_validator()
    try:
        registry = unit_registry(ctx, schema)
    except schema.SchemaProfileError as exc:
        return [Issue("SCHEMA_PROFILE", AICORE_SCHEMAS[0][1], str(exc))]
    config_versions = ctx.config.get("version_sources") or {}
    foundation_id = (ctx.config.get("foundation") or {}).get("id")
    folders = [(f, f"packages/{f}") for f in module_folders(ctx)]
    for folder in bridge_folders(ctx):
        if folder in packages_folders(ctx):
            issues.append(Issue("UNIT_ID", f"{BRIDGES_DIR}/{folder}/{UNIT_FILE}",
                                f"bridge folder {folder!r} has the name of a module folder"))
        else:
            folders.append((folder, f"{BRIDGES_DIR}/{folder}"))
    valid: dict = {}  # folder -> doc, only units that passed schema validation

    for folder, base in folders:
        manifest = f"{base}/{UNIT_FILE}"
        path = ctx.root / manifest
        if not path.is_file():
            issues.append(Issue("UNIT_MISSING", manifest, f"unit folder {base}/ has no {UNIT_FILE}"))
            continue
        try:
            doc = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            issues.append(Issue("UNIT_INVALID", manifest, f"cannot parse JSON: {exc}"))
            continue
        problems = schema.validate(doc, "unit", registry)
        for problem in problems:
            issues.append(Issue("UNIT_INVALID", manifest, f"{problem.code}: {problem.message}"))
        if problems:
            continue
        valid[folder] = doc
        if doc["id"] != folder:
            issues.append(Issue("UNIT_ID", manifest, f"id {doc['id']!r} must equal the folder name {folder!r}"))
        in_bridges = base.startswith(BRIDGES_DIR + "/")
        if in_bridges != (doc["kind"] == "bridge"):
            issues.append(Issue("UNIT_KIND", manifest, f"kind {doc['kind']!r}: a bridge lives in {BRIDGES_DIR}/ and "
                                                       f"only a bridge lives there"))
        elif in_bridges and doc["destination"] != "hub":
            issues.append(Issue("UNIT_KIND", manifest, f"destination {doc['destination']!r}: a bridge belongs to "
                                                       "the hub"))
        if not in_bridges and (ctx.root / base / "lib").is_dir():
            found = lib_packages(ctx, folder)
            if found != [folder]:
                issues.append(Issue("UNIT_LIB", manifest, f"lib/ must hold exactly one top package named "
                                                          f"{folder!r}, found {found or 'none'}"))
        issues.extend(_check_version(ctx, folder, manifest, doc, config_versions, foundation_id))
        issues.extend(_check_paths(ctx, base, manifest, doc))

    for folder, base in folders:
        if folder in valid:
            issues.extend(_check_requires(f"{base}/{UNIT_FILE}", valid[folder], valid, foundation_id))
            issues.extend(_check_ports(f"{base}/{UNIT_FILE}", valid[folder], valid))
    return issues


def _check_version(ctx, folder, manifest, doc, sources, foundation_id) -> list:
    source = sources.get(folder)
    if source is None:
        if doc["id"] == foundation_id or doc["kind"] == "bridge":
            return []  # the unit.json of the foundation and of a bridge is its own version source
        return [Issue("UNIT_VERSION", manifest, f"no entry for {folder!r} in {CONFIG_PATH} version_sources")]
    try:
        expected = read_version(ctx.root, source)
    except ValueError as exc:
        return [Issue("UNIT_VERSION", manifest, str(exc))]
    if doc["version"] != expected:
        return [Issue("UNIT_VERSION", manifest, f"version {doc['version']!r} differs from {source['path']} "
                                                f"({expected!r}); fix {UNIT_FILE}")]
    return []


def _check_requires(manifest, doc, valid, foundation_id) -> list:
    issues = []
    by_id = {d["id"]: d for d in valid.values()}
    seen = set()
    for index, req in enumerate(doc["requires"]):
        name = req["unit"]
        where = f"requires[{index}] {name!r}"
        if name in seen:
            issues.append(Issue("UNIT_REQUIRES", manifest, f"{where}: listed twice"))
        seen.add(name)
        target = by_id.get(name)
        if name == doc["id"]:
            issues.append(Issue("UNIT_REQUIRES", manifest, f"{where}: a unit cannot require itself"))
        elif target is None:
            issues.append(Issue("UNIT_REQUIRES", manifest, f"{where}: no such unit"))
        elif doc["kind"] == "foundation":
            issues.append(Issue("UNIT_REQUIRES", manifest, f"{where}: the foundation requires nothing"))
        elif target["kind"] == "bridge":
            issues.append(Issue("UNIT_REQUIRES", manifest, f"{where}: a bridge is required by nobody"))
        elif target["kind"] != "foundation" and doc["kind"] != "bridge":
            issues.append(Issue("UNIT_REQUIRES", manifest, f"{where}: a {doc['kind']} may require only the "
                                                           f"foundation, {name!r} is a {target['kind']}"))
        elif not satisfies(target["version"], req["range"]):
            issues.append(Issue("UNIT_RANGE", manifest, f"{where}: version {target['version']} of {name!r} "
                                                        f"does not satisfy {req['range']}"))
    return issues


def _check_ports(manifest, doc, valid) -> list:
    """A port is ``<module>:<point>``: the module is required by its bridge and opens the point."""
    issues = []
    by_id = {d["id"]: d for d in valid.values()}
    required = {r["unit"] for r in doc["requires"]}
    for port in doc["provides"].get("ports", ()):
        where = f"provides.ports[{port['id']}]"
        module, _, point = port["id"].partition(":")
        target = by_id.get(module)
        if port["bridge"] != doc["id"]:
            issues.append(Issue("UNIT_PORT", manifest, f"{where}: bridge {port['bridge']!r} must be {doc['id']!r}"))
        elif doc["kind"] != "bridge":
            issues.append(Issue("UNIT_PORT", manifest, f"{where}: only a bridge implements ports"))
        elif not (module and point) or module not in required or target is None:
            issues.append(Issue("UNIT_PORT", manifest, f"{where}: must be <module>:<point> of a required module"))
        elif point not in {p["id"] for p in target["provides"].get("extension_points", ())}:
            issues.append(Issue("UNIT_PORT", manifest, f"{where}: module {module!r} opens no extension point {point!r}"))
    return issues


def _check_paths(ctx, rel_base, manifest, doc) -> list:
    issues = []
    base = ctx.root / rel_base
    provides = doc["provides"]

    def probe(kind, rel, label, executable=False, directory=False, code="UNIT_PATH"):
        if not safe_relpath(rel):
            issues.append(Issue(code, manifest, f"{label}: {rel!r} must stay inside the module"))
            return None
        target = base / rel
        exists = target.is_dir() if directory else target.is_file()
        if not exists:
            issues.append(Issue(code, manifest, f"{label}: {rel!r} does not exist"))
            return None
        if executable and not (rel.endswith(".py") or os.access(target, os.X_OK)):
            issues.append(Issue(code, manifest, f"{label}: {rel!r} is not executable"))
            return None
        return target

    for rel in provides.get("cli", ()):
        probe("cli", rel, "provides.cli", executable=True)
    for plugin in provides.get("plugins", ()):
        target = probe("plugin", plugin["manifest"], f"provides.plugins[{plugin['name']}]")
        if target is not None:
            try:
                name = json.loads(target.read_text(encoding="utf-8")).get("name")
            except (OSError, ValueError, AttributeError):
                name = None
            if name != plugin["name"]:
                issues.append(Issue("UNIT_PATH", manifest, f"provides.plugins: {plugin['manifest']!r} names "
                                                           f"{name!r}, expected {plugin['name']!r}"))
    for contract in provides.get("contracts", ()):
        probe("contract", contract["path"], f"provides.contracts[{contract['id']}]", directory=True)
    for check in provides.get("doctor", ()):
        probe("doctor", check["probe"][0], f"provides.doctor[{check['id']}]")
    if "config" in provides:
        probe("config", provides["config"], "provides.config")
    for event in provides.get("events", ()):  # events-prefix: a module emits only events named after itself
        if event.split(".")[0] != doc["id"]:
            issues.append(Issue("UNIT_EVENTS_PREFIX", manifest, f"provides.events: {event!r} must start with the "
                                                               f"module id {doc['id']!r}"))
    for subscription in doc.get("subscribes", ()):  # subscribes-run: the subscriber program is part of the module
        probe("subscribes", subscription["run"][0], f"subscribes[{subscription['id']}].run", executable=True,
              code="UNIT_SUBSCRIBES_RUN")
    return issues


def check_aicore_schemas(ctx: Context) -> list:
    """Every aicore contract must load under the closed profile (draft 2020-12, no free-form keywords)."""
    if not (ctx.root / "packages" / "aicore").is_dir():
        return []
    schema = schema_validator()
    issues = []
    for kind, rel in AICORE_SCHEMAS:
        if not (ctx.root / rel).is_dir():
            issues.append(Issue("SCHEMA_PROFILE", rel, "schema directory is missing"))
    schemas_dir = ctx.root / "packages" / "aicore" / "schemas"
    for directory in sorted(schemas_dir.glob("*/v*")):
        rel = directory.relative_to(ctx.root).as_posix()
        try:
            schema.load_contract(directory)
        except schema.SchemaProfileError as exc:
            issues.append(Issue("SCHEMA_PROFILE", rel, str(exc)))
    return issues


def check_config_example(ctx: Context) -> list:
    """Each module with ``provides.config`` ships the ``config.example.toml`` generated from its schema."""
    issues: list = []
    rendered = None
    for folder, unit in sorted(load_units(ctx).items()):
        provides = unit.doc.get("provides") if isinstance(unit.doc, dict) else None
        relative = provides.get("config") if isinstance(provides, dict) else None
        if not isinstance(relative, str) or not safe_relpath(relative):
            continue  # a bad or missing path is reported by the manifest check
        schema_file = ctx.root / unit.base / relative
        example = f"{unit.base}/config.example.toml"
        hint = f"run `aicore config example {unit.base} --write`"
        if not schema_file.is_file():
            continue
        if rendered is None:
            schema_validator()  # puts the foundation lib on sys.path
            from aicore.config import example as example_mod, model  # type: ignore
            rendered = (example_mod, model)
        example_mod, model = rendered
        try:
            expected = example_mod.render(model.load_module_schema(schema_file, folder), relative)
        except Exception as exc:  # ConfigError and the like: the schema itself is wrong
            issues.append(Issue("CONFIG_SCHEMA", f"{unit.base}/{relative}", str(exc)))
            continue
        try:
            actual = (ctx.root / example).read_text(encoding="utf-8")
        except OSError:
            issues.append(Issue("CONFIG_EXAMPLE_DRIFT", example, f"missing; {hint}"))
            continue
        if actual != expected:
            issues.append(Issue("CONFIG_EXAMPLE_DRIFT", example, f"differs from the schema; {hint}"))
    return issues


def check_config(ctx: Context) -> list:
    """Shape of configs/ecosystem-units.json (only the keys the implemented checks rely on)."""
    config, issues = ctx.config, []

    def bad(message):
        issues.append(Issue("CONFIG", CONFIG_PATH, message))

    if config.get("schema_version") != "ecosystem-units/v1":
        bad("schema_version must be 'ecosystem-units/v1'")
    targets = config.get("targets")
    if not (isinstance(targets, list) and targets and all(isinstance(t, str) and t for t in targets)):
        bad("targets must be a non-empty list of strings")
        targets = []
    aliases = config.get("module_aliases")
    if not (isinstance(aliases, dict) and all(isinstance(v, str) and v in targets for v in aliases.values())):
        bad("module_aliases must map folder ids to ids listed in targets")
    retired = config.get("retired")
    if not (isinstance(retired, list) and all(isinstance(r, str) for r in retired)):
        bad("retired must be a list of folder names")
    foundation = config.get("foundation")
    if not (isinstance(foundation, dict) and isinstance(foundation.get("id"), str)
            and isinstance(foundation.get("aliases"), list)):
        bad("foundation must be {id, aliases[]}")
    sources = config.get("version_sources")
    if not isinstance(sources, dict):
        bad("version_sources must be an object")
    else:
        for folder, source in sorted(sources.items()):
            if not (isinstance(source, dict) and isinstance(source.get("path"), str)
                    and source.get("read") in VERSION_READERS):
                bad(f"version_sources[{folder!r}] must be {{path, read}} with read in {', '.join(VERSION_READERS)}")
    roots = config.get("transitional_roots")
    if not (isinstance(roots, list) and all(isinstance(r, str) and r.endswith("/") for r in roots)):
        bad("transitional_roots must be a list of directory paths ending with '/'")
    suffixes = config.get("path_suffixes")
    if not (isinstance(suffixes, list) and all(isinstance(x, str) and x.startswith(".") for x in suffixes)):
        bad("path_suffixes must be a list of suffixes starting with '.'")
    for pattern in config.get("path_patterns") if isinstance(config.get("path_patterns"), list) else [None]:
        problem = _pattern_problem(pattern)
        if problem:
            bad(f"path_patterns: {problem}")
    if not isinstance(config.get("path_patterns"), list):
        bad("path_patterns must be a list")
    allow = config.get("path_allow", [])
    if not isinstance(allow, list):
        bad("path_allow must be a list")
    else:
        for entry in allow:
            problem = _allow_problem(entry)
            if problem:
                bad(f"path_allow: {problem}")
    if not isinstance(config.get("ownership"), list):
        bad("ownership must be a list")
    free = (config.get("standalone") or {}).get("foundation_free", [])
    if not (isinstance(free, list) and all(isinstance(x, str) for x in free)):
        bad("standalone.foundation_free must be a list of module folders")
    else:
        for folder in free:
            if folder not in module_folders(ctx):
                bad(f"standalone.foundation_free: {folder!r} is not a module folder")
    return issues


def _allow_problem(entry):
    """Why a path_allow entry is unusable, or None."""
    if not (isinstance(entry, dict) and set(entry) == {"path", "reason"}
            and all(isinstance(entry[k], str) and entry[k] for k in ("path", "reason"))):
        return "each entry must be {path, reason} with non-empty strings (an exemption needs a reason)"
    return None


def _pattern_problem(pattern):
    """Why a path_patterns entry is unusable, or None."""
    if not (isinstance(pattern, dict) and {"id", "regex", "reason"} <= set(pattern) <= {"id", "regex", "reason", "climb"}
            and all(isinstance(pattern[k], str) and pattern[k] for k in ("id", "regex", "reason"))
            and isinstance(pattern.get("climb", False), bool)):
        return ("each entry must be {id, regex, reason[, climb]} with non-empty strings and a boolean climb "
                "(a pattern needs a reason)")
    try:
        compiled = re.compile(pattern["regex"])
    except re.error as exc:
        return f"{pattern['id']!r}: invalid regex: {exc}"
    if "target" not in compiled.groupindex:
        return f"{pattern['id']!r}: the regex must have a named group 'target'"
    return None


# ------------------------------------------------------------------------------------------------- map

def owner_entry(path: str, entries: list):
    """The ownership entry with the longest matching path (a file entry or a directory prefix), or None."""
    best = None
    for entry in entries:
        key = entry["path"]
        if (path == key or (key.endswith("/") and path.startswith(key))) and (best is None or len(key) > len(best["path"])):
            best = entry
    return best


def check_map(ctx: Context) -> list:
    """Ownership entries are valid and point at existing files; transitional roots are fully covered."""
    issues: list = []
    targets = ctx.config.get("targets") or []
    raw = ctx.config.get("ownership")
    entries, seen = [], set()
    for index, entry in enumerate(raw if isinstance(raw, list) else ()):
        where = f"ownership[{index}]"
        if not (isinstance(entry, dict) and isinstance(entry.get("path"), str)):
            issues.append(Issue("MAP_ENTRY", CONFIG_PATH, f"{where}: must be an object with a string path"))
            continue
        path, problems = entry["path"], []
        extra = set(entry) - {"path", "target", "subsystem", "phase", "confidence", "note"}
        if extra:
            problems.append(f"unknown keys {sorted(extra)}")
        if not safe_relpath(path.rstrip("/")) or path == "/":
            problems.append("path must be relative and stay inside the repository")
        if entry.get("target") not in targets:
            problems.append(f"target {entry.get('target')!r} is not in targets")
        if not (isinstance(entry.get("phase"), str) and PHASE.match(entry["phase"])):
            problems.append(f"phase {entry.get('phase')!r} must match {PHASE.pattern}")
        if entry.get("confidence") not in CONFIDENCE:
            problems.append(f"confidence {entry.get('confidence')!r} must be one of {', '.join(CONFIDENCE)}")
        for key in ("subsystem", "note"):
            if key in entry and not (isinstance(entry[key], str) and entry[key]):
                problems.append(f"{key} must be a non-empty string")
        if path in seen:
            problems.append("duplicate path")
        seen.add(path)
        for problem in problems:
            issues.append(Issue("MAP_ENTRY", CONFIG_PATH, f"{where} {path!r}: {problem}"))
        if problems:
            continue
        entries.append(entry)
        if path.endswith("/"):
            exists = any(f.startswith(path) for f in ctx.files)
        else:
            exists = path in ctx.files
            if not exists and any(f.startswith(path + "/") for f in ctx.files):
                issues.append(Issue("MAP_STALE", CONFIG_PATH, f"{where} {path!r} is a directory: end the path with '/'"))
                continue
        if not exists:
            issues.append(Issue("MAP_STALE", CONFIG_PATH, f"{where} {path!r} matches no file; remove the entry "
                                                          "once a phase has moved the code"))
    roots = [r for r in ctx.config.get("transitional_roots") or () if isinstance(r, str)]
    for path in ctx.files:
        if any(path.startswith(r) for r in roots) and owner_entry(path, entries) is None:
            issues.append(Issue("MAP_UNCOVERED", path, "file under a transitional root has no ownership entry"))
    return issues


# --------------------------------------------------------------------------------------------- schemas

def check_schemas(ctx: Context) -> list:
    """Every product JSON Schema declares a known draft and a versioned URN id (E14)."""
    issues = []
    for path in ctx.files:
        parts = path.split("/")
        if not path.endswith(".schema.json") or any(part in SCHEMA_SKIP_DIRS for part in parts[:-1]):
            continue
        try:
            doc = json.loads(ctx.text(path) or "")
        except ValueError as exc:
            issues.append(Issue("PARSE", path, f"cannot parse JSON: {exc}"))
            continue
        if not isinstance(doc, dict):
            issues.append(Issue("SCHEMA_ID", path, "a schema must be a JSON object"))
            continue
        draft = doc.get("$schema")
        if draft not in SCHEMA_DRAFTS:
            issues.append(Issue("SCHEMA_ID", path, f"$schema {draft!r} must be one of {', '.join(SCHEMA_DRAFTS)}"))
        elif path.startswith("packages/aicore/schemas/") and draft != SCHEMA_DRAFT_2020:
            issues.append(Issue("SCHEMA_ID", path, f"aicore schemas must use {SCHEMA_DRAFT_2020}"))
        match = SCHEMA_ID.match(doc["$id"]) if isinstance(doc.get("$id"), str) else None
        if match is None:
            issues.append(Issue("SCHEMA_ID", path, f"$id {doc.get('$id')!r} must match {SCHEMA_ID.pattern}"))
            continue
        dirs = [VERSION_DIR.match(part) for part in parts[:-1]]
        dirs = [m for m in dirs if m]
        if dirs and dirs[-1].group(1) != match.group(1):
            issues.append(Issue("SCHEMA_VERSION", path, f"$id ends with v{match.group(1)} but the folder is "
                                                        f"v{dirs[-1].group(1)}"))
    return issues


# ----------------------------------------------------------------------------------------- boundaries

def packages_folders(ctx: Context) -> set:
    return {p.split("/")[1] for p in ctx.files if p.startswith("packages/") and p.count("/") >= 2}


def import_names(ctx: Context) -> set:
    """Top-level Python packages the modules ship: ``packages/<folder>/lib/<name>/`` over every folder."""
    names = set()
    for folder in packages_folders(ctx):
        names.update(lib_packages(ctx, folder))
    return names


def module_imports(source: str, path: str):
    """Top-level names of every absolute import in a Python source; raises SyntaxError/ValueError."""
    tree = ast.parse(source, filename=path)
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                yield alias.name.split(".")[0]
        elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            yield node.module.split(".")[0]


def scannable_for_paths(path: str, suffixes) -> bool:
    parts = path.split("/")
    if "docs" in parts[:-1] or path.endswith(".md"):
        return False
    return path.endswith(tuple(suffixes)) or (len(parts) >= 4 and parts[2] == "bin")


def scan_boundaries(ctx: Context):
    """(violations {<kind>|<file>|<target>: count}, issues) over the files of every module that has a unit.json.

    The retired folders are not modules and are not scanned. Keys carry no line numbers, so moving code inside
    a file does not disturb the baseline.
    """
    issues: list = []
    violations: dict = {}
    config = ctx.config
    foundation = config.get("foundation") or {}
    foundation_names = {foundation.get("id"), *(foundation.get("aliases") or ())} - {None}
    foundation_id = foundation.get("id")
    modules = import_names(ctx)
    folders = packages_folders(ctx)
    units = {f: u for f, u in load_units(ctx).items()}
    patterns = [(p["id"], re.compile(p["regex"]), bool(p.get("climb"))) for p in config.get("path_patterns") or ()
                if _pattern_problem(p) is None]
    suffixes = config.get("path_suffixes") or ()
    path_allowed = {entry["path"] for entry in config.get("path_allow") or () if _allow_problem(entry) is None}

    def hit(kind, path, target):
        key = f"{kind}|{path}|{target}"
        violations[key] = violations.get(key, 0) + 1

    requires_foundation = {}
    for folder, unit in units.items():
        doc = unit.doc if isinstance(unit.doc, dict) else {}
        requires_foundation[folder] = any(isinstance(r, dict) and r.get("unit") == foundation_id
                                          for r in doc.get("requires") or ())
    for path in ctx.files:
        parts = path.split("/")
        if len(parts) < 3 or parts[0] not in ("packages", BRIDGES_DIR) or parts[1] not in units \
                or units[parts[1]].base != f"{parts[0]}/{parts[1]}":
            continue
        folder = parts[1]
        if path.endswith(".py"):
            try:
                names = list(module_imports(ctx.text(path) or "", path))
            except (SyntaxError, ValueError) as exc:
                issues.append(Issue("PARSE", path, f"cannot parse Python: {exc}"))
                names = []
            for name in names:
                if name in foundation_names:
                    if folder == foundation_id and name == foundation_id:
                        continue  # the foundation imports its own package; its old aliases stay violations
                    if not requires_foundation.get(folder, False):
                        hit("undeclared", path, foundation_id)
                elif name in modules and name != folder:
                    hit("import", path, name)
        if patterns and path not in path_allowed and scannable_for_paths(path, suffixes):
            text = ctx.text(path) or ""
            inside = len(parts) - 3  # directories between the module root and the file
            for _pattern_id, regex, climb in patterns:
                for match in regex.finditer(text):
                    target = match.group("target")
                    if target == folder:
                        continue
                    if target in foundation_names and requires_foundation.get(folder, False):
                        continue  # a module that declares the foundation may locate it (wrapper locator)
                    if climb:
                        # ../ climbs that stay inside the module are not escapes; one level above the module
                        # root lands in packages/, so the target must be a sibling folder there
                        above = match.group(0).count("../") - inside
                        if above < 1 or (above == 1 and target not in folders):
                            continue
                    elif target not in folders:
                        continue
                    hit("path", path, target)
    return violations, issues


def load_baseline(root: Path) -> dict:
    path = root / BASELINE_PATH
    if not path.is_file():
        return {}
    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
        violations = doc["violations"]
        if not (isinstance(violations, dict) and all(isinstance(v, int) for v in violations.values())):
            raise ValueError("violations must map keys to counts")
    except (OSError, ValueError, KeyError, TypeError) as exc:
        raise EnvironmentProblem(f"{BASELINE_PATH}: cannot load: {exc}") from exc
    return violations


def describe_violation(key: str, count: int) -> str:
    kind, _path, target = key.split("|", 2)
    if kind == "import":
        return f"imports module {target!r} ({count}x); modules reach each other only through bridges or events"
    if kind == "undeclared":
        return f"imports the foundation {target!r} ({count}x) but unit.json does not require it"
    return f"names the path of {target!r} ({count}x); reach it through a bridge or an event"


def compare_with_baseline(violations: dict, baseline: dict, strict: bool):
    """(errors, improvements) of the current violations against the accepted ones."""
    errors, improvements = [], []
    for key, count in sorted(violations.items()):
        accepted = 0 if strict else baseline.get(key, 0)
        if count > accepted:
            code = "BOUNDARY" if strict else "BOUNDARY_NEW"
            note = "" if strict or not accepted else f" (baseline allows {accepted})"
            errors.append(Issue(code, key.split("|", 2)[1], describe_violation(key, count) + note))
    if not strict:
        for key, accepted in sorted(baseline.items()):
            count = violations.get(key, 0)
            if count < accepted:
                improvements.append({"key": key, "baseline": accepted, "count": count})
    return errors, improvements


