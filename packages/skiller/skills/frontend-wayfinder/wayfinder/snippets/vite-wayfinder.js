// Source: anonymized production Laravel project
// Connection vite-plugin Wayfinder: auto-generation of types when changing routes in dev.

import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { defineConfig } from 'vite';
import laravel from 'laravel-vite-plugin';
import vue from '@vitejs/plugin-vue';
import { wayfinder } from '@laravel/vite-plugin-wayfinder';

const projectRoot = path.dirname(fileURLToPath(import.meta.url));

export default defineConfig({
    plugins: [
        // wayfinder() BEFORE laravel(): monitors route changes/controllers
        // and regenerates resources/js/{actions,routes,wayfinder} automatically.
        wayfinder(),
        laravel({
            input: ['resources/js/app.ts'],
            refresh: true,
        }),
        vue(),
    ],
    resolve: {
        alias: {
            // Alias of named routes to an autogenerated folder - the order is important:
            // more specific '@/routes' before general '@'.
            '@/routes': path.join(projectRoot, 'resources/js/wayfinder/routes'),
            '@': path.join(projectRoot, 'resources/js'),
        },
    },
});

