# --- private/source-only buckets (2026.07.24-AGENT-RELIABILITY P1.2, D31) ------
def private_source_buckets(env):
    """Бакеты, помеченные `private_source_only` в buckets.json (сейчас: ровно
    `repository-bootstrap`, класс A root-bootstrap identities) — их записи НИКОГДА не
    попадают ни в один consumer-набор (`include`/`buckets`/транзитивные `requires`),
    вне зависимости от того, каким токеном их запросили. `skillset.py` реализует ТОЛЬКО
    это consumer-исключение — он никогда не производитель root-проекций (см.
    `semantic-identity-ownership-v1.md`, `publication.py` root-bootstrap рендерер)."""
    meta_file = env.root / "buckets.json"
    if not meta_file.is_file():
        return frozenset()
    try:
        meta = json.loads(meta_file.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return frozenset()
    if not isinstance(meta, dict):
        return frozenset()
    return frozenset(name for name, data in meta.items()
                     if isinstance(data, dict) and data.get("private_source_only"))


# --- registry index (источник истины — skills.json) ---------------------------
def _registry_index(env):
    """skills.json → {key: entry}, где key — и полный путь 'bucket/rel', и имя.

    entry = {name, bucket, rel, path(SKILL.md, отн. корня реестра), sha256,
             skill_dir(абс.)}. Реестр — единственный источник, по которому
    резолвятся и проверяются на дрейф наши скиллы. Записи private-source-only бакетов
    (2026.07.24-AGENT-RELIABILITY P1.2, D31) исключены здесь же, у ЕДИНОЙ точки входа — так `include` по имени,
    `buckets` целиком и транзитивные `requires` не могут дотянуться до них ни одним
    путём (см. `private_source_buckets`)."""
    f = env.root / "skills.json"
    if not f.is_file():
        die("skills.json не найден — сначала skiller registry")
    data = json.loads(f.read_text(encoding="utf-8"))
    skills = data["skills"] if isinstance(data, dict) else data
    private_buckets = private_source_buckets(env)
    by_key = {}
    by_name = {}
    for s in skills:
        name = s.get("name") or s.get("id")
        bucket = s.get("bucket", "")
        path = s.get("path", "")  # "skills/<bucket>/<rel>/SKILL.md"
        if not (name and path):
            warn(f"skills.json: запись пропущена (нет name или path): {s}")
            continue
        if bucket in private_buckets:
            continue
        skill_dir = (env.root / path).parent
        # rel внутри бакета: skills/<bucket>/<rel>/SKILL.md → <rel>
        rel = ""
        parts = Path(path).parts
        if len(parts) >= 4 and parts[0] == "skills":
            rel = "/".join(parts[2:-1])
        entry = {
            "name": name, "bucket": bucket, "rel": rel, "path": path,
            "sha256": s.get("sha256", ""),
            "content_sha256": s.get("content_sha256", ""),
            "requires": s.get("requires", []) or [],
            "skill_dir": skill_dir,
        }
        full = f"{bucket}/{rel}".rstrip("/") if rel else bucket
        by_key[full] = entry
        if name in by_name:
            warn(f"skills.json: дубль имени '{name}' "
                 f"(бакеты: {by_name[name]['bucket']} и {bucket}) — по имени "
                 f"доступен первый; используйте полный путь 'bucket/rel'")
        else:
            by_name[name] = entry
    return by_key, by_name


def _match(token, by_key, by_name):
    """Разрешить токен правила в entry: сначала по полному пути, потом по имени.

    Drift-устойчивость: после раскола бакетов старый путь 'oldbucket/skill'
    (напр. 'frontend/vue' → 'frontend-vue/vue') промахивается по by_key. Если
    токен — путь, добиваем по базовому имени (последний сегмент). Иначе sync
    молча терял переехавшие скиллы (warn+skip). Вызывающий печатает
    migration-warning со старым→новым путём."""
    if token in by_key:
        return by_key[token]
    if token in by_name:
        return by_name[token]
    if "/" in token:
        base = token.rsplit("/", 1)[1]
        if base in by_name:
            return by_name[base]
    return None


# --- presets (именованные кластеры скиллов) -----------------------------------
def _load_preset(env, name):
    """presets/<name>.json или None. Невалидный JSON — die."""
    f = env.root / "presets" / f"{name}.json"
    if not f.is_file():
        return None
    try:
        return json.loads(f.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError) as e:
        die(f"presets/{name}.json: невалидный JSON: {e}")


def resolve_presets(env, names):
    """Раскрыть пресеты (рекурсивно `extends`) в (buckets, include, skipped).

    Пресет — именованная группа: `{name, description, extends?, buckets?, include?}`.
    Возвращает агрегированные buckets/include (с дедупом, родители раньше детей) и
    skipped — неизвестные пресеты (warning). Цикл `extends` — die."""
    buckets, include, skipped, seen = [], [], [], set()

    def visit(name, trail):
        if name in trail:
            die(f"presets: цикл extends: {' -> '.join(trail + [name])}")
        if name in seen:
            return
        preset = _load_preset(env, name)
        if preset is None:
            warn(f"presets: пресет '{name}' не найден в presets/ — пропуск")
            skipped.append(name)
            return
        seen.add(name)
        for parent in preset.get("extends", []):
            visit(parent, trail + [name])
        buckets.extend(preset.get("buckets", []))
        include.extend(preset.get("include", []))

    for n in names:
        visit(n, [])
    return buckets, include, skipped


# --- config -------------------------------------------------------------------
def skillset_config_path(target):
    return Path(target) / CONFIG_DIR / CONFIG_FILE


def load_skillset_config(target):
    """Прочитать .swissknifeman/config.json (или None, если его нет)."""
    cfg_file = skillset_config_path(target)
    if not cfg_file.is_file():
        return None
    try:
        cfg = json.loads(cfg_file.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        die(f"{cfg_file}: невалидный JSON: {e}")
    import difflib
    for key, value in cfg.items():
        if key.startswith(("_", "$")):  # _comment / $schema — DX, не валидируем
            continue
        if key not in SKILLSET_KEYS:
            hint = difflib.get_close_matches(key, list(SKILLSET_KEYS), n=1)
            suffix = f" — может быть '{hint[0]}'?" if hint else ""
            die(f"{cfg_file}: неизвестный ключ '{key}'{suffix}")
        if not isinstance(value, SKILLSET_KEYS[key]):
            want = SKILLSET_KEYS[key].__name__
            die(f"{cfg_file}: '{key}' должен быть {want}")
    if cfg.get("mode", "vendor") != "vendor":
        die(f"{cfg_file}: поддерживается только mode=vendor")
    return cfg


def _pull_requires(selected, by_name, exclude):
    """Транзитивно дотянуть `requires` выбранных скиллов в `selected` (name->entry).
    exclude ПОБЕЖДАЕТ зависимость (с warning), неизвестная зависимость — warning и
    пропуск. Без этого skill-granular include молча терял зависимости (64/195
    скиллов имеют requires). BFS — общий с vendor.resolve_requires через
    common.resolve_requires_bfs (V-1: раньше два независимых, уже разошедшихся тела)."""
    seed = [(dep, e["name"]) for e in list(selected.values())
            for dep in e.get("requires", [])]
    selected_keys = set(selected.keys())

    def lookup(dep):
        entry = by_name.get(dep)
        if entry is None:
            return None
        full = (f"{entry['bucket']}/{entry['rel']}".rstrip("/")
                if entry["rel"] else entry["bucket"])
        tokens = {dep, entry["name"], full, entry["bucket"]}
        return {"key": entry["name"], "requires": entry.get("requires", []),
                "exclude_tokens": tokens, "_payload": entry}

    for node, _requester in resolve_requires_bfs(seed, lookup, selected_keys, exclude):
        selected[node["key"]] = node["_payload"]


def resolve_skillset(env, cfg, include_core=False):
    """Развернуть правила конфига в набор entry: (buckets ∪ include) − exclude,
    затем транзитивно дотянуть `requires` (exclude по-прежнему побеждает).

    include_core=True добавляет CORE_SKILLS (как vendor/connect) и применяет
    DEFAULT_EXCLUDE — токен-скиллы раздаются в каждый проект по умолчанию.

    Возвращает (entries, skipped): entries отсортированы по 'bucket/name';
    skipped — токены, не найденные в реестре (с warning)."""
    by_key, by_name = _registry_index(env)
    known = set(all_buckets(env))
    selected = {}  # name -> entry (имя уникально в раскладке .claude/skills)
    skipped = []

    # пресеты раскрываем в buckets/include ДО формулы (buckets ∪ include) − exclude
    preset_buckets, preset_include, preset_skipped = \
        resolve_presets(env, cfg.get("presets", []))
    skipped.extend(preset_skipped)
    req_buckets = list(dict.fromkeys(preset_buckets + cfg.get("buckets", [])))
    req_include = list(dict.fromkeys(preset_include + cfg.get("include", [])))

    # бакеты целиком
    private_buckets = private_source_buckets(env)
    for bucket in req_buckets:
        if bucket in private_buckets:
            die(f"бакет '{bucket}' приватный source-only (repository-bootstrap, P1.2/D31) — "
                f"его записи не vendor'ятся/connect'ятся в проекты-потребители")
        if bucket not in known:
            die(f"неизвестный бакет: {bucket}")
        for entry in by_key.values():
            if entry["bucket"] == bucket:
                selected[entry["name"]] = entry

    # конкретные скиллы
    for token in req_include:
        entry = _match(token, by_key, by_name)
        if entry is None:
            warn(f"include: скилл '{token}' не найден в реестре — пропуск")
            skipped.append(token)
            continue
        full = (f"{entry['bucket']}/{entry['rel']}".rstrip("/")
                if entry["rel"] else entry["bucket"])
        if "/" in token and token != full:
            warn(f"include: '{token}' переехал → '{full}' (раскол бакетов) — "
                 f"обновите .swissknifeman/config.json")
        selected[entry["name"]] = entry

    # CORE-политика: токен-скиллы по умолчанию + DEFAULT_EXCLUDE дублей хаба
    exclude = set(cfg.get("exclude", []))
    if include_core:
        exclude |= set(DEFAULT_EXCLUDE)
        for _bucket, _rel, _d, fm_name in core_skill_tuples(env, exclude):
            entry = by_name.get(fm_name)
            if entry:
                selected[entry["name"]] = entry

    # вычитание
    if exclude:
        for name, entry in list(selected.items()):
            full = f"{entry['bucket']}/{entry['rel']}".rstrip("/") \
                if entry["rel"] else entry["bucket"]
            if {name, full, entry["bucket"], entry["rel"]} & exclude:
                del selected[name]

    # транзитивные requires выбранных скиллов (после вычитания: тянем зависимости
    # только тех, что реально останутся). exclude по-прежнему побеждает зависимость.
    _pull_requires(selected, by_name, exclude)

    entries = sorted(selected.values(),
                     key=lambda e: (e["bucket"], e["name"]))
    return entries, skipped


# --- lock ---------------------------------------------------------------------
def load_lock(target):
    f = Path(target) / LOCK_FILE
    if not f.is_file():
        return {}
    try:
        data = json.loads(f.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        # Битый lock молча трактовался как пустой → ВСЕ managed-скиллы считались новыми и
        # перекопировались (лишняя работа + путаный вывод). Предупреждаем: пересоберём из
        # конфига, но пусть это будет видно (проверить git-историю файла).
        warn(f"{f}: битый JSON skills-lock — игнорирую и пересоберу из конфига "
             f"(managed-скиллы могут перекопироваться). См. git-историю файла.")
        return {}
    if not isinstance(data, dict) or not isinstance(data.get("skills"), dict):
        warn(f"{f}: неожиданная структура skills-lock (нет dict 'skills') — игнорирую, пересоберу.")
        return {}
    return data


def _lock_problem(target):
    """Вернуть причину provenance-invalid lock или ``None``.

    Обычный sync не восстанавливает и не перезаписывает повреждённый lock: без
    проверяемого provenance нельзя отличить managed bytes от чужих. Legacy-lock
    без ``version`` и ``content_sha256`` остаётся читаемым, но unknown/newer
    version, provider-map и managed record проходят fail-closed проверку.
    """
    f = Path(target) / LOCK_FILE
    if not f.is_file():
        return None
    try:
        data = json.loads(f.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError, OSError):
        return "invalid-json"
    if not isinstance(data, dict):
        return "root-not-object"
    version = data.get("version", LOCK_VERSION)
    if not isinstance(version, int) or version > LOCK_VERSION:
        return "unsupported-version"
    if not isinstance(data.get("skills"), dict):
        return "skills-map-invalid"
    providers = data.get("providers", {})
    if not isinstance(providers, dict) or any(not isinstance(items, dict)
                                              for items in providers.values()):
        return "provider-map-invalid"
    maps = [data["skills"], *providers.values()]
    for entries in maps:
        for name, record in entries.items():
            if not isinstance(name, str) or not isinstance(record, dict):
                return "record-invalid"
            if record.get("managed"):
                digest = record.get("sha256")
                if (record.get("source") != SOURCE
                        or not isinstance(digest, str)
                        or len(digest) != 64
                        or any(ch not in "0123456789abcdef" for ch in digest)
                        or not isinstance(record.get("installed_path"), str)):
                    return "managed-provenance-invalid"
    return None


def _hash_label(value):
    """P2 diagnostic spelling for an existing bare lock digest."""
    return f"sha256:{value}" if value else "sha256:<missing>"


def write_lock(target, lock):
    atomic_write_json(Path(target) / LOCK_FILE, lock)


def _dir_sha256(skill_dir):
    """sha256 SKILL.md — та же база, что в реестре (skills.json считает по файлу)."""
    md = Path(skill_dir) / "SKILL.md"
    if not md.is_file():
        return ""
    return hashlib.sha256(md.read_bytes()).hexdigest()


# --- sync ---------------------------------------------------------------------
def plan_sync(env, target, cfg, include_core=False, provider="claude-code"):
    """Сухой расчёт: что добавить/обновить/удалить. Ничего не пишет.

    Возвращает dict: {add, update, managed_drift, remove, keep, conflicts,
    skills_path, entries}. ``managed_drift`` имеет приоритет над source staleness:
    ручная правка installed SKILL.md не становится обычным update.
    - add:    name'ы новых managed-скиллов
    - update: name'ы managed-скиллов с разошедшимся sha256 (или отсутствующим файлом)
    - remove: name'ы managed-скиллов из lock, которых больше нет в конфиге
    - keep:   managed-скиллы без изменений
    - conflicts: name'ы из add, чей путь занят ЧУЖИМ скиллом (не managed) — symlink/
                 каталог/файл, который мы не ставили. sync без force их пропускает.
    Чужие (managed!=true) записи в расчёте удаления НЕ участвуют."""
    entries, skipped = resolve_skillset(env, cfg, include_core=include_core)
    skills_path = cfg.get("skills_path") or DEFAULT_SKILLS_PATH
    dest_root = Path(target) / skills_path
    lock = load_lock(target)
    lock_problem = _lock_problem(target)
    locked = (lock.get("skills", {}) if provider == "claude-code"
              else lock.get("providers", {}).get(provider, {}))

    desired = {e["name"]: e for e in entries}
    managed_locked = {n: e for n, e in locked.items() if e.get("managed")}

    add, update, managed_drift, keep, conflicts, conflicts_likely_ours = [], [], [], [], [], []
    drift_hashes = {}
    for name, entry in desired.items():
        dst = dest_root / name
        prev = managed_locked.get(name)
        if prev is None:
            # новый для нас; если путь занят чужим (не managed) — конфликт. НЕ авто-
            # усыновляем даже при совпадении sha256 (V-6): осознанная "ручная чистка
            # lock + живая папка" (test_manual_lock_cleanup_*) тоже даёт точное
            # совпадение содержимого, но требует --force — предохранитель против
            # случайного поглощения чужого. Отличаем в СООБЩЕНИИ (см. sync_skillset):
            # совпадающий sha256 → скорее прерванный прошлый sync (--force безопасен),
            # несовпадающий → правда чужой скилл.
            if dst.is_symlink() or dst.exists():
                conflicts.append(name)
                if not dst.is_symlink() and dst.is_dir() \
                        and _dir_sha256(dst) == entry["sha256"]:
                    conflicts_likely_ours.append(name)
            else:
                add.append(name)
        elif prev.get("installed_path") and prev["installed_path"] != f"{skills_path}/{name}":
            # A configured target-path move is a managed relocation, not drift in
            # the old managed bytes. The old location is pruned via ``relocated``.
            add.append(name)
        elif not dst.is_dir() or dst.is_symlink():
            managed_drift.append(name)
            drift_hashes[name] = {
                "observed": _hash_label(""),
                "expected": _hash_label(prev.get("sha256", "")),
                "source": _hash_label(entry["sha256"]),
            }
        elif _dir_sha256(dst) != prev.get("sha256"):
            # Managed bytes are classified before canonical source/content changes:
            # ordinary sync must never overwrite a local edit incidentally.
            managed_drift.append(name)
            drift_hashes[name] = {
                "observed": _hash_label(_dir_sha256(dst)),
                "expected": _hash_label(prev.get("sha256", "")),
                "source": _hash_label(entry["sha256"]),
            }
        elif prev.get("sha256") != entry["sha256"]:
            update.append(name)
        elif (prev.get("content_sha256")
              and prev.get("content_sha256") != entry.get("content_sha256", "")):
            # дрейф в snippets/references при неизменном SKILL.md. Гард на наличие
            # ключа в локе → старые локи (без content_sha256) не дают ложный update.
            update.append(name)
        else:
            keep.append(name)
    remove = [n for n in managed_locked if n not in desired]
    # V-9: managed-запись, чей installed_path (лок) НЕ совпадает с ТЕКУЩИМ skills_path
    # (конфиг сменил skills_path) — копия по старому пути осиротеет, если её не
    # прунить отдельно от обычного remove (remove бьёт только по «выпало из конфига»,
    # а этот скилл может остаться desired — просто переезжает). {name: старый rel-путь}.
    relocated = {n: e["installed_path"] for n, e in managed_locked.items()
                if e.get("installed_path") and e["installed_path"] != f"{skills_path}/{n}"}
    return {
        "add": sorted(add), "update": sorted(update),
        "managed_drift": sorted(managed_drift),
        "drift_hashes": drift_hashes,
        "remove": sorted(remove), "keep": sorted(keep),
        "conflicts": sorted(conflicts),
        "conflicts_likely_ours": sorted(conflicts_likely_ours),
        "relocated": relocated,
        "skipped": skipped, "skills_path": skills_path,
        "entries": entries, "dest_root": dest_root,
        "provenance_invalid": lock_problem,
    }


def _remove_path(path):
    """Снести каталог/файл/симлинк по пути (симлинк не разыменовываем)."""
    if path.is_symlink() or path.is_file():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)


def sync_skillset(env, target, cfg, dry_run=False, force=False, repair=False,
                  include_core=False, provider="claude-code", plan=None):
    """Применить конфиг: скопировать новые/обновлённые, удалить выбывшие managed,
    переписать skills-lock.json. Чужие скиллы остаются как есть (конфликты
    пропускаются с warning; --force перетирает чужой путь нашим скиллом).
    include_core=True — раздать CORE_SKILLS по умолчанию (как vendor/connect)."""
    if plan is None:
        plan = plan_sync(env, target, cfg, include_core=include_core, provider=provider)
    if plan.get("provenance_invalid"):
        die(f"SPUB_OWNERSHIP_CONFLICT: provider {provider} channel vendor "
            f"target {plan['skills_path']} has invalid skills-lock provenance "
            f"({plan['provenance_invalid']}); repair: restore a valid lock backup")
    if plan.get("managed_drift") and not repair:
        names = ", ".join(plan["managed_drift"])
        die(f"SPUB_OWNERSHIP_CONFLICT: provider {provider} channel vendor "
            f"target {plan['skills_path']} has managed-drift: {names}; "
            "repair: rerun `skiller sync --repair`")
    dest_root = plan["dest_root"]
    entries = {e["name"]: e for e in plan["entries"]}
    lock = load_lock(target)
    locked = dict(lock.get("skills", {}) if provider == "claude-code"
                  else lock.get("providers", {}).get(provider, {}))

    def contained(path):
        return is_within(path, dest_root)

    # Конфликты с чужими путями: без force — пропуск; с force — добавить к install.
    install = list(plan["add"]) + list(plan["update"])
    if repair:
        install += list(plan.get("managed_drift", []))
    if plan["conflicts"]:
        if force:
            install += plan["conflicts"]
        else:
            likely_ours = set(plan.get("conflicts_likely_ours", []))
            for name in plan["conflicts"]:
                if name in likely_ours:
                    # sha256 совпадает с реестром: скорее прерванный прошлый sync
                    # (файлы скопированы, lock не успел записаться — V-6), а не
                    # правда чужой скилл. НЕ авто-усыновляем (см. plan_sync) — но
                    # сообщение не должно пугать «чужим», когда это, вероятно, наше.
                    warn(f"конфликт: '{name}' — папка уже содержит идентичное "
                         f"содержимое (sha256 совпадает с реестром), но не в lock — "
                         f"похоже на прерванный прошлый sync; --force безопасно "
                         f"пере-усыновит")
                else:
                    warn(f"конфликт: '{name}' занят чужим скиллом (не managed) — "
                         f"пропуск; --force чтобы заменить версией из библиотеки")

    # --- prune: только managed, выбывшие из конфига ---------------------------
    for name in plan["remove"]:
        stale = dest_root / name
        if dry_run:
            print(f"[dry-run] remove {stale}")
        elif (stale.is_symlink() or stale.exists()) and contained(stale):
            _remove_path(stale)
        locked.pop(name, None)

    # --- prune: осиротевшие копии по СТАРОМУ skills_path (V-9) -----------------
    # Конфиг сменил skills_path — managed-запись (по installed_path в локе) может
    # указывать на путь ВНЕ текущего dest_root. Без этого прохода такие копии никогда
    # не удаляются: обычный remove-цикл выше бьёт только по dest_root/name (новому
    # пути), а install-цикл ниже просто создаст ВТОРУЮ копию на новом месте.
    target_root = Path(target)
    for old_rel_path in plan.get("relocated", {}).values():
        stale = target_root / old_rel_path
        if dry_run:
            print(f"[dry-run] remove (relocated) {stale}")
        elif (stale.is_symlink() or stale.exists()) and is_within(stale, target_root):
            _remove_path(stale)

    # --- install / update -----------------------------------------------------
    if not dry_run:
        dest_root.mkdir(parents=True, exist_ok=True)
    installed_names, skip_copy, repair_evidence, pending_backups = [], [], [], {}
    for name in install:
        entry = entries[name]
        src = entry["skill_dir"]
        dst = dest_root / name
        if dry_run:
            verb = "add" if name in plan["add"] else \
                ("replace" if name in plan["conflicts"] else "update")
            print(f"[dry-run] {verb} {entry['bucket']}/{entry['name']} -> {dst}")
            continue
        if name in plan.get("managed_drift", []):
            skill_file = dst / "SKILL.md"
            expected_observed = plan["drift_hashes"][name]["observed"]
            if _hash_label(_dir_sha256(dst)) != expected_observed:
                die(f"SPUB_OWNERSHIP_CONFLICT: provider {provider} channel vendor "
                    f"target {plan['skills_path']}/{name} changed after planning; "
                    "repair: replan before `skiller sync --repair`")
            if expected_observed == _hash_label(""):
                # Managed skill VANISHED from the project (dir deleted, or replaced by a
                # symlink): drift is classified at plan time by `not dst.is_dir()`, and
                # there are no local bytes to preserve. Demanding a pre-image here made
                # the ONLY repair path for a deleted managed skill unreachable — repair
                # died instead of restoring it. Nothing to back up is not a conflict.
                pass
            elif not skill_file.is_file():
                die(f"SPUB_OWNERSHIP_CONFLICT: provider {provider} channel vendor "
                    f"target {plan['skills_path']}/{name} has no recoverable pre-image")
            else:
                # safe_copy_skill replaces the directory, so preserve the exact bytes
                # immediately beside it until the new directory exists. Then move this
                # pending file to the P2-standard final backup path beside SKILL.md.
                pending = dst.parent / f".{name}.provider-artifact.bak.pending"
                shutil.copy2(skill_file, pending)
                pending_backups[name] = pending
        # Единый безопасный copy (containment + снятие symlink/файла/каталога + TOCTOU-
        # перепроверка + SKILL_IGNORE) — общий с vendor.copy_skill (не разъезжаться).
        # Пропуск (containment-стоп/TOCTOU-гонка, уже warn'ится внутри) — не тихий:
        # попадает в skip_copy, отчёт печатает ФАКТ (installed_names), не план (V-2).
        if not safe_copy_skill(src, dst, dest_root):
            skip_copy.append(name)
            continue
        installed_names.append(name)
        if name in plan.get("managed_drift", []):
            if _dir_sha256(dst) != entry["sha256"]:
                die(f"SPUB_OWNERSHIP_CONFLICT: provider {provider} channel vendor "
                    f"target {plan['skills_path']}/{name} repair bytes failed verification")
            if name in pending_backups:  # отсутствует у восстановления удалённого скилла
                pending_backups[name].replace(
                    (dst / "SKILL.md").with_name("SKILL.md.provider-artifact.bak"))
            repair_evidence.append({"name": name, **plan["drift_hashes"][name]})
        locked[name] = {
            "source": SOURCE,
            "managed": True,
            "bucket": entry["bucket"],
            "sha256": _dir_sha256(dst),
            # content_sha256 — из реестра (хеш ИСТОЧНИКА): копия отличается игнорами,
            # поэтому хешируем источник, а не dst (иначе ложный дрейф каждый sync).
            "content_sha256": entry.get("content_sha256", ""),
            "installed_path": f"{plan['skills_path']}/{name}",
        }

    # keep: освежить метаданные на случай ручной правки lock (и доpopulation
    # content_sha256 в старых локах — без перекопирования неизменённых скиллов)
    for name in plan["keep"]:
        entry = entries[name]
        locked.setdefault(name, {})
        locked[name].update({
            "source": SOURCE, "managed": True, "bucket": entry["bucket"],
            "sha256": entry["sha256"],
            "content_sha256": entry.get("content_sha256", ""),
            "installed_path": f"{plan['skills_path']}/{name}",
        })

    new_lock = dict(lock)
    new_lock["version"] = lock.get("version", LOCK_VERSION)
    if provider == "claude-code":
        new_lock["skills"] = dict(sorted(locked.items()))
    else:
        providers = dict(lock.get("providers", {}))
        providers[provider] = dict(sorted(locked.items()))
        new_lock["providers"] = dict(sorted(providers.items()))
    new_lock["sources"] = {**lock.get("sources", {}),
                           SOURCE: {"ref": "registry", "mode": "vendor"}}
    if not dry_run:
        # Порядок НАМЕРЕННЫЙ: skills-lock.json — источник истины детекта (plan_sync читает
        # load_lock, НЕ манифест), поэтому пишем его авторитетно ПОСЛЕ того, как файлы уже на
        # диске (copytree выше). Манифест — производная (контракт реинсталла/индекс для hub),
        # регенерится каждый успешный sync. Краш после lock, до манифеста → детект на след.
        # sync корректен (по lock), манифест добьётся. (Не переставлять: манифест-первым сделал
        # бы lock устаревшим при краше и сломал бы детект.)
        write_lock(target, new_lock)
        for evidence in repair_evidence:
            name = evidence["name"]
            if (_dir_sha256(dest_root / name) != entries[name]["sha256"]
                    or locked.get(name, {}).get("sha256") != entries[name]["sha256"]):
                die(f"SPUB_OWNERSHIP_CONFLICT: provider {provider} channel vendor "
                    f"target {plan['skills_path']}/{name} repair lock verification failed")
        _write_manifest(target, plan["skills_path"], locked,
                        entries, cfg)
        # gitignore_managed: держать managed-скиллы вне git (воспроизводимы sync),
        # локальные/кастомные — в репо. Список авто-сопровождается каждым sync.
        if cfg.get("gitignore_managed"):
            _write_gitignore(target, plan["skills_path"], locked)
        else:
            _remove_our_gitignore(target, plan["skills_path"])
    # Факт (что реально скопировано/пропущено) отдельно от плана (plan["add"/"update"]) —
    # do_sync/cmd_sync репортят по installed/skip_copy, а не по плану (V-2).
    plan["installed"] = installed_names
    plan["skip_copy"] = skip_copy
    plan["repair_evidence"] = repair_evidence
    return plan


def _write_gitignore(target, skills_path, locked):
    """gitignore_managed: эмитим `<skills_path>/.gitignore` со списком ТОЛЬКО
    managed-скиллов (воспроизводимы `skiller sync`). Корневой `.gitignore` НЕ трогаем
    (изоляция + авто-сопровождение). Локальные/кастомные скиллы здесь не перечислены
    → остаются в репозитории; манифест/lock/сам .gitignore тоже видимы (не skill-dir)."""
    dest_root = Path(target) / skills_path
    if not dest_root.is_dir():
        return
    managed = sorted(n for n, e in locked.items() if e.get("managed"))
    lines = [
        GITIGNORE_HEADER,
        "# Managed swissknifeman-скиллы держим ВНЕ git — они воспроизводимы:",
        "#   skiller sync   (из .swissknifeman/config.json + skills-lock.json)",
        "# Локальные/кастомные скиллы здесь НЕ перечислены → остаются в репозитории.",
        "",
    ] + [f"/{n}/" for n in managed]
    atomic_write_text(dest_root / ".gitignore", "\n".join(lines) + "\n")


def _remove_our_gitignore(target, skills_path):
    """gitignore_managed выключен → убрать ранее сгенерированный НАМИ `.gitignore`
    (опознаём по заголовку), чтобы managed-скиллы снова коммитились. Чужой .gitignore
    не трогаем."""
    gi = Path(target) / skills_path / ".gitignore"
    try:
        if gi.is_file() and gi.read_text(encoding="utf-8").startswith(GITIGNORE_HEADER):
            gi.unlink()
    except OSError:
        pass


def _write_manifest(target, skills_path, locked, entries, cfg):
    """Манифест .swissknifeman-manifest.json в skills_path — контракт для
    переустановки (vendor) и источник для generate-hub.sh (индекс скиллов).
    Раскладка sync всегда flat: <skills_path>/<name>/SKILL.md. Перечисляем
    все managed-скиллы, фактически установленные после операции. Writer —
    common.write_skill_manifest, общий с vendor.py (V-4)."""
    dest_root = Path(target) / skills_path
    if not dest_root.is_dir():
        return
    installed = []
    for name in sorted(locked):
        entry = entries.get(name)
        if not entry:
            continue  # managed-запись без entry в реестре — не индексируем
        installed.append({
            "flat_name": name,
            "source_path": str(Path(entry["path"]).parent),
        })
    write_skill_manifest(dest_root / MANIFEST, profile=cfg.get("project_type", ""),
                         agent=cfg.get("agent", "claude"), layout="flat",
                         installed=installed)


# --- config materialization (общая для init и do_sync) ------------------------
def materialize_skillset_config(env, target, opts, dry=False, force=False, quiet=False):
    """Вернуть конфиг vendor-режима; создать `.swissknifeman/config.json` из
    профиля проекта, если его ещё нет (force=True — пересоздать из автодетекта).

    Существующий курированный конфиг уважается (force=False → читаем как есть, не
    перетираем). ЕДИНАЯ точка материализации для `cmd_init` и `do_sync` — чтобы
    набор по умолчанию не разъезжался между «создать конфиг» и «синкнуть».
    Возвращает (cfg, profile_name, created): created=True, если файл записан."""
    cfg_path = skillset_config_path(target)
    if cfg_path.is_file() and not force:
        cfg = load_skillset_config(target)
        return cfg, (cfg.get("project_type") or ""), False
    legacy = load_config(env, target)
    buckets, profile_name, _psrc, source, _meta = resolve_selection(
        env, target, legacy, opts.get("profile", ""), [])
    cfg = {"version": LOCK_VERSION, "mode": "vendor", "agent": "claude",
           "buckets": list(buckets), "include": [], "exclude": []}
    if not dry:
        cfg_path.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_json(cfg_path, cfg, version=LOCK_VERSION)
    if not quiet:
        print(("[dry-run] " if dry else "")
              + f"конфиг vendor-режима: {CONFIG_DIR}/{CONFIG_FILE} "
              f"(mode=vendor, buckets: {' '.join(buckets) or '-'})")
    if source == "autodetect-fallback" and not quiet:
        print("⚠ тип проекта не распознан — материализовано МИНИМАЛЬНОЕ ядро;\n"
              "  для оптимального набора укажи профиль: --profile <type>")
    return cfg, profile_name, True


def _sync_report_counts(plan, dry_run, force):
    """(add, update, repl, skip) для отчёта sync. При dry-run план ничего не
    применял — план и есть факт. Иначе считаем по ФАКТУ (plan['installed']), а не
    по плану (plan['add']/['update']): safe_copy_skill мог пропустить часть install
    из-за containment-стопа/TOCTOU-гонки — отчёт не должен рапортовать план как
    сделанную работу (V-2)."""
    if dry_run:
        return (len(plan["add"]), len(plan["update"]),
                len(plan["conflicts"]) if force else 0, 0)
    installed = set(plan.get("installed", []))
    add = sum(1 for n in plan["add"] if n in installed)
    upd = sum(1 for n in plan["update"] if n in installed)
    repl = sum(1 for n in plan["conflicts"] if n in installed) if force else 0
    return add, upd, repl, len(plan.get("skip_copy", []))


# --- integrate/onboard entry (vendor-канал «опубликовать в репо») -------------
def _do_sync_provider(env, target, opts, register=True, plan=None):
    """Vendor-канал через sync: «опубликовать» скиллы физически в .claude/skills/.

    Это путь для проектов, которые отдают сторонним разработчикам БЕЗ доступа к
    реестру swissknifeman: файлы скиллов коммитятся в репо проекта (в отличие от
    connect, где скиллы живут плагинами в реестре). Материализует
    .swissknifeman/config.json из профиля проекта, если конфига ещё нет; уже
    существующий курированный конфиг уважается (не перетираем). Паритет с
    connect/do_vendor: permissions-пресеты, hub, регистрация (channel=vendor)."""
    dry = opts.get("dry_run", False)
    force = opts.get("force", False)
    repair = opts.get("repair", False)
    no_core = opts.get("no_core", False)

    provider = opts.get("provider", "claude-code")
    cfg, profile_name, _created = materialize_skillset_config(
        env, target, opts, dry=dry)
    if provider == "codex":
        cfg = {**cfg, "skills_path": ".agents/skills", "agent": "codex"}

    plan = sync_skillset(env, target, cfg, dry_run=dry, force=force, repair=repair,
                         include_core=not no_core, provider=provider, plan=plan)
    n_add, n_upd, _n_repl, n_skip = _sync_report_counts(plan, dry, force)
    print(("[dry-run] " if dry else "")
          + f"sync: +{n_add} ~{n_upd} "
          f"-{len(plan['remove'])} ={len(plan['keep'])} "
          f"(skills_path: {plan['skills_path']})")
    if plan["conflicts"] and not force:
        print(f"  конфликты (чужие, пропущены): {', '.join(plan['conflicts'])} "
              "— --force чтобы заменить")
    if plan["skipped"]:
        print(f"  пропущено (нет в реестре): {', '.join(plan['skipped'])}")
    if n_skip:
        print(f"  ПРОПУЩЕНО при копировании ({n_skip}): "
              f"{', '.join(plan['skip_copy'])} — см. предупреждения выше, "
              f"sync для них НЕ завершён")
        die(f"SPUB_OWNERSHIP_CONFLICT: provider {provider} vendor apply incomplete; "
            "repair: resolve the target conflict and rerun `skiller sync`")
    for evidence in plan.get("repair_evidence", []):
        print(f"  repair {evidence['name']}: observed={evidence['observed']} "
              f"expected={evidence['expected']} source={evidence['source']}")

    # permissions-пресеты (deny мусора + allow стека) — паритет с connect/do_vendor
    if provider == "claude-code" and not opts.get("no_permissions"):
        apply_permissions(env, target, dry_run=dry)

    if opts.get("hub") and not dry:
        generate_hub(env, target)

    record = {
        "path": str(target),
        "channel": "vendor",
        "profile": profile_name,
        "agent": "codex" if provider == "codex" else "claude",
        "skills_path": plan["skills_path"],
        "provider": provider,
        "hub": opts.get("hub") or hub_artifacts_exist(target),
    }
    if plan.get("repair_evidence"):
        record["repair"] = plan["repair_evidence"]
    if register and not dry:
        upsert_project(env, record)
    return record


def do_sync(env, target, opts, register=True):
    """Build every selected provider plan before the first managed write."""
    from .config import load_config
    from .publication import build_vendor_distribution_plan
    config = load_config(env, target)
    # Derive a missing vendor config in memory first.  An aggregate ownership,
    # drift or provenance refusal must not leave config materialisation behind.
    preflight_cfg, _profile, _created = materialize_skillset_config(
        env, target, opts, dry=True, quiet=True)
    paths = build_vendor_distribution_plan(
        config, target, project_id=target.name,
        claude_path=preflight_cfg.get("skills_path") or DEFAULT_SKILLS_PATH,
        codex_path=".agents/skills")
    provider_ids = opts.get("provider_ids")
    if provider_ids is not None:
        provider_ids = frozenset(provider_ids)
        paths = tuple(path for path in paths if path.provider_id in provider_ids)
    lock_problem = _lock_problem(target)
    if lock_problem:
        providers = ", ".join(descriptor.provider_id for descriptor in paths) or "none"
        targets = ", ".join(descriptor.target.relative_to(target).as_posix()
                            for descriptor in paths) or "-"
        die(f"SPUB_OWNERSHIP_CONFLICT: provider {providers} channel vendor "
            f"target {targets} has invalid skills-lock provenance ({lock_problem}); "
            "repair: restore a valid lock backup")
    planned = []
    for descriptor in paths:
        provider = descriptor.provider_id
        provider_cfg = ({**preflight_cfg, "skills_path": ".agents/skills", "agent": "codex"}
                        if provider == "codex" else preflight_cfg)
        # The immutable copy plan is calculated for every selected provider
        # before applying any of them.  A later provider conflict therefore
        # cannot turn the earlier provider into a misleading partial success.
        planned.append((provider, plan_sync(
            env, target, provider_cfg, include_core=not opts.get("no_core", False),
            provider=provider)))

    # A selected provider's unmanaged target is an aggregate preflight failure:
    # applying Claude first and silently skipping Codex would report a misleading
    # dual-provider success.  ``--force`` remains the explicit, existing escape
    # hatch for the owner of that target.
    for provider, plan in planned:
        if plan.get("provenance_invalid"):
            die(f"SPUB_OWNERSHIP_CONFLICT: provider {provider} channel vendor "
                f"target {plan['skills_path']} has invalid skills-lock provenance "
                f"({plan['provenance_invalid']}); repair: restore a valid lock backup")
        if plan["conflicts"] and not opts.get("force", False):
            conflicts = ", ".join(plan["conflicts"])
            die(f"SPUB_OWNERSHIP_CONFLICT: provider {provider} channel vendor "
                f"target {plan['skills_path']} has unmanaged conflicts: {conflicts}; "
                "repair: resolve the target conflict or rerun `skiller sync --force`")
        if plan.get("managed_drift") and not opts.get("repair", False):
            drifts = ", ".join(plan["managed_drift"])
            die(f"SPUB_OWNERSHIP_CONFLICT: provider {provider} channel vendor "
                f"target {plan['skills_path']} has managed-drift: {drifts}; "
                "repair: rerun `skiller sync --repair`")

    # Only a clean aggregate plan is allowed to materialise the project config.
    base_cfg, _profile, _created = materialize_skillset_config(
        env, target, opts, dry=opts.get("dry_run", False))
    records = [_do_sync_provider(env, target, {**opts, "provider": provider},
                                 register=register, plan=plan)
               for provider, plan in planned]
    return records[0] if len(records) == 1 else {"providers": records}


# --- CLI ----------------------------------------------------------------------
def cmd_init(env, argv):
    """Создать `.swissknifeman/config.json` (mode=vendor) — без копирования скиллов.

    Парадная, идемпотентная дверь «дай мне конфиг»: автодетект типа проекта +
    профиль → buckets. Копирование делает `skiller sync`. Раньше конфиг
    материализовался только как побочный эффект `sync`/`integrate`."""
    opts = parse_flags(argv, {"--target": "str", "--profile": "str",
                              "--force": "bool", "--dry-run": "bool"})
    if opts["help"]:
        print("skiller init [--target DIR] [--profile TYPE] [--force] [--dry-run]\n"
              "  Создаёт .swissknifeman/config.json (mode=vendor) из автодетекта "
              "типа проекта и профиля —\n"
              "  БЕЗ копирования скиллов (это делает skiller sync). Существующий "
              "конфиг не перетирается без --force.")
        return
    target, via = resolve_target(env, opts, allow_home_confirm=True)
    cfg_path = skillset_config_path(target)
    if cfg_path.is_file() and not opts["force"]:
        print(f"✓ {CONFIG_DIR}/{CONFIG_FILE} уже есть ({via}) — не трогаю "
              "(--force пересоздаёт). Дальше: skiller sync")
        return
    _cfg, profile_name, _created = materialize_skillset_config(
        env, target, opts, dry=opts["dry_run"], force=True)
    if not opts["dry_run"]:
        print(f"  профиль: {profile_name or '-'}. Отредактируй "
              "include/buckets/exclude и примени: skiller sync")


def cmd_sync(env, argv):
    opts = parse_flags(argv, {"--target": "str", "--dry-run": "bool",
                              "--force": "bool", "--hub": "bool",
                              "--no-hub": "bool", "--no-core": "bool",
                              "--repair": "bool"})
    if opts["help"]:
        print("skiller sync [--target DIR] [--dry-run] [--force] [--repair] "
              "[--hub] [--no-hub] [--no-core]\n"
              "  Применяет .swissknifeman/config.json (mode=vendor): копирует "
              "скиллы из библиотеки в проект, пишет skills-lock.json (managed),\n"
              "  манифест .swissknifeman-manifest.json и удаляет выбывшие "
              "managed-скиллы. Чужие скиллы не трогает (--force перетирает\n"
              "  занятый чужой путь версией из библиотеки); --repair восстанавливает\n"
              "  только подтверждённый managed-drift с recoverable pre-image. CORE-скиллы "
              "раздаются по умолчанию (--no-core отключает). Индекс скиллов\n"
              "  (managed-блок CLAUDE.md / .ai/guidelines) обновляется, если он "
              "уже есть в проекте или передан --hub; --no-hub отключает.")
        return
    target, via = resolve_target(env, opts, allow_home_confirm=True)
    cfg = load_skillset_config(target)
    if cfg is None:
        die(f"{skillset_config_path(target)} не найден — создайте конфиг "
            "vendor-режима (mode=vendor, include/buckets/exclude)")

    # Индекс скиллов в корне проекта: догоняем поведение vendor — обновляем,
    # если хаб уже есть или запрошен явно. --no-hub перебивает автоопределение.
    want_hub = opts["hub"] or (hub_artifacts_exist(target)
                               and not opts["no_hub"])
    do_sync(env, target, {**opts, "hub": want_hub})
