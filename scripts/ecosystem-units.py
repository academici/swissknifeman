def cell(value) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ") if value not in (None, "") else "-"


def current_module(path: str) -> str:
    parts = path.split("/")
    if parts[0] == BRIDGES_DIR and len(parts) > 2:
        return f"{BRIDGES_DIR}/{parts[1]}"
    return parts[1] if parts[0] == "packages" and len(parts) > 2 else f"{parts[0]} (hub root)"


def render_ownership(ctx: Context) -> str:
    aliases = ctx.config.get("module_aliases") or {}
    lines = [
        "<!-- generated by scripts/ecosystem-units.py render; do not edit -->",
        "# Module ownership map",
        "",
        "> Generated by `scripts/ecosystem-units.py render` from `configs/ecosystem-units.json` and the `unit.json`",
        "> files; do not edit by hand. CI runs `render --check`.",
        "",
        "## Modules",
        "",
        "| id | kind | version | destination | stability | requires |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for folder, unit in sorted(load_units(ctx).items()):
        doc = unit.doc if isinstance(unit.doc, dict) else {}
        name = doc.get("id", folder)
        if folder in aliases:
            name = f"{name} (renamed to {aliases[folder]})"
        requires = ", ".join(str(r.get("unit")) for r in doc.get("requires") or () if isinstance(r, dict))
        lines.append("| " + " | ".join(cell(v) for v in (name, doc.get("kind"), doc.get("version"),
                                                         doc.get("destination"), doc.get("stability"), requires)) + " |")
    lines += [
        "",
        "## Ownership map",
        "",
        "Files that move to another module. A path ending with `/` is a directory; the longest matching entry wins. "
        "Files of a module without an entry stay in that module; hub files without an entry stay in the hub. "
        "`hypothesis` means the owning phase confirms or changes the entry when it reads the code.",
        "",
        "| path | current module | target | subsystem | phase | confidence | note |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]

    def order(entry):
        return int(entry["phase"][1:]), entry["path"]

    entries = [e for e in ctx.config.get("ownership") or () if isinstance(e, dict)
               and isinstance(e.get("path"), str) and isinstance(e.get("phase"), str) and PHASE.match(e["phase"])]
    for entry in sorted(entries, key=order):
        lines.append("| " + " | ".join([f"`{entry['path']}`", cell(current_module(entry["path"]))] + [
            cell(entry.get(k)) for k in ("target", "subsystem", "phase", "confidence", "note")]) + " |")
    return "\n".join(lines) + "\n"


