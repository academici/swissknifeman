class SchemaCase(unittest.TestCase):
    def test_the_spec_and_the_schema_name_the_same_keys(self):
        schema = load_module_schema(hooks_env.SCHEMA_FILE, "harness")
        for hook, keys in hooks_env.HOOK_KEYS.items():
            for key, kind in keys.items():
                self.assertEqual(schema.leaf(f"hooks.{hook}.{key}").type, kind)
                self.assertEqual(schema.leaf(f"hooks.{hook}.providers.cursor.{key}").type, kind)
        self.assertEqual({key[1] for key in schema.leaves if key[0] == "hooks"}, set(hooks_env.HOOK_KEYS))

    def test_enums_match_the_flag_values_of_the_writers(self):
        schema = load_module_schema(hooks_env.SCHEMA_FILE, "harness")

        def enum(hook, key):
            return tuple(schema.leaf(f"hooks.{hook}.{key}").node["enum"])
        self.assertEqual(enum("auto_approve", "mode"), hooks.AA_MODES)
        self.assertEqual(enum("memory", "mode"), hooks.MEM_MODES)
        self.assertEqual(enum("agent_router", "policy"), hooks.ROUTER_MODES)
        self.assertEqual(enum("run_report", "enabled"), hooks.RUNREPORT_MODES)
        self.assertEqual(enum("plan_regen", "mode"), hooks.PLANREGEN_MODES)
        for hook in ("pack_guard", "plan_guard", "changelog_gate", "review_gate", "git_guardrails"):
            self.assertEqual(enum(hook, "mode"), hooks.PACKGUARD_MODES)

    def test_example_is_generated_hook_keys_allow_machine_defaults_and_the_policy_stays_in_the_project(self):
        schema = load_module_schema(hooks_env.SCHEMA_FILE, "harness")
        for key, leaf in schema.leaves.items():
            expected = ["defaults", "machine", "project"] if key[0] == "hooks" else ["defaults", "project"]
            self.assertEqual(leaf.node["x-skm-layers"], expected, key)
        self.assertTrue((PKG / "config.example.toml").is_file())
        unit = json.loads((PKG / "unit.json").read_text(encoding="utf-8"))
        self.assertEqual(unit["provides"]["config"], "configs/config.schema.json")


