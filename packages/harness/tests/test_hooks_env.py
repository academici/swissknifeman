class ShowSyncCase(Base):
    def test_workspace_hook_settings_are_rendered_without_machine_defaults(self):
        home = self.tmp / "home"
        local = (home / ".local/share/swissknifeman/workspaces/axioma/projects/tenant/local")
        local.mkdir(parents=True)
        local.joinpath("config.toml").write_text(
            'schema_version = 1\n[harness.hooks.memory]\nmode = "manual"\n', encoding="utf-8")
        machine = home / ".local/share/swissknifeman/config/config.toml"
        machine.parent.mkdir(parents=True)
        machine.write_text('schema_version = 1\n[harness.hooks.auto_approve]\nmode = "bypass"\n',
                           encoding="utf-8")
        self.config.parent.mkdir(parents=True)
        self.config.write_text('schema_version = 1\n[harness.hooks.memory]\nmode = "off"\n',
                               encoding="utf-8")
        self.config.with_name("project.json").write_text(json.dumps({
            "workspace": "axioma", "project_id": "tenant", "plans_store": "workspace"}),
            encoding="utf-8")
        with patch("pathlib.Path.home", return_value=home):
            run("sync", "--target", str(self.proj))
            state = self.show()
        self.assertEqual(self.carrier_lines()[1:], ["MEMORY_MODE=manual"])
        self.assertEqual(state["settings"], {"hooks": {"memory": {"mode": "manual"}}})
        self.assertFalse(state["stale"])

    def contract(self):
        return load_contract(PKG / "schemas" / "hooks-state" / "v1", urn_prefix="urn:swissknifeman:harness:",
                             foundation=FOUNDATION)

    def show(self):
        return json.loads(run("show", "--target", str(self.proj), "--json"))

    def test_show_output_matches_the_contract_in_every_state(self):
        registry, kind = self.contract()
        empty = self.show()
        self.assertEqual(validate(empty, kind, registry), [])
        self.assertEqual((empty["settings"], empty["hooks_env"], empty["legacy"], empty["stale"]),
                         ({}, {}, [], False))
        run("--target", str(self.proj), "--pack-guard", "strict", "--memory", "file")
        (self.proj / ".claude" / "memory.env.ini").write_text("MODE=off\n", encoding="utf-8")
        state = self.show()
        self.assertEqual(validate(state, kind, registry), [])
        self.assertEqual(state["settings"]["hooks"]["pack_guard"], {"mode": "strict"})
        self.assertEqual(state["hooks_env"]["PACK_GUARD_MODE"], "strict")
        self.assertEqual(state["legacy"], [str(self.proj / ".claude" / "memory.env.ini")])
        self.assertFalse(state["stale"])

    def test_sync_regenerates_a_stale_carrier_and_is_idempotent(self):
        self.config.parent.mkdir(parents=True)
        self.config.write_text("schema_version = 1\n[harness.hooks.review_gate]\nmode = \"warn\"\n",
                               encoding="utf-8")
        self.assertFalse(self.carrier.exists())
        self.assertTrue(self.show()["stale"])
        run("sync", "--target", str(self.proj), "--dry-run")
        self.assertFalse(self.carrier.exists())
        run("sync", "--target", str(self.proj))
        self.assertEqual(self.carrier_lines()[1:], ["REVIEW_GATE_MODE=warn"])
        self.assertFalse(self.show()["stale"])
        before = self.carrier.stat().st_mtime_ns
        self.assertIn("up to date", run("sync", "--target", str(self.proj)))
        self.assertEqual(self.carrier.stat().st_mtime_ns, before)
        self.carrier.write_text(self.carrier.read_text() + "REVIEW_GATE_MODE__CURSOR=off\n", encoding="utf-8")
        self.assertTrue(self.show()["stale"])
        run("sync", "--target", str(self.proj))
        self.assertNotIn("REVIEW_GATE_MODE__CURSOR=off", self.carrier_lines())

    def test_sync_without_modes_and_without_a_carrier_writes_nothing(self):
        out = run("sync", "--target", str(self.proj))
        self.assertIn("nothing to write", out)
        self.assertFalse(self.carrier.exists())

    def test_the_carrier_follows_the_configuration_after_the_keys_are_removed(self):
        self.config.parent.mkdir(parents=True)
        self.config.write_text("schema_version = 1\n[harness.hooks.review_gate]\nmode = \"warn\"\n",
                               encoding="utf-8")
        run("sync", "--target", str(self.proj))
        self.config.write_text("schema_version = 1\n", encoding="utf-8")
        run("sync", "--target", str(self.proj))
        self.assertEqual(len(self.carrier_lines()), 1)

    def _machine_layer(self, text):
        machine = self.tmp / "skm" / "config" / "config.toml"
        machine.parent.mkdir(parents=True, exist_ok=True)
        machine.write_text(text, encoding="utf-8")
        return dict(os.environ, SKM_HOME=str(self.tmp / "skm"))

    def test_a_machine_layer_key_does_not_break_show_or_the_policy_profile(self):
        env = self._machine_layer("schema_version = 1\n[harness.hooks.pack_guard]\nmode = \"strict\"\n"
                                  "[harness.hooks.pack_guard.providers.cursor]\nmode = \"off\"\n")
        self.config.parent.mkdir(parents=True)
        self.config.write_text("schema_version = 1\n[harness]\npolicy_profile = \"base\"\n", encoding="utf-8")
        with _patched_env(env):
            document = self.show()
            from harness import settings_audit
            self.assertEqual(settings_audit.read_policy_declaration(self.proj), "base")
        self.assertEqual(document["settings"], {"policy_profile": "base"})

    def test_sync_renders_only_keys_set_in_the_project_file(self):
        env = self._machine_layer("schema_version = 1\n[harness.hooks.pack_guard]\nmode = \"strict\"\n")
        self.config.parent.mkdir(parents=True)
        self.config.write_text("schema_version = 1\n[harness.hooks.review_gate]\nmode = \"warn\"\n",
                               encoding="utf-8")
        with _patched_env(env):
            run("sync", "--target", str(self.proj))
            stale = self.show()["stale"]
        lines = self.carrier_lines()
        self.assertEqual([l for l in lines if not l.startswith("#")], ["REVIEW_GATE_MODE=warn"])
        self.assertFalse(stale)

    def test_the_launcher_runs_the_new_subcommands(self):
        env = dict(os.environ, HOME=str(self.tmp), SKM_HOME=str(self.tmp / "skm"),
                   PYTHONPATH=os.pathsep.join([str(PKG / "lib"), str(Path(aicore.__file__).resolve().parents[1])]))
        done = subprocess.run([sys.executable, "-m", "harness", str(PKG), "hooks", "show",
                               "--target", str(self.proj), "--json"],
                              capture_output=True, text=True, env=env, check=False)
        self.assertEqual(done.returncode, 0, done.stderr)
        self.assertEqual(json.loads(done.stdout)["$schema"], hooks_env.STATE_SCHEMA)


@contextlib.contextmanager
def _patched_env(values):
    saved = dict(os.environ)
    os.environ.update(values)
    try:
        yield
    finally:
        os.environ.clear()
        os.environ.update(saved)


class PythonReadersCase(Base):
    """Every python hook reads the carrier first, then the legacy file, then its default."""

    def write_carrier(self, *lines):
        self.carrier.parent.mkdir(parents=True, exist_ok=True)
        self.carrier.write_text("# Generated\n" + "".join(line + "\n" for line in lines), encoding="utf-8")

    def legacy(self, name, text):
        (self.proj / ".claude").mkdir(exist_ok=True)
        (self.proj / ".claude" / name).write_text(text, encoding="utf-8")

    def test_gate_hooks(self):
        for directory, script, name, key in (
                ("pack-guard", "pack-guard.py", "pack-guard.env.ini", "PACK_GUARD_MODE"),
                ("plan-guard", "plan-guard.py", "plan-guard.env.ini", "PLAN_GUARD_MODE"),
                ("changelog-gate", "changelog-gate.py", "changelog-gate.env.ini", "CHANGELOG_GATE_MODE")):
            with self.subTest(hook=directory):
                module = load_script(HOOKS / directory / script, "m_" + directory.replace("-", "_"))
                self.assertEqual(module._read_mode(str(self.proj)), "off")
                self.legacy(name, "MODE=warn\n")
                self.assertEqual(module._read_mode(str(self.proj)), "warn")
                self.write_carrier(f"{key}=strict")
                self.assertEqual(module._read_mode(str(self.proj)), "strict")
                self.write_carrier(f"{key}=strict", f"{key}__CLAUDE_CODE=off", f"{key}__CURSOR=warn")
                self.assertEqual(module._read_mode(str(self.proj)), "off")
                self.write_carrier(f"{key}=bogus")
                self.assertEqual(module._read_mode(str(self.proj)), "off")
                self.carrier.unlink()

    def test_plan_regen(self):
        module = load_script(HOOKS / "plan-regen" / "plan-regen.py", "m_plan_regen")
        self.assertFalse(module._enabled(str(self.proj)))
        self.legacy("plan-regen.env.ini", "MODE=on\n")
        self.assertTrue(module._enabled(str(self.proj)))
        self.write_carrier("PLAN_REGEN_MODE=off")
        self.assertFalse(module._enabled(str(self.proj)))

    def test_run_report(self):
        module = load_script(HOOKS / "run-report" / "run-report.py", "m_run_report")
        self.assertEqual(module._read_enabled(str(self.proj)), (True, 30, True))
        self.legacy("run-report.env.ini", "ENABLED=on\nRUNS_KEEP=3\n")
        self.assertEqual(module._read_enabled(str(self.proj)), (True, 3, True))
        self.write_carrier("RUN_REPORT_ENABLED=off", "RUN_REPORT_RUNS_KEEP=7")
        self.assertEqual(module._read_enabled(str(self.proj)), (False, 7, True))
        self.write_carrier("RUN_REPORT_ENABLED=on")
        self.assertEqual(module._read_enabled(str(self.proj)), (True, 3, True))

    def test_agent_router(self):
        sys.path.insert(0, str(HOOKS / "agent-router"))
        self.addCleanup(sys.path.remove, str(HOOKS / "agent-router"))
        module = load_script(HOOKS / "agent-router" / "_lib.py", "m_router_lib")
        cfg = str(HOOKS / "agent-router")
        self.assertEqual(module.read_env(cfg, str(self.proj))["POLICY"], "off")
        self.legacy("agent-router.env.ini", "POLICY=auto_dispatch\n")
        self.assertEqual(module.read_env(cfg, str(self.proj))["POLICY"], "auto_dispatch")
        self.write_carrier("AGENT_ROUTER_POLICY=propose")
        values = module.read_env(cfg, str(self.proj))
        self.assertEqual((values["POLICY"], values["THRESHOLD"]), ("propose", "2"))


class ShellReadersCase(Base):
    def bash(self, script, **env):
        base = {"PATH": "/usr/bin:/bin", "HOME": str(self.tmp)}
        base.update(env)
        done = subprocess.run(["bash", "-c", script], capture_output=True, text=True, env=base, check=False)
        return done.stdout.strip()

    def write_carrier(self, *lines):
        self.carrier.parent.mkdir(parents=True, exist_ok=True)
        self.carrier.write_text("# Generated\n" + "".join(line + "\n" for line in lines), encoding="utf-8")

    def test_auto_approve_and_memory_read_mode(self):
        for directory, key, legacy in (("auto-approve", "AUTO_APPROVE_MODE", "auto-approve.env.ini"),
                                       ("memory", "MEMORY_MODE", "memory.env.ini")):
            with self.subTest(hook=directory):
                common = HOOKS / directory / "lib" / "common.sh"
                hookdir = self.tmp / ("hook-" + directory)
                hookdir.mkdir()
                (hookdir / "env.ini").write_text("MODE=permissive\n", encoding="utf-8")
                script = f'source "{common}"; read_mode "{hookdir}"'
                project = {"CLAUDE_PROJECT_DIR": str(self.proj)}
                self.assertEqual(self.bash(script, **project), "permissive")
                (self.proj / ".claude").mkdir(exist_ok=True)
                (self.proj / ".claude" / legacy).write_text("MODE=warn\n", encoding="utf-8")
                self.assertEqual(self.bash(script, **project), "warn")
                self.write_carrier(f"{key}=strict")
                self.assertEqual(self.bash(script, **project), "strict")
                self.write_carrier(f"{key}=strict", f"{key}__CLAUDE_CODE=bypass", f"{key}__CURSOR=off")
                raising = "permissive" if directory == "auto-approve" else "bypass"  # a project never raises the auto-approve mode
                self.assertEqual(self.bash(script, **project), raising)
                if directory == "auto-approve":
                    (hookdir / "env.ini").write_text("MODE=permissive\nALLOW_PROJECT_CONFIG=1\n", encoding="utf-8")
                    self.assertEqual(self.bash(script, **project), "bypass")
                    (hookdir / "env.ini").write_text("MODE=permissive\n", encoding="utf-8")
                self.assertEqual(self.bash(script), "permissive")  # no project dir: the global default

    def test_memory_brain_prefers_the_carrier_then_swissknife_json(self):
        common = HOOKS / "memory" / "lib" / "common.sh"
        (self.proj / ".swissknife.json").write_text('{"memory_brain": "legacy"}', encoding="utf-8")
        script = f'source "{common}"; brain_default'
        self.assertEqual(self.bash(script, CLAUDE_PROJECT_DIR=str(self.proj)), "legacy")
        self.write_carrier("MEMORY_BRAIN=carried")
        self.assertEqual(self.bash(script, CLAUDE_PROJECT_DIR=str(self.proj)), "carried")

    def run_hook(self, script, payload, **env):
        base = {"PATH": "/usr/bin:/bin", "HOME": str(self.tmp)}
        base.update(env)
        return subprocess.run(["bash", str(script)], input=json.dumps(payload), capture_output=True,
                              text=True, env=base, check=False)

    def test_review_gate_mode_comes_from_the_carrier(self):
        hookdir = self.tmp / "review-gate"
        hookdir.mkdir()
        for name in ("review-gate.sh",):
            (hookdir / name).write_bytes((HOOKS / "review-gate" / name).read_bytes())
        (hookdir / "env.ini").write_text("MODE=strict\n", encoding="utf-8")
        (hookdir / "config.json").write_text(json.dumps({"check_command": "false"}), encoding="utf-8")
        payload = {"cwd": str(self.proj), "session_id": "s", "agent_id": "a", "agent_type": "dev",
                   "hook_event_name": "SubagentStop"}
        failing = self.run_hook(hookdir / "review-gate.sh", payload)
        self.assertEqual(failing.returncode, 2, failing.stderr)
        self.write_carrier("REVIEW_GATE_MODE=off")
