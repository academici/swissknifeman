"""TypeScript retains JSON wire names and optionality; all fields are readonly."""

import json
from hashlib import sha256

from .model import CodegenError, Model, Type
from .parse import escape

_HTTP_METHODS = {"get", "put", "post", "delete", "options", "head", "patch", "trace"}


def render_routes(openapi: str) -> str:
    """Map operation IDs to their literal methods and full path templates."""
    document = json.loads(openapi)
    digest = sha256(openapi.encode("utf-8")).hexdigest()
    lines = [
        f"// generated by tools/gen.py from OpenAPI; sources sha256:{digest}; do not edit",
        "",
        "export const API_ROUTES = {",
    ]
    for path, item in sorted(document["paths"].items()):
        for method in sorted(_HTTP_METHODS.intersection(item)):
            operation = item[method]
            servers = operation.get("servers", item.get("servers", document["servers"]))
            endpoint = servers[0]["url"].rstrip("/") + path
            lines.append(
                f"  {json.dumps(operation['operationId'])}: "
                f"{{ method: {json.dumps(method.upper())}, path: {json.dumps(endpoint)} }},"
            )
    lines.extend(
        [
            "} as const;",
            "",
            "export type OperationId = keyof typeof API_ROUTES;",
            "export type ApiRoute = (typeof API_ROUTES)[OperationId];",
        ]
    )
    return "\n".join(lines) + "\n"


def _javascript_loss(value: int) -> str:
    """Why a JavaScript number cannot carry ``value`` exactly through JSON.parse and JSON.stringify, or ''."""
    magnitude = abs(value)
    try:
        number = float(magnitude)
    except OverflowError:
        return "JSON.parse would overflow the finite binary64 range"
    if int(number) != magnitude:
        return "JSON.parse would round it to a double"
    if not magnitude:
        return ""
    # Number::toString minimizes significant decimal digits, then chooses the closest value:
    # https://tc39.es/ecma262/#sec-numeric-types-number-tostring (step 5 and note 2).
    # If magnitude has t trailing zeros, fewer digits require a multiple of 10**(t+1).
    # Only its two enclosing multiples can round back if any do (rounding intervals are contiguous).
    # A decimal order boundary cannot hide a candidate: the intervening power of ten is a multiple too.
    # With no shorter candidate, the exact integer wins by zero distance, even in exponent notation.
    step = 10
    while magnitude % step == 0:
        step *= 10
    lower = magnitude // step * step
    for candidate in (lower, lower + step):
        try:
            shorter = float(candidate)
        except OverflowError:
            continue
        if shorter == number:
            return "JSON.stringify would write a different decimal"
    return ""


def _literal(value, location: str) -> str:
    loss = "" if isinstance(value, bool) or not isinstance(value, int) else _javascript_loss(value)
    if loss:
        raise CodegenError(
            location,
            f"integer literal of {value.bit_length()} bits has no exact TypeScript number literal; {loss}",
        )
    return json.dumps(value, ensure_ascii=False)


def type_text(t: Type, model: Model, file: str, location: str = "") -> str:
    if t.ref:
        d = model.declarations[t.ref]
        return d.ts_name if d.ts_file == file else f"import('./{d.ts_file[:-3]}').{d.ts_name}"
    primitives = {
        "any": "unknown",
        "never": "never",
        "object": "Readonly<Record<string, unknown>>",
        "null": "null",
        "str": "string",
        "int": "number",
        "float": "number",
        "bool": "boolean",
        "date": "string",
        "secret": "string",
    }
    if t.tag in primitives:
        return primitives[t.tag]
    if t.tag in ("uuid", "datetime"):
        name = "Uuid" if t.tag == "uuid" else "IsoDateTime"
        return name if file == "kernel.ts" else f"import('./kernel').{name}"
    parts = [type_text(a, model, file, location) for a in t.args]
    if t.tag == "literal":
        return " | ".join(_literal(v, location) for v in t.values)
    if t.tag == "union":
        return " | ".join(dict.fromkeys(parts))
    if t.tag == "array":
        return f"readonly ({parts[0]})[]"
    if t.tag == "tuple":
        return "readonly [" + ", ".join(parts) + "]"
    if t.tag == "map":
        # Index signatures are equivalent to Readonly<Record<...>> and permit recursive aliases.
        return f"{{ readonly [key: string]: {parts[0]} }}"
    raise ValueError(t)


def render(model, declarations, header, *, kernel=False):
    lines = [header, ""]
    if kernel:
        lines += [
            'export type Uuid = string & { readonly __brand: "Uuid" };',
            'export type IsoDateTime = string & { readonly __brand: "IsoDateTime" };',
            "",
        ]
    seen = set()
    for d in model.ordered(declarations):
        if d.ts_name in seen:
            continue
        seen.add(d.ts_name)
        if d.type.tag == "record":
            lines += [f"export interface {d.ts_name} {{"]
            lines += [
                f"  readonly {json.dumps(f.wire)}{'' if f.required else '?'}: "
                f"{type_text(f.type, model, d.ts_file, d.location + '/properties/' + escape(f.wire))};"
                for f in d.fields
            ]
            lines += ["}", ""]
        elif d.kind == "enum":
            lines += [
                f"export const {d.ts_name}Values = "
                f"{json.dumps(list(d.type.values), ensure_ascii=False)} as const;",
                f"export type {d.ts_name} = (typeof {d.ts_name}Values)[number];",
                "",
            ]
        else:
            lines += [f"export type {d.ts_name} = {type_text(d.type, model, d.ts_file, d.location)};", ""]
    return "\n".join(lines).rstrip() + "\n"
