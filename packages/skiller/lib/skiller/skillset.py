# Куда складываем скиллы по умолчанию (Claude находит автоматически).
DEFAULT_SKILLS_PATH = ".claude/skills"
CONFIG_DIR = ".swissknifeman"
CONFIG_FILE = "config.json"
LOCK_FILE = "skills-lock.json"
LOCK_VERSION = 1
MANIFEST_VERSION = 1
SOURCE = "swissknifeman"

# Ключи конфига vendor-режима (.swissknifeman/config.json). Намеренно шире
# .swissknife.json — это отдельный, расширяемый конфиг режима физ. переноса.
SKILLSET_KEYS = {
    "version": int,
    "mode": str,          # пока только "vendor"
    "agent": str,         # информативно; путь задаёт skills_path
    "skills_path": str,   # куда копировать (по умолчанию .claude/skills)
    "presets": list,      # именованные кластеры (presets/<name>.json) → buckets/include
    "include": list,      # конкретные скиллы: "bucket/rel" или просто "name"
    "buckets": list,      # бакеты целиком
    "exclude": list,      # вычитание из (presets ∪ buckets ∪ include)
    "gitignore_managed": bool,  # эмитить <skills_path>/.gitignore для managed-скиллов
}

# Заголовок-маркер сгенерированного нами .gitignore (по нему опознаём «свой» файл).
GITIGNORE_HEADER = "# Generated by `skiller sync` — НЕ редактируй вручную."


# --- registry index (источник истины — skills.json) ---------------------------
def _registry_index(env):
    """skills.json → {key: entry}, где key — и полный путь 'bucket/rel', и имя.

    entry = {name, bucket, rel, path(SKILL.md, отн. корня реестра), sha256,
             skill_dir(абс.)}. Реестр — единственный источник, по которому
    резолвятся и проверяются на дрейф наши скиллы."""
    f = env.root / "skills.json"
    if not f.is_file():
        die("skills.json не найден — сначала skiller registry")
    data = json.loads(f.read_text(encoding="utf-8"))
    skills = data["skills"] if isinstance(data, dict) else data
    by_key = {}
    by_name = {}
    for s in skills:
        name = s.get("name") or s.get("id")
        bucket = s.get("bucket", "")
        path = s.get("path", "")  # "skills/<bucket>/<rel>/SKILL.md"
        if not (name and path):
            warn(f"skills.json: запись пропущена (нет name или path): {s}")
            continue
        skill_dir = (env.root / path).parent
        # rel внутри бакета: skills/<bucket>/<rel>/SKILL.md → <rel>
        rel = ""
        parts = Path(path).parts
        if len(parts) >= 4 and parts[0] == "skills":
            rel = "/".join(parts[2:-1])
        entry = {
            "name": name, "bucket": bucket, "rel": rel, "path": path,
            "sha256": s.get("sha256", ""),
            "content_sha256": s.get("content_sha256", ""),
            "requires": s.get("requires", []) or [],
            "skill_dir": skill_dir,
        }
        full = f"{bucket}/{rel}".rstrip("/") if rel else bucket
        by_key[full] = entry
        if name in by_name:
            warn(f"skills.json: дубль имени '{name}' "
                 f"(бакеты: {by_name[name]['bucket']} и {bucket}) — по имени "
                 f"доступен первый; используйте полный путь 'bucket/rel'")
        else:
            by_name[name] = entry
    return by_key, by_name


def _match(token, by_key, by_name):
    """Разрешить токен правила в entry: сначала по полному пути, потом по имени.

    Drift-устойчивость: после раскола бакетов старый путь 'oldbucket/skill'
    (напр. 'frontend/vue' → 'frontend-vue/vue') промахивается по by_key. Если
    токен — путь, добиваем по базовому имени (последний сегмент). Иначе sync
    молча терял переехавшие скиллы (warn+skip). Вызывающий печатает
    migration-warning со старым→новым путём."""
    if token in by_key:
        return by_key[token]
    if token in by_name:
        return by_name[token]
    if "/" in token:
        base = token.rsplit("/", 1)[1]
        if base in by_name:
            return by_name[base]
    return None


# --- presets (именованные кластеры скиллов) -----------------------------------
def _load_preset(env, name):
    """presets/<name>.json или None. Невалидный JSON — die."""
    f = env.root / "presets" / f"{name}.json"
    if not f.is_file():
        return None
    try:
        return json.loads(f.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError) as e:
        die(f"presets/{name}.json: невалидный JSON: {e}")


def resolve_presets(env, names):
    """Раскрыть пресеты (рекурсивно `extends`) в (buckets, include, skipped).

    Пресет — именованная группа: `{name, description, extends?, buckets?, include?}`.
    Возвращает агрегированные buckets/include (с дедупом, родители раньше детей) и
    skipped — неизвестные пресеты (warning). Цикл `extends` — die."""
    buckets, include, skipped, seen = [], [], [], set()

    def visit(name, trail):
        if name in trail:
            die(f"presets: цикл extends: {' -> '.join(trail + [name])}")
        if name in seen:
            return
        preset = _load_preset(env, name)
        if preset is None:
            warn(f"presets: пресет '{name}' не найден в presets/ — пропуск")
            skipped.append(name)
            return
        seen.add(name)
        for parent in preset.get("extends", []):
            visit(parent, trail + [name])
        buckets.extend(preset.get("buckets", []))
        include.extend(preset.get("include", []))

    for n in names:
        visit(n, [])
    return buckets, include, skipped


# --- config -------------------------------------------------------------------
def skillset_config_path(target):
    return Path(target) / CONFIG_DIR / CONFIG_FILE


def load_skillset_config(target):
    """Прочитать .swissknifeman/config.json (или None, если его нет)."""
    cfg_file = skillset_config_path(target)
    if not cfg_file.is_file():
        return None
    try:
        cfg = json.loads(cfg_file.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        die(f"{cfg_file}: невалидный JSON: {e}")
    import difflib
    for key, value in cfg.items():
        if key.startswith(("_", "$")):  # _comment / $schema — DX, не валидируем
            continue
        if key not in SKILLSET_KEYS:
            hint = difflib.get_close_matches(key, list(SKILLSET_KEYS), n=1)
            suffix = f" — может быть '{hint[0]}'?" if hint else ""
            die(f"{cfg_file}: неизвестный ключ '{key}'{suffix}")
        if not isinstance(value, SKILLSET_KEYS[key]):
            want = SKILLSET_KEYS[key].__name__
            die(f"{cfg_file}: '{key}' должен быть {want}")
    if cfg.get("mode", "vendor") != "vendor":
        die(f"{cfg_file}: поддерживается только mode=vendor")
    return cfg


def _pull_requires(selected, by_name, exclude):
    """Транзитивно дотянуть `requires` выбранных скиллов в `selected` (name->entry).
    Паритет с vendor.resolve_requires (но на entry реестра): exclude ПОБЕЖДАЕТ
    зависимость (с warning), неизвестная зависимость — warning и пропуск. Без этого
    skill-granular include молча терял зависимости (64/195 скиллов имеют requires)."""
    queue = [(dep, e["name"]) for e in list(selected.values())
             for dep in e.get("requires", [])]
    while queue:
        dep, requester = queue.pop(0)
        if dep in selected:
            continue
        dep_entry = by_name.get(dep)
        if dep_entry is None:
            warn(f"'{requester}' requires неизвестный скилл '{dep}' — пропуск")
            continue
        full = (f"{dep_entry['bucket']}/{dep_entry['rel']}".rstrip("/")
                if dep_entry["rel"] else dep_entry["bucket"])
        if {dep, dep_entry["name"], full, dep_entry["bucket"]} & exclude:
            warn(f"'{requester}' requires '{dep}', но он в exclude — зависимость пропущена")
            continue
        selected[dep_entry["name"]] = dep_entry
        queue.extend((d, dep) for d in dep_entry.get("requires", []))


def resolve_skillset(env, cfg, include_core=False):
    """Развернуть правила конфига в набор entry: (buckets ∪ include) − exclude,
    затем транзитивно дотянуть `requires` (exclude по-прежнему побеждает).

    include_core=True добавляет CORE_SKILLS (как vendor/connect) и применяет
    DEFAULT_EXCLUDE — токен-скиллы раздаются в каждый проект по умолчанию.

    Возвращает (entries, skipped): entries отсортированы по 'bucket/name';
    skipped — токены, не найденные в реестре (с warning)."""
    by_key, by_name = _registry_index(env)
    known = set(all_buckets(env))
    selected = {}  # name -> entry (имя уникально в раскладке .claude/skills)
    skipped = []

    # пресеты раскрываем в buckets/include ДО формулы (buckets ∪ include) − exclude
    preset_buckets, preset_include, preset_skipped = \
        resolve_presets(env, cfg.get("presets", []))
    skipped.extend(preset_skipped)
    req_buckets = list(dict.fromkeys(preset_buckets + cfg.get("buckets", [])))
    req_include = list(dict.fromkeys(preset_include + cfg.get("include", [])))

    # бакеты целиком
    for bucket in req_buckets:
        if bucket not in known:
            die(f"неизвестный бакет: {bucket}")
        for entry in by_key.values():
            if entry["bucket"] == bucket:
                selected[entry["name"]] = entry

    # конкретные скиллы
    for token in req_include:
        entry = _match(token, by_key, by_name)
        if entry is None:
            warn(f"include: скилл '{token}' не найден в реестре — пропуск")
            skipped.append(token)
            continue
        full = (f"{entry['bucket']}/{entry['rel']}".rstrip("/")
                if entry["rel"] else entry["bucket"])
        if "/" in token and token != full:
            warn(f"include: '{token}' переехал → '{full}' (раскол бакетов) — "
                 f"обновите .swissknifeman/config.json")
        selected[entry["name"]] = entry

    # CORE-политика: токен-скиллы по умолчанию + DEFAULT_EXCLUDE дублей хаба
    exclude = set(cfg.get("exclude", []))
    if include_core:
        exclude |= set(DEFAULT_EXCLUDE)
        for _bucket, _rel, _d, fm_name in core_skill_tuples(env, exclude):
            entry = by_name.get(fm_name)
            if entry:
                selected[entry["name"]] = entry

    # вычитание
    if exclude:
        for name, entry in list(selected.items()):
            full = f"{entry['bucket']}/{entry['rel']}".rstrip("/") \
                if entry["rel"] else entry["bucket"]
            if {name, full, entry["bucket"], entry["rel"]} & exclude:
                del selected[name]

    # транзитивные requires выбранных скиллов (после вычитания: тянем зависимости
    # только тех, что реально останутся). exclude по-прежнему побеждает зависимость.
    _pull_requires(selected, by_name, exclude)

    entries = sorted(selected.values(),
                     key=lambda e: (e["bucket"], e["name"]))
    return entries, skipped


# --- lock ---------------------------------------------------------------------
def load_lock(target):
    f = Path(target) / LOCK_FILE
    if not f.is_file():
        return {}
    try:
        data = json.loads(f.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        # Битый lock молча трактовался как пустой → ВСЕ managed-скиллы считались новыми и
        # перекопировались (лишняя работа + путаный вывод). Предупреждаем: пересоберём из
        # конфига, но пусть это будет видно (проверить git-историю файла).
        warn(f"{f}: битый JSON skills-lock — игнорирую и пересоберу из конфига "
             f"(managed-скиллы могут перекопироваться). См. git-историю файла.")
        return {}
    if not isinstance(data, dict) or not isinstance(data.get("skills"), dict):
        warn(f"{f}: неожиданная структура skills-lock (нет dict 'skills') — игнорирую, пересоберу.")
        return {}
    return data


def write_lock(target, lock):
    atomic_write_json(Path(target) / LOCK_FILE, lock)


def _dir_sha256(skill_dir):
    """sha256 SKILL.md — та же база, что в реестре (skills.json считает по файлу)."""
    md = Path(skill_dir) / "SKILL.md"
    if not md.is_file():
        return ""
    return hashlib.sha256(md.read_bytes()).hexdigest()


# --- sync ---------------------------------------------------------------------
def plan_sync(env, target, cfg, include_core=False):
    """Сухой расчёт: что добавить/обновить/удалить. Ничего не пишет.

    Возвращает dict: {add, update, remove, keep, conflicts, skills_path, entries}.
    - add:    name'ы новых managed-скиллов
    - update: name'ы managed-скиллов с разошедшимся sha256 (или отсутствующим файлом)
    - remove: name'ы managed-скиллов из lock, которых больше нет в конфиге
    - keep:   managed-скиллы без изменений
    - conflicts: name'ы из add, чей путь занят ЧУЖИМ скиллом (не managed) — symlink/
                 каталог/файл, который мы не ставили. sync без force их пропускает.
    Чужие (managed!=true) записи в расчёте удаления НЕ участвуют."""
    entries, skipped = resolve_skillset(env, cfg, include_core=include_core)
    skills_path = cfg.get("skills_path") or DEFAULT_SKILLS_PATH
    dest_root = Path(target) / skills_path
    lock = load_lock(target)
    locked = lock.get("skills", {})

    desired = {e["name"]: e for e in entries}
    managed_locked = {n: e for n, e in locked.items() if e.get("managed")}

    add, update, keep, conflicts = [], [], [], []
    for name, entry in desired.items():
        dst = dest_root / name
        prev = managed_locked.get(name)
        if prev is None:
            # новый для нас; если путь занят чужим (не managed) — конфликт
            if dst.is_symlink() or dst.exists():
                conflicts.append(name)
            else:
                add.append(name)
        elif not dst.is_dir() or dst.is_symlink():
            add.append(name)
        elif prev.get("sha256") != entry["sha256"]:
            update.append(name)
        elif (prev.get("content_sha256")
              and prev.get("content_sha256") != entry.get("content_sha256", "")):
            # дрейф в snippets/references при неизменном SKILL.md. Гард на наличие
            # ключа в локе → старые локи (без content_sha256) не дают ложный update.
            update.append(name)
        else:
            keep.append(name)
    remove = [n for n in managed_locked if n not in desired]
    return {
        "add": sorted(add), "update": sorted(update),
        "remove": sorted(remove), "keep": sorted(keep),
        "conflicts": sorted(conflicts),
        "skipped": skipped, "skills_path": skills_path,
        "entries": entries, "dest_root": dest_root,
    }


def _remove_path(path):
    """Снести каталог/файл/симлинк по пути (симлинк не разыменовываем)."""
    if path.is_symlink() or path.is_file():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)


def sync_skillset(env, target, cfg, dry_run=False, force=False,
                  include_core=False):
    """Применить конфиг: скопировать новые/обновлённые, удалить выбывшие managed,
    переписать skills-lock.json. Чужие скиллы остаются как есть (конфликты
    пропускаются с warning; --force перетирает чужой путь нашим скиллом).
    include_core=True — раздать CORE_SKILLS по умолчанию (как vendor/connect)."""
    plan = plan_sync(env, target, cfg, include_core=include_core)
    dest_root = plan["dest_root"]
    entries = {e["name"]: e for e in plan["entries"]}
    lock = load_lock(target)
    locked = dict(lock.get("skills", {}))

    def contained(path):
        return is_within(path, dest_root)

    # Конфликты с чужими путями: без force — пропуск; с force — добавить к install.
    install = list(plan["add"]) + list(plan["update"])
    if plan["conflicts"]:
        if force:
            install += plan["conflicts"]
        else:
            for name in plan["conflicts"]:
                warn(f"конфликт: '{name}' занят чужим скиллом (не managed) — "
                     f"пропуск; --force чтобы заменить версией из библиотеки")

    # --- prune: только managed, выбывшие из конфига ---------------------------
    for name in plan["remove"]:
        stale = dest_root / name
        if dry_run:
            print(f"[dry-run] remove {stale}")
        elif (stale.is_symlink() or stale.exists()) and contained(stale):
            _remove_path(stale)
        locked.pop(name, None)

    # --- install / update -----------------------------------------------------
    if not dry_run:
        dest_root.mkdir(parents=True, exist_ok=True)
    for name in install:
        entry = entries[name]
        src = entry["skill_dir"]
        dst = dest_root / name
        if dry_run:
            verb = "add" if name in plan["add"] else \
                ("replace" if name in plan["conflicts"] else "update")
            print(f"[dry-run] {verb} {entry['bucket']}/{entry['name']} -> {dst}")
            continue
        # Единый безопасный copy (containment + снятие symlink/файла/каталога + TOCTOU-
        # перепроверка + SKILL_IGNORE) — общий с vendor.copy_skill (не разъезжаться).
        if not safe_copy_skill(src, dst, dest_root):
            continue
        locked[name] = {
            "source": SOURCE,
            "managed": True,
            "bucket": entry["bucket"],
            "sha256": _dir_sha256(dst),
            # content_sha256 — из реестра (хеш ИСТОЧНИКА): копия отличается игнорами,
            # поэтому хешируем источник, а не dst (иначе ложный дрейф каждый sync).
            "content_sha256": entry.get("content_sha256", ""),
            "installed_path": f"{plan['skills_path']}/{name}",
        }

    # keep: освежить метаданные на случай ручной правки lock (и доpopulation
    # content_sha256 в старых локах — без перекопирования неизменённых скиллов)
    for name in plan["keep"]:
        entry = entries[name]
        locked.setdefault(name, {})
        locked[name].update({
            "source": SOURCE, "managed": True, "bucket": entry["bucket"],
            "sha256": entry["sha256"],
            "content_sha256": entry.get("content_sha256", ""),
            "installed_path": f"{plan['skills_path']}/{name}",
        })

    new_lock = {
        "version": lock.get("version", LOCK_VERSION),
        "skills": dict(sorted(locked.items())),
        "sources": {**lock.get("sources", {}),
                    SOURCE: {"ref": "registry", "mode": "vendor"}},
    }
    if not dry_run:
        # Порядок НАМЕРЕННЫЙ: skills-lock.json — источник истины детекта (plan_sync читает
        # load_lock, НЕ манифест), поэтому пишем его авторитетно ПОСЛЕ того, как файлы уже на
        # диске (copytree выше). Манифест — производная (контракт реинсталла/индекс для hub),
        # регенерится каждый успешный sync. Краш после lock, до манифеста → детект на след.
        # sync корректен (по lock), манифест добьётся. (Не переставлять: манифест-первым сделал
        # бы lock устаревшим при краше и сломал бы детект.)
        write_lock(target, new_lock)
        _write_manifest(target, plan["skills_path"], new_lock["skills"],
                        entries, cfg)
        # gitignore_managed: держать managed-скиллы вне git (воспроизводимы sync),
        # локальные/кастомные — в репо. Список авто-сопровождается каждым sync.
        if cfg.get("gitignore_managed"):
            _write_gitignore(target, plan["skills_path"], new_lock["skills"])
        else:
            _remove_our_gitignore(target, plan["skills_path"])
    return plan


def _write_gitignore(target, skills_path, locked):
    """gitignore_managed: эмитим `<skills_path>/.gitignore` со списком ТОЛЬКО
    managed-скиллов (воспроизводимы `skiller sync`). Корневой `.gitignore` НЕ трогаем
    (изоляция + авто-сопровождение). Локальные/кастомные скиллы здесь не перечислены
    → остаются в репозитории; манифест/lock/сам .gitignore тоже видимы (не skill-dir)."""
    dest_root = Path(target) / skills_path
    if not dest_root.is_dir():
        return
    managed = sorted(n for n, e in locked.items() if e.get("managed"))
    lines = [
        GITIGNORE_HEADER,
        "# Managed swissknifeman-скиллы держим ВНЕ git — они воспроизводимы:",
        "#   skiller sync   (из .swissknifeman/config.json + skills-lock.json)",
        "# Локальные/кастомные скиллы здесь НЕ перечислены → остаются в репозитории.",
        "",
    ] + [f"/{n}/" for n in managed]
    atomic_write_text(dest_root / ".gitignore", "\n".join(lines) + "\n")


def _remove_our_gitignore(target, skills_path):
    """gitignore_managed выключен → убрать ранее сгенерированный НАМИ `.gitignore`
    (опознаём по заголовку), чтобы managed-скиллы снова коммитились. Чужой .gitignore
    не трогаем."""
    gi = Path(target) / skills_path / ".gitignore"
    try:
        if gi.is_file() and gi.read_text(encoding="utf-8").startswith(GITIGNORE_HEADER):
            gi.unlink()
    except OSError:
        pass


def _write_manifest(target, skills_path, locked, entries, cfg):
    """Манифест .swissknifeman-manifest.json в skills_path — контракт для
    переустановки (vendor) и источник для generate-hub.sh (индекс скиллов).
    Раскладка sync всегда flat: <skills_path>/<name>/SKILL.md. Перечисляем
    все managed-скиллы, фактически установленные после операции."""
    dest_root = Path(target) / skills_path
    if not dest_root.is_dir():
        return
    installed = []
    for name in sorted(locked):
        entry = entries.get(name)
        if not entry:
            continue  # managed-запись без entry в реестре — не индексируем
        installed.append({
            "flat_name": name,
            "source_path": str(Path(entry["path"]).parent),
        })
    data = {
        "installed_at": now_iso(),
        "profile": cfg.get("project_type", ""),
        "agent": cfg.get("agent", "claude"),
        "layout": "flat",
        "skills": installed,
    }
    # Атомарно (tmp+os.replace) и с version первым ключом — как skills-lock.json;
    # raw write_text здесь оставлял бы шанс на полузаписанный манифест при крахе.
    atomic_write_json(dest_root / MANIFEST, data, version=MANIFEST_VERSION)


# --- config materialization (общая для init и do_sync) ------------------------
def materialize_skillset_config(env, target, opts, dry=False, force=False):
    """Вернуть конфиг vendor-режима; создать `.swissknifeman/config.json` из
    профиля проекта, если его ещё нет (force=True — пересоздать из автодетекта).

    Существующий курированный конфиг уважается (force=False → читаем как есть, не
    перетираем). ЕДИНАЯ точка материализации для `cmd_init` и `do_sync` — чтобы
    набор по умолчанию не разъезжался между «создать конфиг» и «синкнуть».
    Возвращает (cfg, profile_name, created): created=True, если файл записан."""
    cfg_path = skillset_config_path(target)
    if cfg_path.is_file() and not force:
        cfg = load_skillset_config(target)
        return cfg, (cfg.get("project_type") or ""), False
    legacy = load_config(env, target)
    buckets, profile_name, _psrc, source, _meta = resolve_selection(
        env, target, legacy, opts.get("profile", ""), [])
    cfg = {"version": LOCK_VERSION, "mode": "vendor", "agent": "claude",
           "buckets": list(buckets), "include": [], "exclude": []}
    if not dry:
        cfg_path.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_json(cfg_path, cfg, version=LOCK_VERSION)
    print(("[dry-run] " if dry else "")
          + f"конфиг vendor-режима: {CONFIG_DIR}/{CONFIG_FILE} "
          f"(mode=vendor, buckets: {' '.join(buckets) or '-'})")
    if source == "autodetect-fallback":
        print("⚠ тип проекта не распознан — материализовано МИНИМАЛЬНОЕ ядро;\n"
              "  для оптимального набора укажи профиль: --profile <type>")
    return cfg, profile_name, True


# --- integrate/onboard entry (vendor-канал «опубликовать в репо») -------------
def do_sync(env, target, opts, register=True):
    """Vendor-канал через sync: «опубликовать» скиллы физически в .claude/skills/.

    Это путь для проектов, которые отдают сторонним разработчикам БЕЗ доступа к
    реестру swissknifeman: файлы скиллов коммитятся в репо проекта (в отличие от
    connect, где скиллы живут плагинами в реестре). Материализует
    .swissknifeman/config.json из профиля проекта, если конфига ещё нет; уже
    существующий курированный конфиг уважается (не перетираем). Паритет с
    connect/do_vendor: permissions-пресеты, hub, регистрация (channel=vendor)."""
    dry = opts.get("dry_run", False)
    force = opts.get("force", False)
    no_core = opts.get("no_core", False)

    cfg, profile_name, _created = materialize_skillset_config(
        env, target, opts, dry=dry)

    plan = sync_skillset(env, target, cfg, dry_run=dry, force=force,
                         include_core=not no_core)
    print(("[dry-run] " if dry else "")
          + f"sync: +{len(plan['add'])} ~{len(plan['update'])} "
          f"-{len(plan['remove'])} ={len(plan['keep'])} "
          f"(skills_path: {plan['skills_path']})")
    if plan["conflicts"] and not force:
        print(f"  конфликты (чужие, пропущены): {', '.join(plan['conflicts'])} "
              "— --force чтобы заменить")
    if plan["skipped"]:
        print(f"  пропущено (нет в реестре): {', '.join(plan['skipped'])}")

    # permissions-пресеты (deny мусора + allow стека) — паритет с connect/do_vendor
    if not opts.get("no_permissions"):
        apply_permissions(env, target, dry_run=dry)

    if opts.get("hub") and not dry:
        generate_hub(env, target)

    record = {
        "path": str(target),
        "channel": "vendor",
        "profile": profile_name,
        "agent": "claude",
        "skills_path": plan["skills_path"],
        "hub": opts.get("hub") or hub_artifacts_exist(target),
    }
    if register and not dry:
        upsert_project(env, record)
    return record


# --- CLI ----------------------------------------------------------------------
def cmd_init(env, argv):
    """Создать `.swissknifeman/config.json` (mode=vendor) — без копирования скиллов.

    Парадная, идемпотентная дверь «дай мне конфиг»: автодетект типа проекта +
    профиль → buckets. Копирование делает `skiller sync`. Раньше конфиг
    материализовался только как побочный эффект `sync`/`integrate`."""
    opts = parse_flags(argv, {"--target": "str", "--profile": "str",
                              "--force": "bool", "--dry-run": "bool"})
    if opts["help"]:
        print("skiller init [--target DIR] [--profile TYPE] [--force] [--dry-run]\n"
              "  Создаёт .swissknifeman/config.json (mode=vendor) из автодетекта "
              "типа проекта и профиля —\n"
              "  БЕЗ копирования скиллов (это делает skiller sync). Существующий "
              "конфиг не перетирается без --force.")
        return
    target, via = resolve_target(env, opts, allow_home_confirm=True)
    cfg_path = skillset_config_path(target)
    if cfg_path.is_file() and not opts["force"]:
        print(f"✓ {CONFIG_DIR}/{CONFIG_FILE} уже есть ({via}) — не трогаю "
              "(--force пересоздаёт). Дальше: skiller sync")
        return
    _cfg, profile_name, _created = materialize_skillset_config(
        env, target, opts, dry=opts["dry_run"], force=True)
    if not opts["dry_run"]:
        print(f"  профиль: {profile_name or '-'}. Отредактируй "
              "include/buckets/exclude и примени: skiller sync")


def cmd_sync(env, argv):
    opts = parse_flags(argv, {"--target": "str", "--dry-run": "bool",
                              "--force": "bool", "--hub": "bool",
                              "--no-hub": "bool", "--no-core": "bool"})
    if opts["help"]:
        print("skiller sync [--target DIR] [--dry-run] [--force] "
              "[--hub] [--no-hub] [--no-core]\n"
              "  Применяет .swissknifeman/config.json (mode=vendor): копирует "
              "скиллы из библиотеки в проект, пишет skills-lock.json (managed),\n"
              "  манифест .swissknifeman-manifest.json и удаляет выбывшие "
              "managed-скиллы. Чужие скиллы не трогает (--force перетирает\n"
              "  занятый чужим путь версией из библиотеки). CORE-скиллы "
              "раздаются по умолчанию (--no-core отключает). Индекс скиллов\n"
              "  (managed-блок CLAUDE.md / .ai/guidelines) обновляется, если он "
              "уже есть в проекте или передан --hub; --no-hub отключает.")
        return
    target, via = resolve_target(env, opts, allow_home_confirm=True)
    cfg = load_skillset_config(target)
    if cfg is None:
        die(f"{skillset_config_path(target)} не найден — создайте конфиг "
            "vendor-режима (mode=vendor, include/buckets/exclude)")

    plan = sync_skillset(env, target, cfg, dry_run=opts["dry_run"],
                         force=opts["force"], include_core=not opts["no_core"])
    prefix = "[dry-run] " if opts["dry_run"] else ""
    n_repl = len(plan["conflicts"]) if opts["force"] else 0
    print(f"{prefix}sync ({via}): +{len(plan['add'])} ~{len(plan['update'])} "
          f"-{len(plan['remove'])} ={len(plan['keep'])}"
          + (f" !{n_repl}" if n_repl else "")
          + f" (skills_path: {plan['skills_path']})")
    if plan["conflicts"] and not opts["force"]:
        print(f"  конфликты (чужие, пропущены): {', '.join(plan['conflicts'])} "
              "— --force чтобы заменить")
    if plan["skipped"]:
        print(f"  пропущено (нет в реестре): {', '.join(plan['skipped'])}")

    # Индекс скиллов в корне проекта: догоняем поведение vendor — обновляем,
    # если хаб уже есть или запрошен явно. --no-hub перебивает автоопределение.
    want_hub = opts["hub"] or (hub_artifacts_exist(target)
                               and not opts["no_hub"])
    if want_hub and not opts["dry_run"]:
        generate_hub(env, target)
