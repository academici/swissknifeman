def integer_literal_schema(value, placement):
    node = schema()
    literal = {"type": "integer", "const": value}
    if placement == "alias":
        for key in ("properties", "required", "additionalProperties"):
            node.pop(key)
        node.update(literal)
        node["x-skm-codegen"]["python"]["kind"] = "alias"
    elif placement == "reference":
        node["$defs"] = {"Number": literal}
        node["properties"]["value"] = {"$ref": "#/$defs/Number"}
    else:
        node["properties"]["value"] = {
            "const": literal,
            "enum": {"type": "integer", "enum": [0, value]},
            "array": {"type": "array", "items": literal},
            "map": {"type": "object", "additionalProperties": literal},
            "union": {"anyOf": [literal, {"type": "null"}]},
            "tuple": {"type": "array", "prefixItems": [literal], "minItems": 1, "maxItems": 1},
        }[placement]
    return node


