// TypeScript types of the gui contracts: `gui schemas bundle` (self-contained schemas, no external $ref) →
// json-schema-to-typescript → src/contracts/generated/<contract>.ts (kept in git).
// `--check` compares with the files in git and exits 1 on any difference (golden).
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const frontend = join(here, "..");
const outDir = join(frontend, "src", "contracts", "generated");
const gui = join(frontend, "..", "bin", "gui");
const check = process.argv.includes("--check");

const bundleDir = mkdtempSync(join(tmpdir(), "gui-schemas-"));
try {
  execFileSync(gui, ["schemas", "bundle", "--out", bundleDir], { stdio: ["ignore", "ignore", "inherit"] });
  const files = readdirSync(bundleDir).filter((name) => name.endsWith(".schema.json")).sort();
  const produced = new Map();
  for (const file of files) {
    const contract = file.replace(/\.schema\.json$/, "");
    const schema = JSON.parse(readFileSync(join(bundleDir, file), "utf8"));
    const name = contract.replace(/(^|-)([a-z])/g, (_, __, letter) => letter.toUpperCase());
    const ts = await compile({ ...schema, title: name }, name, {
      bannerComment: `/* Generated by scripts/gen-types.mjs from the gui contract ${contract}/v1; do not edit. */`,
      additionalProperties: false,
      strictIndexSignatures: true,
      unreachableDefinitions: false,
      ignoreMinAndMaxItems: true,
      format: true,
      style: { printWidth: 120, singleQuote: false },
    });
    produced.set(`${contract}.ts`, ts);
  }
  if (check) {
    const stale = [];
    for (const [file, text] of produced) {
      const path = join(outDir, file);
      if (!existsSync(path) || readFileSync(path, "utf8") !== text) stale.push(file);
    }
    const extra = existsSync(outDir) ? readdirSync(outDir).filter((file) => !produced.has(file)) : [];
    if (stale.length || extra.length) {
      console.error(`generated contract types are stale: ${[...stale, ...extra].join(", ")}; run npm run gen:types`);
      process.exit(1);
    }
    console.log(`contract types: ${produced.size} up to date`);
  } else {
    mkdirSync(outDir, { recursive: true });
    for (const file of readdirSync(outDir)) if (!produced.has(file)) rmSync(join(outDir, file));
    for (const [file, text] of produced) writeFileSync(join(outDir, file), text);
    console.log(`contract types: wrote ${produced.size}`);
  }
} finally {
  rmSync(bundleDir, { recursive: true, force: true });
}
