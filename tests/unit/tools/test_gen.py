def conditional_module(monkeypatch, *, mode_required=True, guard_required=()):
    """A record whose nullable ``base`` is required only while ``mode`` is ``fork``."""
    node = schema("Conditional")
    node["properties"] = {
        "mode": {"enum": ["fork", "fresh"]},
        "base": {"type": ["string", "null"]},
        "note": {"type": "string"},
    }
    node["required"] = ["mode"] if mode_required else []
    guard: dict[str, Any] = {"properties": {"mode": {"const": "fork"}}}
    if guard_required:
        guard["required"] = list(guard_required)
    node["allOf"] = [
        True,
        {"if": guard, "then": {"required": ["base", "note"]}},
        {
            "if": {"properties": {"mode": {"const": "fresh"}, "note": {"const": "x"}}},
            "then": {"required": ["base"]},
        },
    ]
    model = normalize({node["$id"]: node})
    module = ModuleType(node["x-skm-codegen"]["python"]["module"])
    monkeypatch.setitem(sys.modules, module.__name__, module)
    declarations = list(model.declarations.values())
    text = render_python.render(model, declarations, "# test", "test")
    exec(compile(text, "<conditional>", "exec"), module.__dict__)  # noqa: S102
    return model.declarations[node["$id"] + "#"], module, text


def test_conditionally_required_nullable_field_keeps_its_explicit_null(monkeypatch):
    declaration, module, text = conditional_module(monkeypatch)
    rules = {f.wire: f.required_when for f in declaration.fields}
    # Only the single-const condition is recognized, and only the nullable optional field carries it.
    assert rules == {"mode": (), "base": (("mode", "fork", True),), "note": ()}
    assert "_REQUIRED_WHEN_Conditional = (('base', 'mode', 'fork', True),)" in text
    forked = module.Conditional.from_json({"mode": "fork", "base": None, "note": "n"})
    assert forked.base is None
    assert forked.to_json() == {"mode": "fork", "base": None, "note": "n"}
    with pytest.raises(ValueError, match="missing field 'base' required when 'mode' is 'fork'"):
        module.Conditional.from_json({"mode": "fork", "note": "n"})
    fresh = module.Conditional.from_json({"mode": "fresh"})
    assert fresh.to_json() == {"mode": "fresh"}  # outside the condition absence stays absence


