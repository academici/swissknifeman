"""The TypedDicts generated from the orch schemas (``orch._types``) agree with the schemas: for every kind whose root
is an object, the keys of the class are the ``properties`` of the schema and the required keys are its ``required``.
The modules are generated by ``aicore schema codegen`` (``configs/schema-types.json``); a hand edit or a stale module
breaks these tests (and ``python3 scripts/schema-types.py --check``)."""
from __future__ import annotations

import importlib
import json
from pathlib import Path
import typing
import unittest

ROOT = Path(__file__).resolve().parents[1]
SCHEMAS = ROOT / "schemas"
# schema directory -> generated module
MODULES = {"records": "records", "conductor": "conductor", "exec": "exec", "work-source": "work_source"}
# Roots that are no TypedDict, with the reason: the schema has no fixed key set, or the root has no type of its own.
NOT_CLASSES = {
    "records/item-routes": "route labels are dynamic keys (patternProperties): a Dict",
    "exec/defs": "definitions only",
    "work-source/input": "oneOf of two documents: a Union",
    "work-source/output": "oneOf of two documents: a Union",
}


def camel(kind: str) -> str:
    return "".join(word[:1].upper() + word[1:] for word in kind.replace("_", "-").split("-"))


def schema_files():
    for directory, module in MODULES.items():
        for path in sorted((SCHEMAS / directory / "v1").glob("*.schema.json")):
            yield directory, module, path


class GeneratedTypesMatchSchemas(unittest.TestCase):
    def test_every_object_root_is_a_typed_dict_with_the_keys_of_its_schema(self):
        checked = 0
        for directory, module_name, path in schema_files():
            kind = path.name[: -len(".schema.json")]
            key = f"{directory}/{kind}"
            if key in NOT_CLASSES:
                continue
            with self.subTest(kind=key):
                schema = json.loads(path.read_text(encoding="utf-8"))
                module = importlib.import_module(f"orch._types.{module_name}")
                cls = getattr(module, camel(kind), None)
                self.assertIsNotNone(cls, f"{key}: no class {camel(kind)} in orch._types.{module_name}")
                self.assertTrue(typing.is_typeddict(cls), f"{key}: {cls!r} is not a TypedDict")
                properties = set(schema.get("properties", {}))
                required = set(schema.get("required", ()))
                self.assertEqual(properties, set(cls.__required_keys__) | set(cls.__optional_keys__), key)
                self.assertEqual(required, set(cls.__required_keys__), key)
                self.assertEqual(properties - required, set(cls.__optional_keys__), key)
                checked += 1
        self.assertEqual(len(list(schema_files())) - len(NOT_CLASSES), checked)

    def test_the_roots_that_are_no_classes_are_exactly_the_listed_ones(self):
        found = set()
        for directory, module_name, path in schema_files():
            kind = path.name[: -len(".schema.json")]
            module = importlib.import_module(f"orch._types.{module_name}")
            cls = getattr(module, camel(kind), None)
            if cls is None or not typing.is_typeddict(cls):
                found.add(f"{directory}/{kind}")
        self.assertEqual(set(NOT_CLASSES), found)

    def test_a_definition_is_a_class_of_its_own(self):
        records = importlib.import_module("orch._types.records")
        self.assertTrue(typing.is_typeddict(records.QuestionsEntry))
        schema = json.loads((SCHEMAS / "records" / "v1" / "questions.schema.json").read_text(encoding="utf-8"))
        entry = schema["$defs"]["entry"]
        self.assertEqual(set(entry.get("required", ())), set(records.QuestionsEntry.__required_keys__))

    def test_the_documents_the_run_store_keeps_are_typed_dicts(self):
        records = importlib.import_module("orch._types.records")
        for name in ("Run", "State", "Questions", "Lease"):
            with self.subTest(name=name):
                self.assertTrue(typing.is_typeddict(getattr(records, name)))
        self.assertIn("status", records.State.__optional_keys__ | records.State.__required_keys__)

    def test_a_closed_step_keeps_the_required_status_of_the_open_envelope_it_refers_to(self):
        records = importlib.import_module("orch._types.records")
        schema = json.loads((SCHEMAS / "records" / "v1" / "state.schema.json").read_text(encoding="utf-8"))
        envelope = schema["$defs"]["step-envelope"]
        step = records.StateStepAny
        self.assertTrue(typing.is_typeddict(step))
        self.assertEqual(set(envelope["required"]), set(step.__required_keys__))
        self.assertEqual(set(envelope["properties"]), set(step.__required_keys__) | set(step.__optional_keys__))
        self.assertEqual(typing.Literal["started", "done", "stopped"], typing.get_type_hints(step)["status"])

    def test_the_run_store_and_questions_are_annotated_with_them(self):
        from orch._types.records import Questions, Run, State
        from orch.conductor import questions
        from orch.conductor.infrastructure.files import RunStore

        self.assertEqual(typing.Optional[Questions], typing.get_type_hints(questions.read)["return"])
        self.assertEqual(tuple[Run, State], typing.get_type_hints(RunStore.load)["return"])
        self.assertEqual(State, typing.get_type_hints(RunStore.save)["state"])


if __name__ == "__main__":
    unittest.main()
