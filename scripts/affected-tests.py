#!/usr/bin/env python3
"""The tests a change needs, and no others: modules touched by the changed paths and the units that depend on them.

    affected-tests.py [--base REF] [--paths P ...] [--tier fast|full|all] [--with-tools] [--run] [-j N] [--json]

Changed paths come from ``git status`` (the working tree), or from ``git diff --name-only REF`` with ``--base``, or from
``--paths``. Each path belongs to the unit whose folder is its longest prefix (``packages/<id>``, ``bridges/<id>``); other
paths belong to the hub. The affected set is the touched units plus the units that require a touched one (a bridge follows
its partners); a change of the foundation (``aicore``) affects every unit. A *tool* (``standalone.tools`` of
``configs/ecosystem-units.json``, e.g. ``maind``) is tested only when its own files changed or ``--with-tools`` is given: it
never joins the tests of the core because a core module changed.

Tiers: ``fast`` runs ``dev.test`` of the affected units (and the hub checks of the hub paths that changed); ``full`` adds
``dev.validate``; ``all`` is every unit that is not a tool — the full pass for the end of a phase. Without ``--run`` the
commands are only printed (one per line, ``<folder>: <command>``), ``--json`` prints them as a document.

Hub paths bring their own checks: always ``ecosystem-units check`` and ``public-hygiene``; ``golden.py check`` when a
generated surface can move (skills, configs, bootstrap, command catalogs, unit manifests) and with any change inside a
unit (its help and generated bytes are golden; seconds); ``scripts/test-<name>.py`` when
``scripts/<name>.*`` or the test itself changed.

A green result is remembered (``--run``, tiers ``fast`` and ``full``): the key is the command and the content of the
unit, of every unit it requires and of the foundation (tracked bytes plus the changes of the tree). The modules import
nothing of each other, so the same content gives the same verdict; an unchanged unit is not run again. The cache lives in
the git directory (``affected-tests/``) and is never used by ``--tier all``, the full pass that must run everything;
``--no-cache`` turns it off.
"""
from __future__ import annotations

import argparse
import contextlib
import hashlib
import json
import os
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HUB_CHECKS = [["python3", "scripts/ecosystem-units.py", "check"], ["python3", "scripts/public-hygiene.py"]]
GOLDEN = ["python3", "scripts/golden.py", "check"]
# a change below these prefixes (or of a unit manifest, a SKILL.md, a command catalog) can move a generated surface
GOLDEN_PREFIXES = ("bootstrap/", ".claude/", ".agents/", ".cursor/", "configs/", "golden/", "tests/golden/")
GOLDEN_NAMES = ("SKILL.md", "unit.json", "command-routing.json", "launch-catalog.json")


def units() -> dict:
    found = {}
    for pattern in ("packages/*/unit.json", "bridges/*/unit.json"):
        for path in sorted(ROOT.glob(pattern)):
            doc = json.loads(path.read_text(encoding="utf-8"))
            found[path.parent.relative_to(ROOT).as_posix()] = doc
    return found


def changed_paths(args) -> list:
    if args.paths:
        return list(args.paths)
    if args.base:
        out = subprocess.run(["git", "diff", "--name-only", args.base], cwd=ROOT, capture_output=True, text=True, check=True).stdout
        return [line for line in out.splitlines() if line]
    out = subprocess.run(["git", "status", "--porcelain=v1", "-z", "--untracked-files=all"], cwd=ROOT, capture_output=True,
                         text=True, check=True).stdout.split("\0")
    paths, index = [], 0
    while index < len(out):
        entry = out[index]
        index += 1
        if not entry:
            continue
        if entry[0] in "RC":
            index += 1
        paths.append(entry[3:])
    return paths


def hub_checks(paths: list) -> list:
    """The checks of the hub paths among ``paths`` (none when no path is outside a unit)."""
    found = [list(argv) for argv in HUB_CHECKS]
    if any(path.startswith(GOLDEN_PREFIXES) or Path(path).name in GOLDEN_NAMES or "/dev-skills/" in path
           or "/skills/" in path for path in paths):
        found.append(list(GOLDEN))
    for path in paths:
        name = Path(path)
        if name.parent.as_posix() != "scripts":
            continue
        test = name if name.name.startswith("test-") else name.with_name(f"test-{name.stem}.py")
        if test.suffix == ".py" and (ROOT / test).is_file():
            argv = ["python3", test.as_posix()]
            if argv not in found:
                found.append(argv)
    return found


def select(all_units: dict, foundation: str, tools: set, paths: list, tier: str, with_tools: bool) -> tuple:
    """``(folders to test, hub touched)``."""
    ids = {folder: doc.get("id", folder.split("/")[-1]) for folder, doc in all_units.items()}
    by_id = {value: folder for folder, value in ids.items()}
    if tier == "all":
        return sorted(f for f in all_units if f.split("/")[-1] not in tools or with_tools), True
    touched, hub = set(), False
    for path in paths:
        owner = max((f for f in all_units if path == f or path.startswith(f + "/")), key=len, default=None)
        if owner:
            touched.add(owner)
        else:
            hub = True
    chosen = set(touched)
    if any(ids[f] == foundation for f in touched):  # the foundation: everything depends on it
        chosen |= set(all_units)
    changed = True
    while changed:  # whoever requires an affected unit is affected too
        changed = False
        for folder, doc in all_units.items():
            required = {r.get("unit") for r in doc.get("requires") or () if isinstance(r, dict)}
            if folder not in chosen and any(by_id.get(r) in chosen for r in required):
                chosen.add(folder)
                changed = True
    kept = {f for f in chosen if f.split("/")[-1] not in tools or f in touched or with_tools}
    return sorted(kept), hub


def commands(all_units: dict, folders: list, hub: bool, tier: str, paths: list = ()) -> list:
    plan = []
    for folder in folders:
        dev = all_units[folder].get("dev") or {}
        names = ("test",) if tier == "fast" else ("test", "validate")
        plan += [(folder, dev[name]) for name in names if dev.get(name)]
    if tier == "all":
        plan += [("hub", argv) for argv in HUB_CHECKS + [GOLDEN]]
    elif hub:
        owned = [path for path in paths if not any(path == f or path.startswith(f + "/") for f in all_units)]
        plan += [("hub", argv) for argv in hub_checks(owned)]
    # The golden fixtures record the help and the generated bytes of the units, so a change inside a unit can move
    # them too (a new verb, a role in the launch catalog): the check is cheap (seconds) and runs with the unit, not
    # only at the end of a phase.
    if folders and tier != "all" and GOLDEN not in [argv for _, argv in plan]:
        plan.append(("hub", list(GOLDEN)))
    return plan


def requirements(all_units: dict, folder: str, foundation: str) -> list:
    """``folder`` and every unit folder it requires, transitively, plus the foundation."""
    by_id = {doc.get("id", f.split("/")[-1]): f for f, doc in all_units.items()}
    seen, todo = set(), [folder]
    while todo:
        current = todo.pop()
        if current in seen:
            continue
        seen.add(current)
        for entry in all_units.get(current, {}).get("requires") or ():
            unit = entry.get("unit") if isinstance(entry, dict) else entry
            if by_id.get(unit):
                todo.append(by_id[unit])
    if by_id.get(foundation):
        seen.add(by_id[foundation])
    return sorted(seen)


def content_key(folders: list, command: list) -> str:
    """The working-tree bytes and executable modes a command reads, independent of staging and commits."""
    digest = hashlib.sha256(json.dumps([command, sys.version.split()[0], folders]).encode("utf-8"))
    names = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z", "--", *folders], cwd=ROOT,
                               capture_output=True, check=True).stdout.split(b"\0")
    for name in sorted(set(item for item in names if item)):
        path = ROOT / os.fsdecode(name)
        if not path.exists() and not path.is_symlink():
            continue  # an unstaged deletion and its committed state are the same candidate
        digest.update(b"\0" + name)
        try:
            digest.update(str(path.lstat().st_mode & 0o170111).encode("ascii"))
            digest.update(os.fsencode(os.readlink(path)) if path.is_symlink() else path.read_bytes())
        except OSError:
            digest.update(b"?")
    return digest.hexdigest()


def cache_file() -> Path:
    common = subprocess.run(["git", "rev-parse", "--path-format=absolute", "--git-common-dir"], cwd=ROOT,
                            capture_output=True, text=True, check=True).stdout.strip()
    primary = Path(common) / "affected-tests" / "green.json"
    try:
        primary.parent.mkdir(parents=True, exist_ok=True)
        probe = primary.parent / f".probe-{os.getpid()}"
        probe.write_text("", encoding="utf-8")
        probe.unlink()
        return primary
    except OSError:  # a read-only git directory (a sandboxed check): the cache moves to the temporary folder
        key = hashlib.sha256(str(ROOT).encode("utf-8")).hexdigest()[:16]
        return Path(tempfile.gettempdir()) / "skm-affected-tests" / key / "green.json"


def read_cache(path: Path) -> dict:
    try:
        found = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return found if isinstance(found, dict) else {}


def bridge_env() -> dict:
    """The partners a bridge finds through the environment, wired from the hub layout (as scripts/test-bridges.sh does)."""
    env = dict(os.environ)
    packages = ROOT / "packages"
    env.update({"PLANNER_ROOT": str(packages / "planner"), "PLANNER_PLAN_PY": str(packages / "planner/scripts/plan.py"),
                "SKM_ORCH_ROOT": str(packages / "orch"), "SKM_SKILLER_ROOT": str(packages / "skiller"),
                "SKM_HARNESS_ROOT": str(packages / "harness"), "AICORE_ROOT": str(packages / "aicore")})
    return env


@contextlib.contextmanager
def command_env(folder: str, command: list):
    """The environment of one command. ``validate.sh`` of a module calls the guarded CLIs of the clone (``skiller registry
    --check``), which refuse the real HOME, so it runs with a throwaway one, as scripts/dev-sandbox.sh sets it up."""
    env = bridge_env() if folder.startswith("bridges/") else dict(os.environ)
    if command[-1:] != ["scripts/validate.sh"]:
        yield env
        return
    with tempfile.TemporaryDirectory(prefix="skm-validate-home-") as home:
        env.update({"HOME": home, "XDG_CONFIG_HOME": f"{home}/.config", "XDG_STATE_HOME": f"{home}/.local/state",
                    "XDG_DATA_HOME": f"{home}/.local/share", "XDG_CACHE_HOME": f"{home}/.cache",
                    "SKM_HOME": f"{home}/.swissknifeman-home", "GIT_CONFIG_GLOBAL": f"{home}/.gitconfig"})
        yield env


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--base")
    parser.add_argument("--paths", nargs="*")
    parser.add_argument("--tier", choices=["fast", "full", "all"], default="fast")
    parser.add_argument("--with-tools", action="store_true")
    parser.add_argument("--run", action="store_true")
    parser.add_argument("-j", "--jobs", type=int, default=3)
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--no-cache", dest="cache", action="store_false",
                        help="run every command even when its content was green before")
    args = parser.parse_args(argv)
    config = json.loads((ROOT / "configs" / "ecosystem-units.json").read_text(encoding="utf-8"))
    tools = set((config.get("standalone") or {}).get("tools") or ())
    all_units = units()
    foundation = (config.get("foundation") or {}).get("id", "aicore")
    paths = [] if args.tier == "all" else changed_paths(args)
    folders, hub = select(all_units, foundation, tools, paths, args.tier, args.with_tools)
    plan = commands(all_units, folders, hub, args.tier, paths)
    if args.json:
        print(json.dumps({"tier": args.tier, "units": folders, "hub": hub,
                          "commands": [{"folder": f, "argv": a} for f, a in plan]}, indent=2))
    else:
        for folder, command in plan:
            print(f"{folder}: {' '.join(command)}")
    if not args.run:
        return 0

    use_cache = args.cache and args.tier != "all"
    store = cache_file() if use_cache else None
    green = read_cache(store) if store else {}
    # the commands share the machine: each test runner gets its part of the cores, not all of them
    share = str(max(1, (os.cpu_count() or 2) // max(1, min(args.jobs, len(plan) or 1))))

    def key_of(folder, command):
        reads = requirements(all_units, folder, foundation) if folder != "hub" else ["."]
        return content_key(reads, command) if use_cache and folder != "hub" else None

    def run(item):
        folder, command = item
        key = key_of(folder, command)
        if key and key in green:
            return folder, command, None, key
        cwd = ROOT if folder == "hub" else ROOT / folder
        with command_env(folder, command) as env:
            env.setdefault("SKM_TEST_JOBS", share)
            done = subprocess.run(command, cwd=cwd, capture_output=True, text=True, env=env)
        return folder, command, done, key

    failed = 0
    with ThreadPoolExecutor(max_workers=max(1, args.jobs)) as pool:
        for folder, command, done, key in pool.map(run, plan):
            if done is None:
                print(f"[cached] {folder}: {' '.join(command)}", flush=True)
                continue
            state = "ok" if done.returncode == 0 else "FAIL"
            print(f"[{state}] {folder}: {' '.join(command)}", flush=True)
            if done.returncode:
                failed += 1
                sys.stderr.write((done.stdout + done.stderr)[-3000:])
            elif key:
                green[key] = {"folder": folder, "command": command}
    if store and green:
        store.parent.mkdir(parents=True, exist_ok=True)
        store.write_text(json.dumps(green, sort_keys=True), encoding="utf-8")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
