class GeneratedHandlersCase(Base):
    """The Cursor and Codex/Grok dispatchers read the carrier: the provider key first."""

    def cursor(self, mode_lines, legacy=None):
        self.carrier.parent.mkdir(parents=True, exist_ok=True)
        self.carrier.write_text("# g\n" + "".join(line + "\n" for line in mode_lines), encoding="utf-8")
        if legacy is not None:
            (self.proj / ".cursor").mkdir(exist_ok=True)
            (self.proj / ".cursor" / "git-guardrails.env.ini").write_text(legacy, encoding="utf-8")
        handler = self.tmp / "cursor-lifecycle.py"
        handler.write_bytes(hooks.render_cursor_hook_handler())
        payload = {"hook_event_name": "beforeShellExecution", "conversation_id": "c", "cwd": str(self.proj),
                   "workspace_roots": [str(ROOT)], "command": "git reset --hard HEAD~1"}
        done = subprocess.run([sys.executable, str(handler), "--surface", "lifecycle.git-guardrails"],
                              input=json.dumps(payload).encode(), capture_output=True, timeout=20)
        return json.loads(done.stdout)["permission"]

    def test_cursor_handler(self):
        self.assertEqual(self.cursor(["GIT_GUARDRAILS_MODE=strict"]), "deny")
        self.assertEqual(self.cursor(["GIT_GUARDRAILS_MODE=strict", "GIT_GUARDRAILS_MODE__CURSOR=off"]), "allow")
        self.assertEqual(self.cursor(["GIT_GUARDRAILS_MODE=off", "GIT_GUARDRAILS_MODE__CODEX=strict"]), "allow")
        self.assertEqual(self.cursor([], legacy="MODE=strict\n"), "deny")
        self.assertEqual(self.cursor(["GIT_GUARDRAILS_MODE__CURSOR=off"], legacy="MODE=strict\n"), "allow")

    def codex(self, provider, lines, legacy=None):
        self.carrier.parent.mkdir(parents=True, exist_ok=True)
        self.carrier.write_text("# g\n" + "".join(line + "\n" for line in lines), encoding="utf-8")
        state = ".codex" if provider == "codex" else ".grok"
        if legacy is not None:
            (self.proj / state).mkdir(exist_ok=True)
            (self.proj / state / "git-guardrails.env.ini").write_text(legacy, encoding="utf-8")
        handler = self.tmp / f"{provider}-lifecycle.py"
        handler.write_bytes(hooks.render_codex_hook_handler(state_dir=state))
        payload = {"session_id": "s", "cwd": str(self.proj), "model": "m", "hook_event_name": "PreToolUse",
                   "tool_name": "Bash", "tool_input": {"command": "git reset --hard HEAD~1"}}
        env = {**os.environ, "PATH": f"{ROOT / 'bin'}:{os.environ.get('PATH', '')}"}
        return subprocess.run([sys.executable, str(handler), "--surface", "lifecycle.git-guardrails"],
                              input=json.dumps(payload).encode(), capture_output=True, env=env,
                              timeout=20).returncode

    def test_codex_and_grok_handlers(self):
        for provider, other in (("codex", "GROK"), ("grok", "CODEX")):
            with self.subTest(provider=provider):
                key = provider.upper()
                self.assertEqual(self.codex(provider, ["GIT_GUARDRAILS_MODE=strict"]), 2)
                self.assertEqual(self.codex(provider, ["GIT_GUARDRAILS_MODE=strict",
                                                       f"GIT_GUARDRAILS_MODE__{key}=off"]), 0)
                self.assertEqual(self.codex(provider, ["GIT_GUARDRAILS_MODE=off",
                                                       f"GIT_GUARDRAILS_MODE__{other}=strict"]), 0)
                self.assertEqual(self.codex(provider, [], legacy="MODE=strict\n"), 2)


