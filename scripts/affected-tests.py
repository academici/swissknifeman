ROOT = Path(__file__).resolve().parents[1]
HUB_CHECKS = [["python3", "scripts/ecosystem-units.py", "check"], ["python3", "scripts/public-hygiene.py"]]
GOLDEN = ["python3", "scripts/golden.py", "check"]
# a change below these prefixes (or of a unit manifest, a SKILL.md, a command catalog) can move a generated surface
GOLDEN_PREFIXES = ("bootstrap/", ".claude/", ".agents/", ".cursor/", "configs/", "golden/", "tests/golden/")
GOLDEN_NAMES = ("SKILL.md", "unit.json", "command-routing.json", "launch-catalog.json")


def units() -> dict:
    found = {}
    for pattern in ("packages/*/unit.json", "bridges/*/unit.json"):
        for path in sorted(ROOT.glob(pattern)):
            doc = json.loads(path.read_text(encoding="utf-8"))
            found[path.parent.relative_to(ROOT).as_posix()] = doc
    return found


def changed_paths(args) -> list:
    if args.paths is not None:
        return list(args.paths)
    if args.base:
        entries = subprocess.run(["git", "diff", "--name-status", "-z", args.base], cwd=ROOT,
                                 capture_output=True, text=True, check=True).stdout.split("\0")
        paths, index = [], 0
        while index < len(entries) and entries[index]:
            status = entries[index]
            count = 2 if status[0] in "RC" else 1
            paths.extend(entries[index + 1:index + count + 1])
            index += count + 1
        paths += subprocess.run(["git", "ls-files", "--others", "--exclude-standard", "-z"], cwd=ROOT,
                                capture_output=True, text=True, check=True).stdout.split("\0")
        return list(dict.fromkeys(p for p in paths if p))
    out = subprocess.run(["git", "status", "--porcelain=v1", "-z", "--untracked-files=all"], cwd=ROOT, capture_output=True,
                         text=True, check=True).stdout.split("\0")
    paths, index = [], 0
    while index < len(out):
        entry = out[index]
        index += 1
        if not entry:
            continue
        if "R" in entry[:2] or "C" in entry[:2]:
            paths.append(out[index])
            index += 1
        paths.append(entry[3:])
    return paths


def owner(all_units: dict, path: str):
    return max((f for f in all_units if path == f or path.startswith(f + "/")), key=len, default=None)


def profile(all_units: dict, foundation: str, path: str) -> str:
    folder = owner(all_units, path)
    if not folder:
        if path in ("docs/develop.md", "CHANGELOG.md", "CONTRIBUTING.md"):
            return "documentation"
        name = Path(path)
        if name.parent.as_posix() == "scripts" and name.stem not in (
                "affected-tests", "test-affected-tests", "ci-matrix", "test-ci-matrix", "ecosystem-units",
                "test-bridges", "golden", "schema-types") and (
                (ROOT / name.with_name(f"test-{name.stem}.py")).is_file() or name.name.startswith("test-")):
            return "hub-check"
        return "unknown"
    relative = path[len(folder) + 1:]
    if all_units[folder].get("id") == foundation or relative.startswith(("schemas/", "schema/")):
        return "foundation-schema"
    if relative.startswith("tests/"):
        return "test-only" if Path(path).name.startswith("test_") and path.endswith(".py") else "unknown"
    if relative.startswith(("scripts/", "bin/")) or Path(path).name == "cli.py":
        return "cli"
    if relative == "unit.json" or relative.startswith(("configs/", "_vendor/")):
        return "packaging-install"
    if folder.startswith("bridges/"):
        return "cross-module"
    if relative.startswith("lib/"):
        return "module-logic"
    # Product instructions, templates, skills and module docs can have executable consumers.
    return "unknown"


def hub_checks(paths: list) -> list:
    """The checks of the hub paths among ``paths`` (none when no path is outside a unit)."""
    found = [list(argv) for argv in HUB_CHECKS]
    if any(path.startswith(GOLDEN_PREFIXES) or Path(path).name in GOLDEN_NAMES or "/dev-skills/" in path
           or "/skills/" in path for path in paths):
        found.append(list(GOLDEN))
    for path in paths:
        name = Path(path)
        if name.parent.as_posix() != "scripts":
            continue
        test = name if name.name.startswith("test-") else name.with_name(f"test-{name.stem}.py")
        if test.suffix == ".py" and (ROOT / test).is_file():
            argv = ["python3", test.as_posix()]
            if argv not in found:
                found.append(argv)
    return found


def select(all_units: dict, foundation: str, tools: set, paths: list, tier: str, with_tools: bool) -> tuple:
    """``(folders to test, hub touched)``."""
    ids = {folder: doc.get("id", folder.split("/")[-1]) for folder, doc in all_units.items()}
    by_id = {value: folder for folder, value in ids.items()}
    touched, hub = set(), False
    for path in paths:
        folder = owner(all_units, path)
        if folder:
            touched.add(folder)
        else:
            hub = True
    chosen = set(touched)
    if tier == "all" or any(owner(all_units, p) is None and profile(all_units, foundation, p) == "unknown" for p in paths):
        chosen |= set(all_units)
        hub = True
    if any(ids[f] == foundation for f in touched):  # the foundation: everything depends on it
        chosen |= set(all_units)
    changed = True
    while changed:  # whoever requires an affected unit is affected too
        changed = False
        for folder, doc in all_units.items():
            required = {r.get("unit") if isinstance(r, dict) else r for r in doc.get("requires") or ()}
            if folder not in chosen and any(by_id.get(r) in chosen for r in required):
                chosen.add(folder)
                changed = True
    kept = {f for f in chosen if f.split("/")[-1] not in tools or f in touched or with_tools}
    return sorted(kept), hub


def commands(all_units: dict, folders: list, hub: bool, tier: str, paths: list = (), subsets=None) -> list:
    """Jobs are (cwd, [argv, ...]); test and validate of one unit share a worker."""
    plan = []
    for folder in folders:
        dev = all_units[folder].get("dev") or {}
        names = ("test",) if tier == "fast" else ("test", "validate")
        argv = [list(dev[name]) for name in names if dev.get(name)]
        if subsets and folder in subsets:
            argv = subsets[folder]
        if argv:
            plan.append((folder, argv))
    checks = []
    if tier == "all":
        checks += [list(argv) for argv in HUB_CHECKS + [GOLDEN]]
    elif hub:
        owned = [path for path in paths if not any(path == f or path.startswith(f + "/") for f in all_units)]
        checks += hub_checks(owned)
    # The golden fixtures record the help and the generated bytes of the units, so a change inside a unit can move
    # them too (a new verb, a role in the launch catalog): the check is cheap (seconds) and runs with the unit, not
    # only at the end of a phase.
    if folders and GOLDEN not in checks:
        checks.append(list(GOLDEN))
    return [("hub", [argv]) for i, argv in enumerate(checks) if argv not in checks[:i]] + plan


def obligations(all_units: dict, folders: list, paths: list, foundation: str, tier: str) -> tuple:
    """Only mapped, existing test files in runners with -p support qualify for an explicit subset."""
    subsets, explain = {}, []
    ids = {d.get("id", f.split("/")[-1]) for f, d in all_units.items()}
    known_edges = all((r.get("unit") if isinstance(r, dict) else r) in ids
                      for folder in folders for r in all_units[folder].get("requires") or ())
    for folder in folders:
        inputs = [p for p in paths if owner(all_units, p) == folder]
        kinds = sorted({profile(all_units, foundation, p) for p in inputs})
        reason = "owner full-suite fallback" if inputs else "declared dependency consumer contract"
        if tier == "all":
            reason = "tier-all full coverage"
        elif any(owner(all_units, p) is None and profile(all_units, foundation, p) == "unknown" for p in paths):
            reason = "unknown hub surface: full-unit fallback"
        dev = all_units[folder].get("dev") or {}
        if not known_edges:
            reason = "unmapped dependency edge: full-suite closure fallback"
        if (tier == "fast" and folder in ("packages/planner", "packages/orch") and kinds == ["test-only"]
                and known_edges and dev.get("test") == ["bash", "scripts/test.sh"]
                and leaf_tests(folder, inputs)):
            subsets[folder] = [[*dev["test"], "-p", name] for name in sorted({Path(p).name for p in inputs})]
            reason = "known test-file subset; dependent units retain full consumer contracts"
        explain.append({"folder": folder, "profiles": kinds or ["consumer"], "context": "partner" if
                        folder.startswith("bridges/") else "local", "inputs": inputs or list(paths),
                        "obligation": "explicit-subset" if folder in subsets else "full-suite", "reason": reason})
    return subsets, explain


def leaf_tests(folder: str, inputs: list) -> bool:
    """Imported test modules are shared fixtures, so their consumers require a broad suite."""
    if not inputs or not all((ROOT / p).is_file() and not (ROOT / p).is_symlink() for p in inputs):
        return False
    stems = {Path(p).stem for p in inputs}
    for path in (ROOT / folder / "tests").rglob("*.py"):
        if path.relative_to(ROOT).as_posix() in inputs:
            continue
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except (OSError, SyntaxError, UnicodeError):
            return False
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == "load_tests":
                return False
            if isinstance(node, ast.Call) and (getattr(node.func, "attr", "") == "import_module" or
                                              getattr(node.func, "id", "") == "__import__"):
                return False
            names = []
            if isinstance(node, ast.Import):
                names = [a.name for a in node.names]
            elif isinstance(node, ast.ImportFrom):
                names = [node.module or "", *(a.name for a in node.names)]
            if any(name.split(".")[-1] in stems for name in names):
                return False
    return True


def requirements(all_units: dict, folder: str, foundation: str) -> list:
    """``folder`` and every unit folder it requires, transitively, plus the foundation."""
    by_id = {doc.get("id", f.split("/")[-1]): f for f, doc in all_units.items()}
    seen, todo = set(), [folder]
    while todo:
        current = todo.pop()
        if current in seen:
            continue
        seen.add(current)
        for entry in all_units.get(current, {}).get("requires") or ():
            unit = entry.get("unit") if isinstance(entry, dict) else entry
            if by_id.get(unit):
                todo.append(by_id[unit])
    if by_id.get(foundation):
        seen.add(by_id[foundation])
    return sorted(seen)


