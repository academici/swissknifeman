"""Managed skill copies: the marker, the manifest, the lock, and the sync that applies a plan.

What a project receives when a skill is vendored: the copy of the skill directory with the managed marker
after its frontmatter, ``.swissknifeman-manifest.json`` next to the copies, ``skills-lock.json`` with a
record per managed skill (source, digest, install path), an optional ``.gitignore`` of the managed
copies. :func:`sync_skillset` applies an already computed plan (add, update, remove, keep, conflicts) to
a project. Choosing which skills a project wants, and planning, stay with the caller. stdlib only.
"""
import hashlib
import json
import shutil
from pathlib import Path

from ..content.skill import SKILL_IGNORE
from ..util.io import atomic_write_json, atomic_write_text, safe_load_json
from ..util.paths import is_within, is_within_lexical
from ..util.term import die, now_iso, warn

MANIFEST = ".swissknifeman-manifest.json"
MANIFEST_VERSION = 1
AGENT_DEFAULTS = {"claude": ".claude/skills", "cursor": ".cursor/skills",
                  "generic": ".ai/skills"}
SKILL_MANAGED_MARKER = "<!-- swissknifeman:managed -->"

LOCK_FILE = "skills-lock.json"
LOCK_VERSION = 1
SOURCE = "swissknifeman"

# Title-marker of the .gitignore (by it we identify «yours» file).
GITIGNORE_HEADER = "# Generated by `skiller sync` — DO NOT edit manually."


def split_bom(raw):
    """(bom, body) — cut BOM-prefix (if available) without normalizing the rest."""
    if raw.startswith(b"\xef\xbb\xbf"):
        return raw[:3], raw[3:]
    return b"", raw


def mark_skill_managed(dst):
    """Enter SKILL_MANAGED_MARKER immediately after the closing `---` frontmatter'a
    in `dst/SKILL.md`, BYTE MODE (without text-mode read/normalization `\\r\\n`→`\\n`) —
    old version read the file via `.read_text()`, because of which CRLF-skills
    written bytes diverged from the original ones and `hashlib.sha256(read_bytes())`
    registry (registry.py) detected a false drift on each sync. Idempotent
    (second call - no-op); no file/no frontmatter → quiet no-op (no crash)."""
    path = Path(dst) / "SKILL.md"
    if not path.is_file():
        return
    raw = path.read_bytes()
    bom, body = split_bom(raw)
    if body.startswith(b"---\r\n"):
        newline = b"\r\n"
    elif body.startswith(b"---\n"):
        newline = b"\n"
    else:
        return  # no frontmatter — not our file, skip
    delim = b"---" + newline
    close_idx = body.find(delim, len(delim))
    if close_idx == -1:
        return  # frontmatter not closed - malformed, pass
    insert_at = close_idx + len(delim)
    marker_bytes = SKILL_MANAGED_MARKER.encode("utf-8")
    if body[insert_at:insert_at + len(marker_bytes)] == marker_bytes:
        return  # already marked - idempotent no-op
    new_body = body[:insert_at] + marker_bytes + newline + body[insert_at:]
    path.write_bytes(bom + new_body)


def strip_skill_managed_marker(data):
    """Reverse to `mark_skill_managed` — remove marker string from bytes `data`
    (LF or CRLF), returning the original contents byte-for-byte. No marker -
    identity (is not a find, but a regular uninserted file)."""
    marker_bytes = SKILL_MANAGED_MARKER.encode("utf-8")
    for newline in (b"\r\n", b"\n"):
        pattern = marker_bytes + newline
        idx = data.find(pattern)
        if idx != -1:
            return data[:idx] + data[idx + len(pattern):]
    return data


def safe_copy_skill(src, dst, dest_root):
    """Safely copy skill directory src→dst inside dest_root. SINGLE copy path
    for vendor.do_vendor and skillset.sync_skillset (used to be duplicated, diverging into
    security details). Steps: lex. containment (traversal via '../' in name → stop),
    remove existing dst (symlink/file/dir, symlink DO NOT dereference), re-check
    against race (TOCTOU: someone else's process could recreate dst symlink outwards), copytree with
    SKILL_IGNORE. The destination must be a child of dest_root: replacing the whole root
    would remove sibling skills. Return True when copying, False when skipping (with warn)."""
    if not is_within_lexical(dst, dest_root, allow_root=False):
        warn(f"skip: path outside the destination directory: {dst}")
        return False
    if dst.is_symlink() or dst.is_file():
        dst.unlink()
    elif dst.is_dir():
        shutil.rmtree(dst)
    if dst.is_symlink() or dst.exists():
        warn(f"pass '{dst.name}': path recreated between deletion and copy (race)")
        return False
    shutil.copytree(src, dst, dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns(*SKILL_IGNORE))
    return True


def write_skill_manifest(manifest_file, *, profile, agent, layout, installed,
                         support_files=None):
    """ONE writer `.swissknifeman-manifest.json` — common for vendor.do_vendor and
    skillset.sync_skillset (used to be two independent writers with different designs:
    date-only timestamp without `version` y vendor, `now_iso`+`version` y skillset —
    audit V-4, update.detect_vendor_path reads both and could have encountered a discrepancy).
    The unchanged manifest retains the original installed_at and file bytes.
    Atomic (tmp+os.replace), `version` as the first key."""
    stable_data = {
        "profile": profile,
        "agent": agent,
        "layout": layout,
        "skills": installed,
    }
    if support_files is not None:
        stable_data["support_files"] = support_files
    existing = safe_load_json(manifest_file)
    if (isinstance(existing, dict)
            and existing.get("version") == MANIFEST_VERSION
            and isinstance(existing.get("installed_at"), str)
            and existing["installed_at"]
            and {key: value for key, value in existing.items()
                 if key not in {"version", "installed_at"}} == stable_data):
        return
    data = {"installed_at": now_iso(), **stable_data}
    atomic_write_json(manifest_file, data, version=MANIFEST_VERSION)


# --- lock ---------------------------------------------------------------------
def load_lock(target):
    f = Path(target) / LOCK_FILE
    if not f.is_file():
        return {}
    try:
        data = json.loads(f.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        # Broken lock was silently treated as empty → ALL managed-skills were considered new and
        # copied (extra work + confusing output). We warn you: we will rebuild from
        # config, but let it be visible (check git-file history).
        warn(f"{f}: broken JSON skills-lock — I ignore and rebuild from the config "
             f"(managed-skills can be copied). See The git-file history.")
        return {}
    if not isinstance(data, dict) or not isinstance(data.get("skills"), dict):
        warn(f"{f}: unexpected structure skills-lock (no dict 'skills') — I ignore, I will rebuild.")
        return {}
    return data


def lock_problem(target):
    """Return reason provenance-invalid lock or ``None``.

    Normal sync does not restore or overwrite damaged lock: without
    being checked provenance cannot be distinguished managed bytes from strangers. Legacy-lock
    without ``version`` and ``content_sha256`` remains readable, but unknown/newer
    version, provider-map and managed record pass fail-closed check.
    """
    f = Path(target) / LOCK_FILE
    if not f.is_file():
        return None
    try:
        data = json.loads(f.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError, OSError):
        return "invalid-json"
    if not isinstance(data, dict):
        return "root-not-object"
    version = data.get("version", LOCK_VERSION)
    if not isinstance(version, int) or version > LOCK_VERSION:
        return "unsupported-version"
    if not isinstance(data.get("skills"), dict):
        return "skills-map-invalid"
    providers = data.get("providers", {})
    if not isinstance(providers, dict) or any(not isinstance(items, dict)
                                              for items in providers.values()):
        return "provider-map-invalid"
    maps = [data["skills"], *providers.values()]
    for entries in maps:
        for name, record in entries.items():
            if not isinstance(name, str) or not isinstance(record, dict):
                return "record-invalid"
            if record.get("managed"):
                digest = record.get("sha256")
                if (record.get("source") != SOURCE
                        or not isinstance(digest, str)
                        or len(digest) != 64
                        or any(ch not in "0123456789abcdef" for ch in digest)
                        or not isinstance(record.get("installed_path"), str)):
                    return "managed-provenance-invalid"
    return None


def hash_label(value):
    """P2 diagnostic spelling for an existing bare lock digest."""
    return f"sha256:{value}" if value else "sha256:<missing>"


def write_lock(target, lock):
    atomic_write_json(Path(target) / LOCK_FILE, lock)


def dir_sha256(skill_dir):
    """sha256 SKILL.md — same base as in the registry (skills.json counts by file)."""
    md = Path(skill_dir) / "SKILL.md"
    if not md.is_file():
        return ""
    return hashlib.sha256(md.read_bytes()).hexdigest()


# --- sync ---------------------------------------------------------------------
def remove_path(path):
    """Demolish directory/file/symlink along the path (symlink is not dereferenced)."""
    if path.is_symlink() or path.is_file():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)


def sync_skillset(env, target, cfg, dry_run=False, force=False, repair=False,
                  include_core=False, provider="claude-code", plan=None, planner=None):
    """Apply config: copy new/updated, remove retired ones managed,
    rewrite skills-lock.json. Other people's skills remain as they are (conflicts
    are skipped with warning; --force grinds someone else's path with our skill).
    include_core=True — distribute CORE_SKILLS default (like vendor/connect).
    ``plan`` is what the caller planned; without one, ``planner(env, target, cfg, include_core=,
    provider=)`` plans it (the library and the selection rules belong to the caller)."""
    if plan is None:
        if planner is None:
            raise ValueError("sync_skillset needs a plan or a planner")
        plan = planner(env, target, cfg, include_core=include_core, provider=provider)
    if plan.get("provenance_invalid"):
        die(f"SPUB_OWNERSHIP_CONFLICT: provider {provider} channel vendor "
            f"target {plan['skills_path']} has invalid skills-lock provenance "
            f"({plan['provenance_invalid']}); repair: restore a valid lock backup")
    if plan.get("managed_drift") and not repair:
        names = ", ".join(plan["managed_drift"])
        die(f"SPUB_OWNERSHIP_CONFLICT: provider {provider} channel vendor "
            f"target {plan['skills_path']} has managed-drift: {names}; "
            "repair: rerun `skiller sync --repair`")
    dest_root = plan["dest_root"]
    entries = {e["name"]: e for e in plan["entries"]}
    lock = load_lock(target)
    locked = dict(lock.get("skills", {}) if provider == "claude-code"
                  else lock.get("providers", {}).get(provider, {}))

    def contained(path):
        return is_within(path, dest_root)

    # Conflicts with other people's ways: without force — pass; with force — add to install.
    install = list(plan["add"]) + list(plan["update"])
    if repair:
        install += list(plan.get("managed_drift", []))
    if plan["conflicts"]:
        if force:
            install += plan["conflicts"]
        else:
            likely_ours = set(plan.get("conflicts_likely_ours", []))
            for name in plan["conflicts"]:
                if name in likely_ours:
                    # sha256 matches the registry: rather interrupted past sync
                    # (files copied, lock didn't have time to sign up - V-6), and not
                    # really someone else's skill. We do NOT auto-adopt. (see plan_sync) — but
                    # the message should not be scary «strangers», when it's probably ours.
                    warn(f"conflict: '{name}' — folder already contains identical "
                         f"contents (sha256 matches the registry), but not in lock — "
                         f"looks like an interrupted past sync; --force safe "
                         f"will re-adopt")
                else:
                    warn(f"conflict: '{name}' busy with someone else's skill (not managed) — "
                         f"pass; --force to replace with the version from the library")

    # --- prune: only managed, removed from the config ---------------------------
    for name in plan["remove"]:
        stale = dest_root / name
        if dry_run:
            print(f"[dry-run] remove {stale}")
        elif (stale.is_symlink() or stale.exists()) and contained(stale):
            remove_path(stale)
        locked.pop(name, None)

    # --- prune: orphaned copies of the OLD skills_path (V-9) -----------------
    # Config changed skills_path — managed-entry (by installed_path in lock) may
    # point to a path OUTSIDE the current one dest_root. Without this pass, such copies will never
    # are not deleted: normal remove-the loop above only hits dest_root/name (new The
    # paths), a install-loop below will simply create a SECOND copy in a new location.
    target_root = Path(target)
    for old_rel_path in plan.get("relocated", {}).values():
        stale = target_root / old_rel_path
        if dry_run:
            print(f"[dry-run] remove (relocated) {stale}")
        elif (stale.is_symlink() or stale.exists()) and is_within(stale, target_root):
            remove_path(stale)

    # --- install / update -----------------------------------------------------
    if not dry_run:
        dest_root.mkdir(parents=True, exist_ok=True)
    installed_names, skip_copy, repair_evidence, pending_backups = [], [], [], {}
    for name in install:
        entry = entries[name]
        src = entry["skill_dir"]
        dst = dest_root / name
        if dry_run:
            verb = "add" if name in plan["add"] else \
                ("replace" if name in plan["conflicts"] else "update")
            print(f"[dry-run] {verb} {entry['bucket']}/{entry['name']} -> {dst}")
            continue
        if name in plan.get("managed_drift", []):
            skill_file = dst / "SKILL.md"
            expected_observed = plan["drift_hashes"][name]["observed"]
            if hash_label(dir_sha256(dst)) != expected_observed:
                die(f"SPUB_OWNERSHIP_CONFLICT: provider {provider} channel vendor "
                    f"target {plan['skills_path']}/{name} changed after planning; "
                    "repair: replan before `skiller sync --repair`")
            if expected_observed == hash_label(""):
                # Managed skill VANISHED from the project (dir deleted, or replaced by a
                # symlink): drift is classified at plan time by `not dst.is_dir()`, and
                # there are no local bytes to preserve. Demanding a pre-image here made
                # the ONLY repair path for a deleted managed skill unreachable — repair
                # died instead of restoring it. Nothing to back up is not a conflict.
                pass
            elif not skill_file.is_file():
                die(f"SPUB_OWNERSHIP_CONFLICT: provider {provider} channel vendor "
                    f"target {plan['skills_path']}/{name} has no recoverable pre-image")
            else:
                # safe_copy_skill replaces the directory, so preserve the exact bytes
                # immediately beside it until the new directory exists. Then move this
                # pending file to the P2-standard final backup path beside SKILL.md.
                pending = dst.parent / f".{name}.provider-artifact.bak.pending"
                shutil.copy2(skill_file, pending)
                pending_backups[name] = pending
        # Unified secure copy (containment + removal symlink/file/directory + TOCTOU-
        # recheck + SKILL_IGNORE) — shared with vendor.copy_skill (do not leave).
        # Skip (containment-stop/TOCTOU-race, already warn'is located inside) — not silent:
        # hits skip_copy, report prints FACT (installed_names), not a plan (V-2).
        if not safe_copy_skill(src, dst, dest_root):
            skip_copy.append(name)
            continue
        installed_names.append(name)
        if name in plan.get("managed_drift", []):
            if dir_sha256(dst) != entry["sha256"]:
                die(f"SPUB_OWNERSHIP_CONFLICT: provider {provider} channel vendor "
                    f"target {plan['skills_path']}/{name} repair bytes failed verification")
            if name in pending_backups:  # is missing from restoring a deleted skill
                pending_backups[name].replace(
                    (dst / "SKILL.md").with_name("SKILL.md.provider-artifact.bak"))
            repair_evidence.append({"name": name, **plan["drift_hashes"][name]})
        locked[name] = {
            "source": SOURCE,
            "managed": True,
            "bucket": entry["bucket"],
            "sha256": dir_sha256(dst),
            # content_sha256 — from the registry (SOURCE hash): copy differs in ignores,
            # so we hash the source, not dst (otherwise false drift every sync).
            "content_sha256": entry.get("content_sha256", ""),
            "installed_path": f"{plan['skills_path']}/{name}",
        }

    # keep: refresh metadata in case of manual editing lock (and uppopulation
    # content_sha256 in old locks - without copying unchanged skills)
    for name in plan["keep"]:
        entry = entries[name]
        locked.setdefault(name, {})
        locked[name].update({
            "source": SOURCE, "managed": True, "bucket": entry["bucket"],
            "sha256": entry["sha256"],
            "content_sha256": entry.get("content_sha256", ""),
            "installed_path": f"{plan['skills_path']}/{name}",
        })

    new_lock = dict(lock)
    new_lock["version"] = lock.get("version", LOCK_VERSION)
    if provider == "claude-code":
        new_lock["skills"] = dict(sorted(locked.items()))
    else:
        providers = dict(lock.get("providers", {}))
        providers[provider] = dict(sorted(locked.items()))
        new_lock["providers"] = dict(sorted(providers.items()))
    new_lock["sources"] = {**lock.get("sources", {}),
                           SOURCE: {"ref": "registry", "mode": "vendor"}}
    if not dry_run:
        # INTENTIONAL order: skills-lock.json — detection source of truth (plan_sync reads
        # load_lock, NOT a manifest), so we write it authoritatively AFTER the files are already on
        # disk (copytree above). Manifest - derivative (reinstallation contract/index for hub),
        # regenerates every successful sync. Crash after lock, before manifest → detection on trace.
        # sync is correct (by lock), manifest will achieve. (Do not rearrange: the manifesto was made first
        # would lock would become obsolete if it crashed and would break the detection.)
        write_lock(target, new_lock)
        for evidence in repair_evidence:
            name = evidence["name"]
            if (dir_sha256(dest_root / name) != entries[name]["sha256"]
                    or locked.get(name, {}).get("sha256") != entries[name]["sha256"]):
                die(f"SPUB_OWNERSHIP_CONFLICT: provider {provider} channel vendor "
                    f"target {plan['skills_path']}/{name} repair lock verification failed")
        write_manifest(target, plan["skills_path"], locked,
                        entries, cfg)
        # gitignore_managed: hold managed-skills outside git (reproducible sync),
        # local/custom - in the repo. List of auto-accompanied by each sync.
        if cfg.get("gitignore_managed"):
            write_gitignore(target, plan["skills_path"], locked)
        else:
            remove_our_gitignore(target, plan["skills_path"])
    # Fact (which is actually copied/missing) separate from the plan (plan["add"/"update"]) —
    # do_sync/cmd_sync report on installed/skip_copy, and not according to plan (V-2).
    plan["installed"] = installed_names
    plan["skip_copy"] = skip_copy
    plan["repair_evidence"] = repair_evidence
    return plan


def write_gitignore(target, skills_path, locked):
    """gitignore_managed: issuing `<skills_path>/.gitignore` with list ONLY
    managed-skills (reproducible `skiller sync`). Root `.gitignore` DO NOT touch
    (insulation + auto-tracking). Local/custom skills are not listed here
    → remain in the repository; manifesto/lock/himself .gitignore are also visible (not skill-dir)."""
    dest_root = Path(target) / skills_path
    if not dest_root.is_dir():
        return
    managed = sorted(n for n, e in locked.items() if e.get("managed"))
    lines = [
        GITIGNORE_HEADER,
        "# Managed swissknifeman-keep skills OUT git — they are reproducible:",
        "#   skiller sync   (from .swissknifeman/config.json + skills-lock.json)",
        "# Local/custom skills are NOT listed here → remain in the repository.",
        "",
    ] + [f"/{n}/" for n in managed]
    atomic_write_text(dest_root / ".gitignore", "\n".join(lines) + "\n")


def remove_our_gitignore(target, skills_path):
    """gitignore_managed disabled → remove previously generated by US `.gitignore`
    (identified by title), to managed-skills have been committed again. Stranger .gitignore
    do not touch."""
    gi = Path(target) / skills_path / ".gitignore"
    try:
        if gi.is_file() and gi.read_text(encoding="utf-8").startswith(GITIGNORE_HEADER):
            gi.unlink()
    except OSError:
        pass


def write_manifest(target, skills_path, locked, entries, cfg):
    """Manifest .swissknifeman-manifest.json in skills_path — contract for
    reinstallation (vendor) and source for generate-hub.sh (skill index).
    Layout sync always flat: <skills_path>/<name>/SKILL.md. Listing
    all managed-skills actually installed after the operation. Writer —
    common.write_skill_manifest, shared with vendor.py (V-4)."""
    dest_root = Path(target) / skills_path
    if not dest_root.is_dir():
        return
    installed = []
    for name in sorted(locked):
        entry = entries.get(name)
        if not entry:
            continue  # managed-entry without entry in the registry - not indexed
        installed.append({
            "flat_name": name,
            "source_path": str(Path(entry["path"]).parent),
        })
    write_skill_manifest(dest_root / MANIFEST, profile=cfg.get("project_type", ""),
                         agent=cfg.get("agent", "claude"), layout="flat",
                         installed=installed)


def sync_report_counts(plan, dry_run, force):
    """(add, update, repl, skip) for report sync. When dry-run plan nothing
    applied - the plan is the fact. Otherwise, we consider it according to FACT (plan['installed']), and not
    according to plan (plan['add']/['update']): safe_copy_skill might have missed a part install
    due containment-foot/TOCTOU-races - the report should not report the plan as
    job done (V-2)."""
    if dry_run:
        return (len(plan["add"]), len(plan["update"]),
                len(plan["conflicts"]) if force else 0, 0)
    installed = set(plan.get("installed", []))
    add = sum(1 for n in plan["add"] if n in installed)
    upd = sum(1 for n in plan["update"] if n in installed)
    repl = sum(1 for n in plan["conflicts"] if n in installed) if force else 0
    return add, upd, repl, len(plan.get("skip_copy", []))
