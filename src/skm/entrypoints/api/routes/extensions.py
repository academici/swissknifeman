"""HTTP routes for extensions."""

from skm.application_bus.registry import IdempotencyMode
from skm.entrypoints.api.routing import Route
from skm.modules.extensions.public import (
    GetPack,
    GetResourceVersion,
    InstallPack,
    InstallPackResult,
    ListPacks,
    ListResources,
    PacksView,
    PackView,
    QuarantineResource,
    QuarantineResourceResult,
    ReleaseQuarantine,
    ReleaseQuarantineResult,
    ResolutionView,
    ResolveResource,
    ResourcesView,
    ResourceVersionView,
    SyncBuiltinPacks,
    SyncBuiltinPacksResult,
    UninstallPackVersion,
    UninstallPackVersionResult,
)

__all__ = ["ROUTES"]


ROUTES: tuple[Route, ...] = (
    Route(
        "GET",
        "/api/v1/extensions/packs",
        PacksView,
        query=ListPacks,
        query_params={"state": "state", "after": "after", "limit": "limit"},
        body="none",
        tags=("extensions",),
    ),
    Route(
        "POST",
        "/api/v1/extensions/packs",
        InstallPackResult,
        command=InstallPack,
        success_status=201,
        body_limit_key="extensions.install.max_archive_bytes",
        idempotency=IdempotencyMode.OPTIONAL,
        tags=("extensions",),
    ),
    Route(
        "POST",
        "/api/v1/extensions/packs/sync-builtin",
        SyncBuiltinPacksResult,
        command=SyncBuiltinPacks,
        idempotency=IdempotencyMode.OPTIONAL,
        body="none",
        tags=("extensions",),
    ),
    Route(
        "GET",
        "/api/v1/extensions/packs/{pack_id}",
        PackView,
        query=GetPack,
        path_params={"pack_id": "pack"},
        body="none",
        tags=("extensions",),
    ),
    Route(
        "DELETE",
        "/api/v1/extensions/pack-versions/{pack_version_id}",
        UninstallPackVersionResult,
        command=UninstallPackVersion,
        path_params={"pack_version_id": "pack_version_id"},
        idempotency=IdempotencyMode.OPTIONAL,
        body="none",
        tags=("extensions",),
    ),
    Route(
        "GET",
        "/api/v1/extensions/resources",
        ResourcesView,
        query=ListResources,
        query_params={
            "kind": "kind",
            "scope": "scope",
            "include_quarantined": "include_quarantined",
            "after": "after",
            "limit": "limit",
        },
        body="none",
        tags=("extensions",),
    ),
    Route(
        "GET",
        "/api/v1/extensions/resolve",
        ResolutionView,
        query=ResolveResource,
        query_params={"kind": "kind", "key": "key", "scope": "scope"},
        body="none",
        tags=("extensions",),
    ),
    Route(
        "GET",
        "/api/v1/extensions/resource-versions/{resource_version_id}",
        ResourceVersionView,
        query=GetResourceVersion,
        path_params={"resource_version_id": "resource_version_id"},
        query_params={"include_bodies": "include_bodies"},
        body="none",
        tags=("extensions",),
    ),
    Route(
        "POST",
        "/api/v1/extensions/resource-versions/{resource_version_id}/quarantine",
        QuarantineResourceResult,
        command=QuarantineResource,
        path_params={"resource_version_id": "resource_version_id"},
        idempotency=IdempotencyMode.OPTIONAL,
        tags=("extensions",),
    ),
    Route(
        "POST",
        "/api/v1/extensions/resource-versions/{resource_version_id}/release",
        ReleaseQuarantineResult,
        command=ReleaseQuarantine,
        path_params={"resource_version_id": "resource_version_id"},
        idempotency=IdempotencyMode.OPTIONAL,
        tags=("extensions",),
    ),
)
